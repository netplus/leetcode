// ============================================================================
// LC-128：最长连续序列
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 7 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个未排序的整数数组 nums，找出数字连续的最长序列（不要求序列元素在原数组中连续）的长度。
// 请你设计并实现时间复杂度为 O(n) 的算法解决此问题。
//
// 题目示例：
// 示例 1：
//   Input: nums = [100,4,200,1,3,2]
//   Output: 4
//   Explanation: The longest consecutive elements sequence is [1, 2, 3, 4]. Therefore its length is 4.
//
// 示例 2：
//   Input: nums = [0,3,7,2,5,8,4,6,0,1]
//   Output: 9
//
// 示例 3：
//   Input: nums = [1,0,1,2]
//   Output: 3
//
// 约束与要求：
//   - 0 <= nums.length <= 10^5
//   - -10^9 <= nums[i] <= 10^9
//
// 复杂度目标：O(n) 时间，O(n) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜哈希集合 + 只从序列起点扩展
//
// 前置概念
//   这里的“连续序列”指的是数值连续，而不是数组位置连续：相邻数值必须相差 1，但它们在原数组中可以分散在任意位置。
//
//   例如 nums=[100,4,200,1,3,2] 中，1、2、3、4 在原数组里并不连续，却构成长度 4 的连续序列。
//
//   这与 subarray 不同：subarray 必须占据原数组中的连续下标。正因为本题不关心原下标，才可以把所有值丢进哈希集合后只研究数值邻接关系。
//
// 0. 优化是怎么来的
//   最直接且容易想到的做法是排序后扫描连续段，时间 O(n log n)。题目要求 O(n)，所以排序这一步必须被拿掉。
//
//   用哈希集合可以把“x+1 是否存在”降成平均 O(1) 查询，但如果从每个 x 都向后走一遍连续链，像 1,2,3,...,n 这样的输入仍会重复扫描同一条链，退化到 O(n^2)。
//
//   关键是只允许链头启动扫描：当 x-1 不存在时，x 才是某条连续段唯一的起点；链内部节点全部跳过。于是每条连续段只会被完整走一次。
//
//   优化类型：排序 -> 哈希查询；再消除重复链扫描 -> 只从唯一链头启动。
//
// 1. 图像直觉
//   把数组里的数放到数轴上，不关心它们原来的下标：
//
//   nums = [100,4,200,1,3,2]
//
//   数轴上实际形成三段：
//   1 -- 2 -- 3 -- 4        100        200
//   ^
//   真正值得启动搜索的只有每一段最左端。
//
//   如果从 2 开始向右数，会得到 2,3,4；从 3 又数 3,4；从 4 又数 4。
//   这样同一条链会被重复扫描。
//
//   怎样一眼认出链头？对 x 看 x-1：
//   x=1：0 不存在 -> 1 是链头，开始向右扩展 1,2,3,4
//   x=2：1 存在  -> 2 不是链头，跳过
//   x=3：2 存在  -> 跳过
//   x=4：3 存在  -> 跳过
//
//   于是每条连续链只完整扫描一次。
//   哈希集合负责 O(1) 地回答“邻居存在吗”，而 x-1 不存在这个条件负责消除重复起点。
//
// 2. 一句话核心
//   先用哈希集合抹掉原数组顺序，只从“没有前驱 x-1”的数启动一次向右扩展；这样每条连续链恰好扫描一次。
//
// 3. 公式 / 不变量
//   values = set(nums)
//
//   x 是连续段起点当且仅当：
//   x ∈ values 且 x-1 ∉ values
//
//   从起点 x 出发：
//   length = 1
//   while x+length ∈ values:
//       length++
//
//   关键不变量：
//   只有连续段的最小值负责遍历整段；段内其余元素因为存在前驱而永不启动第二次扩展。
//
//   若不同连续段长度为 L1,L2,...：
//   总扩展次数 = L1 + L2 + ... <= |values| <= n。
//
// 4. 执行步骤
//   1. 把 nums 全部放入 unordered_set，顺便消除重复值
//   2. 遍历集合中的每个 x；若 x-1 存在，说明 x 位于某条连续链内部，直接跳过
//   3. 只有 x-1 不存在时才把 x 当作链头，并从 x 开始反复查询 current+1
//   4. 记录这条连续链长度，并更新全局 best
//   5. 所有链头处理完后返回 best；空集合自然保持 0
//   记忆：有前驱就不是头；只从链头向右走，每条链只走一遍。
//
// 5. 为什么不会漏 / 不会重
//   任何非空连续段都有唯一最小值 s，而 s-1 不在集合中，所以 s 一定会启动扩展并沿 s+1,s+2... 访问完整段。段内任意 x>s 都有前驱 x-1，因此不会再次启动扫描。同一个集合元素至多作为某一条链扩展中的成员被访问一次，因此虽然代码外层 for 加内层 while 看起来像双层循环，总扩展工作量仍是 O(n)。
//
// 6. 边界与易错点
//   不要从每个元素都向右扩展，否则 [1,2,3,...,n] 会退化为 O(n^2)。set 的去重很重要，否则重复输入会产生无意义重复外层扫描。当前题面值域只有 ±1e9，本来不会触碰 int 边界；实现仍保留 INT_MIN/INT_MAX 防护，使代码对更宽输入也不会在 x-1/current+1 上产生有符号溢出。空数组答案为 0。
//
// 7. 举一反三
//   这与 Day 6 的区间扫描和本日 LC-239 有同一个优化思想：找到一个“支配/归属规则”，只保留真正有资格启动工作的候选。LC-239 删除被支配的最大值候选；LC-128 则让只有无前驱节点拥有一条链的扫描权。以后看到隐式链、连续编号段或哈希图连通块，可先问：能否定义唯一的 canonical start？
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：最长连续序列的长度。
// test.in 的预期输出：4
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int longestConsecutive(vector<int>& nums) {
        // 原数组下标与题目无关；集合只保留“哪些数值存在”，并顺便消除重复值。
        // 这样 predecessor/successor 是否存在都可用平均 O(1) 哈希查询回答。
        unordered_set<int> values(nums.begin(), nums.end());
        int best = 0;

        for (int x : values) {
            // 只有 x-1 不存在时，x 才是某条连续链唯一的最小值/链头。
            // 若 x-1 已存在，从 x 再向右扫描只会重复链头早晚会完成的同一段工作，必须跳过。
            // INT_MIN 防护避免在更宽输入下计算 x-1 时发生有符号溢出。
            if (x != INT_MIN && values.count(x - 1)) continue;

            // 只有 canonical start 才拥有向右遍历整条链的资格。
            int length = 1;
            int current = x;
            while (current != INT_MAX && values.count(current + 1)) {
                ++current;
                ++length;
            }

            // 一条链只在它唯一的链头处完整计算一次。
            best = max(best, length);
        }

        // 虽然代码有 for + while，两层并不会形成 O(n^2)：
        // 链内部节点因存在前驱不会启动扫描，每个集合元素只归属于唯一链头的一次扩展。
        return best;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.longestConsecutive(a) << "\n";
    return 0;
}
