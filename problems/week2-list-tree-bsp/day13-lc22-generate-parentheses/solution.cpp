// ============================================================================
// LC-22：括号生成
// 难度：中等
// 优先级：P1（进阶）
// 学习进度：第 2 周 / 第 13 天
// ----------------------------------------------------------------------------
// 题目描述：
// 数字 n 代表生成括号的对数，请你设计一个函数，用于能够生成所有可能的并且有效的括号组合。
//
// 约束与要求：
//   - 1 <= n <= 8
//
// 复杂度目标：O(4^n / sqrt(n))。
//
// ----------------------------------------------------------------------------
// 解法精讲｜约束生成：把合法前缀写进搜索树，只生成仍可能成功的节点
//
// 0. 优化是怎么来的
//   最直接的方法是枚举长度 2n 的所有括号字符串：每一位选 '(' 或 ')'，总共有 2^(2n)=4^n 个候选；
//   等完整字符串生成后，再复用 LC-20 的栈规则逐个验证。这是正确算法。
//
//   浪费在于：很多字符串在很短的前缀阶段就已经永远不可能合法。例如 `())...` 扫到第三个字符时
//   close=2、open=1，历史上已经出现“右括号没有可匹配左括号”，未来追加任何字符都救不回来。
//
//   所以把 LC-20 的完整串验收条件前移成“搜索前缀不变量”：
//   - open < n 才允许放 '('；
//   - close < open 才允许放 ')'。
//
//   这样不是先生成坏答案再过滤，而是在“不可能恢复”的那一刻直接不生成整棵坏子树。
//
// 1. 图像直觉
//   n=3 时，搜索树不是完整二叉树；非法孩子根本不存在：
//
//                        ""  (0,0)
//                         |
//                        "(" (1,0)
//                     /          \
//                 "(("(2,0)    "()"(1,1)
//                 /   \             |
//             "((("  "(()"          "()("
//              |        ...            ...
//
//   根节点没有 ')' 分支，因为 close<open 不成立：手里没有任何未闭合左括号可供关闭。
//   对任意被搜索的前缀始终保持 0 <= close <= open <= n。
//   可以把 open-close 看成当前“尚未闭合”的左括号数，它绝不能为负。
//
// 2. 一句话核心
//   把 LC-20 的括号合法性从“完整字符串验收”前移成搜索前缀约束，只给仍可能完成的前缀生成孩子。
//
// 3. 公式 / 不变量
//   open  = path 中已使用 '(' 数
//   close = path 中已使用 ')' 数
//
//   搜索前缀始终满足：0 <= close <= open <= n
//   添加 '('：open < n
//   添加 ')'：close < open
//
//   当 path.size()==2n：
//   open+close=2n，且 close<=open<=n
//   => open=close=n
//   => 当前 path 自动是完整合法括号串。
//
// 4. 执行步骤
//   1. 从空 path、open=0、close=0 开始，当前状态天然满足合法前缀不变量
//   2. 若 open<n，push '(' 并递归 open+1；返回后 pop，恢复父前缀
//   3. 若 close<open，push ')' 并递归 close+1；这个条件保证右括号永远不会超过已出现的左括号
//   4. path 长度达到 2n 时直接记录答案；无需再做一次 LC-20 完整校验
//   记忆：不要先造坏答案再过滤；能开才开，手里有未闭合左括号才关。
//
// 5. 为什么不会漏 / 不会重
//   不会生成非法答案：每个前缀都满足 close<=open，从未出现无法匹配的右括号；最终长度 2n 又迫使左右各 n 个。
//   不会漏：任意合法括号串的每个前缀都必满足 close<=open，且总左括号不超过 n，所以沿它真实字符逐步选择时，
//   对应分支始终不会被剪掉。不会重：一个具体字符串的字符序列唯一，对应搜索树中唯一一条根到叶路径。
//
// 6. 边界与易错点
//   右括号条件必须是 `close < open`，不是 `close < n`；后者会生成 `)(` 一类已经无法修复的非法前缀。
//   push 后递归、递归后 pop 必须成对，否则兄弟分支会继承错误 path。终点无需再调用 LC-20，因为合法性已经作为
//   不变量贯穿生成过程。题目 n>=1；若扩展到 n=0，这套逻辑也会自然得到空字符串这一种组合。
//
// 7. 举一反三
//   这是 LC-20 的反向使用：LC-20 给定完整字符串后判断前缀何时非法；LC-22 在生成阶段只允许不会让前缀非法的动作。
//   构造 IP、表达式、棋盘或受限序列时也应先问：哪些前缀一旦违规，未来无论怎么补都救不回来？把条件前移就是剪枝。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   输出：所有组合，每行一个。
// test.in 的预期输出：((())) | (()()) | (())() | ()(()) | ()()()
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
    vector<string> answer;
    string path;

    void search(int n, int open, int close) {
        if (static_cast<int>(path.size()) == 2 * n) {
            answer.push_back(path);
            return;
        }
        if (open < n) {
            path.push_back('(');
            search(n, open + 1, close);
            path.pop_back();
        }
        if (close < open) {
            path.push_back(')');
            search(n, open, close + 1);
            path.pop_back();
        }
    }

public:
    vector<string> generateParenthesis(int n) {
        answer.clear();
        path.clear();
        search(n, 0, 0);
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    auto res = sol.generateParenthesis(n);
    for (auto& s : res) cout << s << "\n";
    return 0;
}
