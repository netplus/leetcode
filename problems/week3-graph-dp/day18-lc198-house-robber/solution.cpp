// 题目描述：
// 你是一个专业的小偷，计划偷窃沿街的房屋。
// 每间房内都藏有一定的现金，影响你偷窃的唯一制约因素就是相邻的房屋装有相互连通的防盗系统，如果两间相邻的房屋在同一晚上被小偷闯入，系统会自动报警。
// 给定一个代表每个房屋存放金额的非负整数数组，计算你不触动警报装置的情况下，一夜之内能够偷窃到的最高金额。
//
// 约束与要求：
//   - 1 <= nums.length <= 100
//   - 0 <= nums[i] <= 400
//
// 复杂度目标：O(n) 时间，O(1) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜选择 DP：把所有方案按“当前房偷不偷”分成两类，只保留前两个前缀最优
//
// 0. 优化是怎么来的
//   最自然的正确算法是 DFS 枚举每间房“偷 / 不偷”。若偷当前房，就跳过下一间；若不偷，就继续看下一间。所有合法选择集合都会被枚举，因此正确，但最坏会产生指数级搜索树。
//
//   重复在哪里？从不同选择路径走到同一个位置时，后面面对的是完全相同的一段房屋。例如前面如何到达“现在开始考虑第 i 间”并不重要；在只关心最大金额时，历史细节可以压缩成一个最优值。
//
//   换成前缀视角更直观：设 dp[i] 是处理完前 i 间房的最大金额。加入当前房 money 后，完整方案按是否选择它分成：
//   - 不偷当前：仍是 dp[i-1]；
//   - 偷当前：前一间不能偷，所以是 dp[i-2] + money。
//
//   同一前缀下，金额较小的方案面对完全相同的未来，再也不可能反超金额较大的方案，因此只需保留 max。这就是候选支配带来的状态压缩。
//
//   又因为下一步只读取 dp[i-1]/dp[i-2]，最终只保留 previous1/previous2，得到 O(n) 时间、O(1) 额外空间。
//
// 1. 图像直觉
//   nums = [2,7,9,3,1]
//
//   走到金额 9 这间房时，面前只有两个互斥选择：
//
//   不偷 9：
//   [2,7] 的最优 = 7
//                    \
//                     max -> 当前前缀最优
//                    /
//   偷 9：
//   必须跳过相邻的 7，
//   接 [2] 的最优 2 + 9 = 11
//
//   所以当前变成 11。
//
//   注意我们没有保存“11 是偷了哪些房得到的”。
//   对于后续房屋，真正有用的只有：
//   前一前缀最大值 previous1
//   前两前缀最大值 previous2
//
//   更差的同前缀方案面对相同未来永远不可能反超，可以永久丢弃。
//
// 2. 一句话核心
//   对当前房只比较两类完整方案：不偷它就继承前一前缀最优；偷它就接前两前缀最优加当前金额，取较大者。
//
// 3. 公式 / 不变量
//   把处理到当前房之前的两个前缀最优记为：
//   previous1 = 前 i-1 间房可取得的最大金额
//   previous2 = 前 i-2 间房可取得的最大金额
//
//   当前房金额 money：
//   skip = previous1
//   take = previous2 + money
//   current = max(skip, take)
//
//   滚动后：
//   previous2 = old previous1
//   previous1 = current
//
//   初始空前缀：
//   previous2 = previous1 = 0。
//
// 4. 执行步骤
//   1. 从空前缀开始令 previous2=0、previous1=0；0 表示当前没有任何房时最大收益为 0
//   2. 从左到右读取当前 money，先算 skip=previous1 与 take=previous2+money
//   3. 令 current=max(skip,take)；这一步已经把所有合法方案压缩成当前前缀唯一需要保留的最优值
//   4. 必须在 current 算完后再执行 previous2=previous1、previous1=current，避免覆盖 take 仍需的旧 dp[i-2]
//   5. 处理完所有房后 previous1 就是整个线性街道的最优收益
//   记忆：当前房：不偷就继承前一最优；偷就接前两最优。面对同一未来，只留金额最大的前缀。
//
// 5. 为什么不会漏 / 不会重
//   任意针对当前前缀的合法方案，要么不含最后一间房，要么包含它，两类互斥且覆盖全部方案。不含最后房的最优值就是 previous1；包含最后房时相邻前一房必不能选，所以此前最多取 previous2，再加当前 money。两类各自都取到了最优，再取 max 就得到完整前缀最优。由于以后只关心这个前缀能提供的最大金额，更差方案面对相同未来不会重新变优，因此可以安全丢弃。
//
// 6. 边界与易错点
//   不要把 previous1 理解成“上一间房偷到的钱”，它表示整个前一前缀的最优总额。take 必须使用 previous2，而不是 previous1+money，否则会同时偷相邻房。滚动更新顺序不能提前覆盖 previous1。题目金额非负，但初始化为 0 也自然允许空前缀。
//
// 7. 举一反三
//   LC-198 把 LC-70 的“最后来源分类”升级成一般的“决策分类”：先枚举当前决策的互斥类别，再只保留每类未来真正需要的摘要状态。LC-213 完全复用这个线性 DP，不重新发明 recurrence；它只负责先消除首尾相邻造成的环。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：可获得的最大金额。
// test.in 的预期输出：4
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int rob(vector<int>& nums) {
        int previous2 = 0, previous1 = 0;
        for (int money : nums) {
            int current = max(previous1, previous2 + money);
            previous2 = previous1;
            previous1 = current;
        }
        return previous1;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.rob(a) << "\n";
    return 0;
}

