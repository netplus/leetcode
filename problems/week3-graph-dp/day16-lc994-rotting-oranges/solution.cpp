// ============================================================================
// LC-994：腐烂的橘子
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 3 周 / 第 16 天
// ----------------------------------------------------------------------------
// 题目描述：
// 在给定的 m x n 网格 grid 中，每个单元格可以有以下三个值之一：值 0 代表空单元格；值 1 代表新鲜橘子；值 2 代表腐烂的橘子。
// 每分钟，腐烂的橘子周围 4 个方向上相邻的新鲜橘子都会腐烂。
// 返回直到单元格中没有新鲜橘子为止所必须经过的最小分钟数。
// 如果不可能，返回 -1。
//
// 约束与要求：
//   - m == grid.length
//   - n == grid[i].length
//   - 1 <= m, n <= 10
//   - grid[i][j] 仅为 0、1 或 2
//
// 复杂度目标：O(m*n) 时间（多源 BFS）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜多源 BFS 时间传播：同一层代表同一分钟，状态改变时立即入下一层
//
// 0. 优化是怎么来的
//   最贴近题意的直接模拟，是每一分钟都重新扫描整张网格：找到当前腐烂橘子附近的新鲜橘子，先记录本分钟将腐烂的位置，扫描结束后统一更新，再进入下一分钟。它正确，但每分钟都要 O(mn) 全表扫描；传播最长又可能持续 O(mn) 分钟，因此最坏 O((mn)^2)。
//
//   浪费在于：绝大多数格子每一分钟都被重新检查，即使它与当前传播边界毫无关系。真正能在下一分钟制造新变化的，只有“这一分钟刚刚处于腐烂前沿”的那些橘子。
//
//   队列正好保存这个活动前沿。把所有初始腐烂橘子同时作为第 0 层；固定当前 layer 大小时，这一层产生的新腐烂橘子只入队，不在本层继续传播，下一轮再处理，于是队列层边界天然实现了“同步一分钟”。
//
//   优化类型：每分钟全网格重复扫描 -> 只维护会产生新事件的传播前沿；多源 BFS 把总时间降为 O(mn)。
//
// 1. 图像直觉
//   初始：
//   2 1 1
//   1 1 0
//   0 1 1
//
//   时间0 frontier：所有初始 2
//   [左上角]
//
//   第1分钟：只处理时间0 frontier
//   2 2 1
//   2 1 0
//   0 1 1
//   新腐烂节点进入 next frontier
//
//   第2分钟再处理上一分钟新加入的节点。
//
//   关键层边界：
//   layer = rotten.size()
//   只处理这 layer 个旧节点。
//   处理过程中 push 的新节点属于“下一分钟”，不能马上在同一分钟继续感染。
//
//   fresh 则是一个剩余工作计数器：
//   每感染一个 1：--fresh
//   fresh==0 时说明所有新鲜橘子都已被某一层波前覆盖。
//
// 2. 一句话核心
//   队列只保存当前传播前沿；冻结 layer 后处理这一分钟已有的腐烂橘子，新腐烂节点只进入下一层，因此 BFS 层数与真实分钟一一对应。
//
// 3. 公式 / 不变量
//   初始：
//   所有 grid==2 的格子入队，时间为 0
//   fresh = grid==1 的格子总数
//
//   每轮：
//   layer = queue.size()
//   minutes++
//   只弹出 layer 个节点
//
//   若邻格为新鲜橘子：
//   grid[nr][nc] = 2
//   fresh--
//   push(neighbor)
//
//   不变量：
//   一轮开始时，队列前 layer 个节点恰好是在 minutes-1 时刻已经腐烂、能在本分钟向外传播的 frontier。
//
//   结束：
//   fresh == 0 => minutes
//   否则队列耗尽但 fresh>0 => 存在不可达新鲜橘子，返回 -1。
//
// 4. 执行步骤
//   1. 先完整扫描一次网格：所有初始 2 入队，同时统计 fresh；这一步建立时间 0 的全部多源前沿
//   2. 若 fresh 一开始就是 0，while 条件不会进入，最终自然返回 0
//   3. 每分钟开始冻结 layer=rotten.size()，再 minutes++；只处理这 layer 个节点，隔离本分钟与下一分钟
//   4. 枚举四邻，只对值仍为 1 的格子执行 1->2、fresh--、入队；改成 2 就是入队即 visited，防止多个腐烂邻居重复感染同一格
//   5. 队列为空或 fresh 清零时结束；fresh==0 返回 minutes，否则返回 -1
//   记忆：每分钟只处理当前 frontier；所有源时间 0 同时入队，新节点留到下一层。
//
// 5. 为什么不会漏 / 不会重
//   所有初始腐烂点在时间 0 同时作为 BFS 源。由无权多源 BFS 性质，一个新鲜格第一次被传播前沿到达的层数就是它到最近初始腐烂点的最短四邻距离，也正是它最早可能腐烂的分钟。冻结 layer 保证新加入节点必须等到下一轮才能继续传播，与题目的同步分钟过程一致。若最终仍有 fresh，则这些格子不在任何初始腐烂源的可达区域中，因此不可能腐烂。
//
// 6. 边界与易错点
//   不能在处理当前节点时让刚入队的节点立刻继续传播，否则会把多分钟压成一分钟；所以必须冻结 layer。感染时立即把 1 改成 2，避免同一新鲜橘子被多个邻居重复入队和重复 fresh--。没有新鲜橘子应返回 0。这里没有使用任何 C++20/C++23 API。
//
// 7. 举一反三
//   它和 LC-542 是同一个多源 BFS：前者把层数解释为最早感染时间，后者解释为最近目标距离。再往外推广，火灾、病毒、信号扩散、多个入口的最短到达时间都只是在改变“源是什么、哪些格子可传播、层数代表什么”。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：m n。
//   接下来 m 行：n 个以空格分隔的整数。
//   输出：所需的最少分钟数；无法完成时输出 -1。
// test.in 的预期输出：4
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int orangesRotting(vector<vector<int>>& grid) {
        const int rows = static_cast<int>(grid.size());
        const int cols = static_cast<int>(grid[0].size());

        // rotten 是“当前传播前沿”队列；初始化时所有原始腐烂橘子都作为时间 0 的多源起点。
        queue<pair<int, int>> rotten;

        // fresh 是尚未被任何传播波前覆盖的新鲜橘子数量，也是判断最终是否还有不可达节点的剩余工作计数器。
        int fresh = 0;
        for (int r = 0; r < rows; ++r) {
            for (int c = 0; c < cols; ++c) {
                if (grid[r][c] == 2) rotten.push({r, c});
                else if (grid[r][c] == 1) ++fresh;
            }
        }

        const int directions[4][2] = {{1, 0}, {-1, 0}, {0, 1}, {0, -1}};
        int minutes = 0;

        // 没有 fresh 时无需进入循环，minutes 自然保持 0；
        // rotten 为空但 fresh>0 时也无法继续传播，最终会返回 -1。
        while (!rotten.empty() && fresh > 0) {
            // 冻结这一分钟开始时的 frontier 大小。处理过程中新入队的橘子属于“下一分钟”，
            // 不能在本轮继续传播，否则会把多分钟链式感染错误压缩到同一分钟。
            int layer = static_cast<int>(rotten.size());
            ++minutes;

            while (layer--) {
                auto [r, c] = rotten.front();
                rotten.pop();

                for (auto& d : directions) {
                    int nr = r + d[0], nc = c + d[1];
                    if (nr >= 0 && nr < rows && nc >= 0 && nc < cols && grid[nr][nc] == 1) {
                        // 感染时立即执行 1->2，相当于“入队即 visited”；
                        // 这样同一新鲜橘子即使同时邻接多个腐烂橘子，也只会入队一次、fresh-- 一次。
                        grid[nr][nc] = 2;
                        --fresh;
                        rotten.push({nr, nc});
                    }
                }
            }
        }

        // fresh==0 表示所有新鲜橘子都已在某一 BFS 层被覆盖；
        // 若队列耗尽后 fresh 仍大于 0，则这些橘子与所有初始腐烂源都不可达。
        return fresh == 0 ? minutes : -1;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int m, n; if (!(cin >> m >> n)) return 0;
    vector<vector<int>> g(m, vector<int>(n));
    for (int i = 0; i < m; ++i) for (int j = 0; j < n; ++j) cin >> g[i][j];
    cout << sol.orangesRotting(g) << "\n";
    return 0;
}
