// ============================================================================
// LC-739：每日温度
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 2 周 / 第 12 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个整数数组 temperatures，表示每天的温度，返回一个数组 answer，其中 answer[i] 是指对于第 i 天，下一个更高温度出现在几天后。
// 如果气温在这之后都不会升高，请在该位置用 0 来代替。
//
// 约束与要求：
//   - 1 <= temperatures.length <= 10^5
//   - 30 <= temperatures[i] <= 100
//
// 复杂度目标：O(n) 时间（单调栈）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜单调递减栈：新元素批量结算仍在等待的旧元素
//
// 0. 优化是怎么来的
//   最直接的做法，是对每一天 i 向右逐日寻找第一个更高温度；最坏每个位置都要扫描很远，总时间 O(n^2)。
//
//   换成从左到右看，真正需要保存的只有“还没有找到答案的历史日期”。当前温度到来时，如果它比某些历史日期更高，那么这些日期的答案就在这一刻第一次被确定，可以立即结算并永久删除。
//
//   为了快速知道哪些未决日期能被当前温度结算，让栈中温度保持单调不增；当前温度只需从栈顶连续处理更冷的日期。
//
//   优化类型：每个位置向未来重复搜索 -> 保存未决状态，由未来事件一次结算。每个下标只入栈/出栈一次，O(n)。
//
// 1. 图像直觉
//   把每个还没等到更暖天气的日期看成一张“待结算订单”：
//
//   temperatures = [73, 74, 75, 71, 69, 72, 76]
//
//   扫描到 72 前，栈中可能是：
//   下标       2    3    4
//   温度      75   71   69
//              |    |    |
//             等待  等待  等待
//
//   72 到来：
//   69 < 72 -> 69 的订单完成，弹出
//   71 < 72 -> 71 的订单完成，弹出
//   75 > 72 -> 75 还不能完成，停止
//
//   栈从底到顶温度保持单调不增。
//
// 2. 一句话核心
//   栈只保留还没遇到更暖日子的下标；当前温度一旦更高，就连续结算栈顶那些终于等到答案的日期。
//
// 3. 公式 / 不变量
//   栈中下标从底到顶递增，对应温度单调不增：
//   T[s0] >= T[s1] >= ... >= T[stop]
//
//   若当前 day 满足：
//   T[day] > T[stack.top()]
//   则：
//   answer[stack.top()] = day - stack.top()
//   并弹栈继续检查。
//
//   相等不能弹，因为题目要求 strictly warmer。
//
// 4. 执行步骤
//   1. 从左到右扫描 day；在处理当前日之前，栈中只包含尚未找到更暖日期的历史下标
//   2. 当 temperatures[day] 严格大于栈顶温度时，当前 day 就是该栈顶日期的答案：记录距离并弹出；重复直到栈空或栈顶不再更冷
//   3. 把当前 day 压栈，让它成为新的待结算日期；扫描结束仍留在栈中的日期答案保持初始化的 0
//   记忆：当前值不是来“维护排序”的，它是在帮助历史元素第一次确定答案；单调性只是把仍有资格等待的元素压缩在栈里。
//
// 5. 为什么不会漏 / 不会重
//   为什么当前 day 是被弹日期的第一个更暖日？因为我们按时间从左到右扫描；若此前已有更暖日，该下标早就会在那个时刻被弹，不可能一直留到现在。
//   为什么可以连续弹？栈顶是目前最晚、也最冷的一批未决日期；只要当前温度能超过它们，就能一次性结算。
//   每个下标只入栈一次、出栈至多一次，所以 while 虽然嵌套在 for 中，总操作量仍是 O(n)。
//
// 6. 边界与易错点
//   必须存下标而非只存温度，因为答案是天数差；比较条件必须是 `>` 而不是 `>=`；不要看到双层循环就误判 O(n^2)，摊还分析的关键是每个下标最多弹一次。
//
// 7. 举一反三
//   这是 Day 7 LC-239“淘汰失去资格候选”的近亲：LC-239 用 deque 维护一个移动窗口里的最优候选；LC-739 用 stack 维护等待未来触发条件的未决候选。下一题 LC-84 会把“未来触发时结算”升级成同时确定左右边界。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：n 个以空格分隔的等待天数。
// test.in 的预期输出：1 1 4 2 1 1 0 0
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> dailyTemperatures(vector<int>& temperatures) {
        vector<int> answer(temperatures.size(), 0);
        stack<int> pending;
        for (int day = 0; day < static_cast<int>(temperatures.size()); ++day) {
            while (!pending.empty() && temperatures[day] > temperatures[pending.top()]) {
                const int previous = pending.top();
                pending.pop();
                answer[previous] = day - previous;
            }
            pending.push(day);
        }
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto ans = sol.dailyTemperatures(a);
    for (size_t i = 0; i < ans.size(); ++i) cout << ans[i] << " \n"[i + 1 == ans.size()];
    return 0;
}
