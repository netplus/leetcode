// ============================================================================
// LC-300：最长递增子序列
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 3 周 / 第 19 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 nums，找到其中最长严格递增子序列的长度。
// 子序列是由数组派生而来的序列，删除（或不删除）数组中的元素而不改变其余元素的顺序。
// 例如，[3,6,2,7] 是数组 [0,3,1,6,2,2,7] 的子序列。
//
// 题目示例：
// 示例 1：
//   Input: nums = [10,9,2,5,3,7,101,18]
//   Output: 4
//   Explanation: The longest increasing subsequence is [2,3,7,101], therefore the length is 4.
//
// 示例 2：
//   Input: nums = [0,1,0,3,2,3]
//   Output: 4
//
// 示例 3：
//   Input: nums = [7,7,7,7,7,7,7]
//   Output: 1
//
// 约束与要求：
//   - 1 <= nums.length <= 2500
//   - -10^4 <= nums[i] <= 10^4
//
// 复杂度目标：O(n log n) 时间，O(n) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜从题目直觉到可复用算法
//
// 1. 题目直觉 / 图形模型
//   题目允许跳过元素，但保留的元素必须维持原下标顺序，数值还要严格变大。
//
//   原数组：3  5  6  2  4
//   一种选择：3 -> 5 -> 6，长度 3
//   另一选择：2 -> 4，长度 2
//
//   [2,4,6] 数值虽然递增，却不是这份输入的子序列，因为 6 出现在 2 和 4 前面。
//   题目求的是最大长度，不要求立即选定或输出一条最终路径。
//
//   假设下一个数是 x，要判断它能接到哪些已有选择后面，至少要知道那些选择
//   的最后一个数，以及接上之后能得到多长。只记“目前最长是几”显然不够。
//
// 2. 最自然的一般性解法
//   最直接的办法是枚举每个位置选或不选，检查保留序列是否严格递增。
//   它能覆盖全部子序列，但有 2^n 种选择，直接逐条检查需 O(n*2^n) 时间。
//
//   先做一个容易理解、可以独立作为完整解法的改进：按“最后选了哪个位置”分组。
//   对固定的 i，所有以 nums[i] 结尾的递增子序列有相同的最后一个值；
//   未来能接上的元素相同，因此只保留这组里最长的长度即可。
//   把它记为 dp[i]，这时才得到“以 i 结尾”的状态，而不是先背定义。
//
//   初值 dp[i]=1，因为 nums[i] 自己就是长度 1 的合法子序列。
//   要以 i 结尾，倒数第二个位置只能是某个 j<i 且 nums[j]<nums[i]：
//
//   对 i 从左到右：
//       dp[i] = 1
//       对 j 从 0 到 i-1：
//           如果 nums[j] < nums[i]：
//               dp[i] = max(dp[i], dp[j]+1)
//   答案 = max(dp)
//
//   为什么完整？长度至少为 2 的任意答案去掉最后一个元素，就一定落到这些 j
//   中的某一个；反过来每次合法接续都得到一条真实子序列。没有可接前驱时保留 1。
//   对 [3,5,6,2,4]，dp 依次为 [1,2,3,1,2]，答案是 3，而不是最后的 dp 值 2。
//   这就是结尾动态规划：时间 O(n^2)，状态空间 O(n)，实现并不需要二分查找。
//
// 3. 一般解法的问题与限制
//   结尾 DP 已经合并了“同一位置结尾”的候选，但每个新元素仍会重新扫描
//   所有历史位置；其中有些不同结尾，面对未来其实一直处于劣势。
//
//   在同一个已扫描前缀里，比较长度相同的两个候选：
//   A=[3,5]，结尾 5；B=[2,4]，结尾 4。
//   未来 x 若能接在 5 后，就也能接在 4 后；有些数还能接在 4 后却不能接在 5 后。
//   所以只求长度时，没有必要同时保存两者的结尾。
//
//   不能只保留全局最小值，因为不同长度不能这样比较；也不能只保留最长长度。
//   例如前缀 [1,100] 与 [1,2] 都有最长长度 2，但同样追加 3 后答案分别为 2 和 3。
//   这说明“只记长度”丢失了判断未来接续所必需的信息。
//
// 4. 从具体问题抽象规律
//   第二次压缩：同一个已扫描前缀、同样长度，只保留最小结尾。
//   现在定义 tails[L-1] 为长度 L 的真实递增子序列所能取得的最小结尾。
//   较大结尾能接的任何未来递增后缀，较小结尾也能接；较大者因此可以永久淘汰。
//   注意这保留的是最优长度所需的信息，不保留全部路径或方案数量。
//
//   为什么这些最小结尾有序？取一条长度 L+1、结尾最小的真实序列，其结尾为 y。
//   删掉 y 后得到长度 L 的序列，结尾 z<y；该长度的最小结尾又满足 tails[L-1]<=z，
//   所以 tails[L-1]<y=tails[L]。严格有序是推出来的，不是容器名称带来的性质。
//
//   处理新数 x，先线性找第一个 >=x 的位置 p（下标从 0 开始）：
//   - p 之前的结尾都 <x，所以存在长度 p、能够接上 x 的真实序列；p=0 时从 x 自身开始。
//   - 因而可以形成长度 p+1、结尾 x 的序列，替换这一档不会凭空制造答案。
//   - 不能形成更长的新序列：否则去掉 x 后，应有长度至少 p+1、结尾 <x 的旧序列，
//     与第 p 档最小结尾已经 >=x 矛盾。
//   - 若没有这样的 p，x 能接在当前最长序列后，新增一档。
//
//   线性寻找位置仍是 O(n^2)；到这里才利用刚证明的有序性，用二分把查找降为
//   O(log n)，整体 O(n log n)。候选淘汰与二分加速是两个不同的推理步骤。
//
// 5. 专项算法｜LIS：从 O(n²) 结尾 DP 到候选支配压缩，再用二分维护最优结尾
//   到这里才需要给这套规律命名：本题对应“LIS：从 O(n²) 结尾 DP 到候选支配压缩，再用二分维护最优结尾”。通用机制见 docs/algorithms/binary-search.md；回到本题时只保留与当前题意直接相关的状态、边界和更新顺序。
//
// 6. 核心算法
//   维护每个长度的最小结尾，用 lower_bound 找第一个 >=x 的槽位：
//   找到就替换；没找到就追加。相等值只能替换，不能延长严格递增序列。
//
//   输入：3,5,6,2,4
//   读入 3：tails=[3]
//   读入 5：tails=[3,5]
//   读入 6：tails=[3,5,6]
//   读入 2：tails=[2,5,6]
//   读入 4：tails=[2,4,6]
//
//   最后长度为 3，但 [2,4,6] 不是原数组子序列：6 在原数组中出现得更早。
//   这不矛盾。三个槽位分别有真实序列作为依据，例如 [2]、[2,4]、[3,5,6]，
//   却不要求所有槽位来自同一条历史路径。替换一个槽位不会抹去其它长度已经存在的事实。
//
// 7. 公式 / 不变量
//   自然 DP：
//   dp[i] = 1 + max(dp[j])，其中 j<i 且 nums[j] < nums[i]。
//
//   压缩后的状态：
//   tails[L-1] = 当前扫描前缀中，长度为 L 的严格递增子序列的最小可能结尾。
//
//   不变量：
//   tails[0] < tails[1] < ... < tails[k-1]
//   且 tails.size() = 当前前缀的 LIS 长度。
//
//   处理 x：
//   pos = lower_bound(tails.begin(), tails.end(), x)
//
//   若 pos == end：
//       x 大于所有最优结尾，追加 x，LIS 长度 +1
//   否则：
//       *pos = x，当前长度不变，但对应长度的最优结尾不变差且通常变小。
//
//   严格递增使用第一个 >=x；若用 upper_bound，会错误允许相等值扩展长度。
//
// 8. 执行步骤
//   1. 从空 tails 开始，逐个处理 nums 中的 value；tails 不保存所有候选，只保存每种长度的最小结尾
//   2. 对 value 使用 lower_bound，寻找第一个 >= value 的最优结尾位置；有序性使这个查找为 O(log n)
//   3. 若找不到该位置，说明 value 大于所有现有结尾，可以接到当前最长序列之后，因此 push_back(value)
//   4. 若找到位置，只替换该结尾为 value；这不会制造更长长度，只是在相同长度下保留更有利的未来状态
//   5. 扫描结束后返回 tails.size()；不要把 tails 内容本身当成一定可还原的 LIS
//   记忆：先学 O(n²) 的“以 i 结尾”；再问同长度谁更值得留——结尾越小越强；最小结尾有序，所以二分。
//
// 9. 为什么不会漏 / 不会重
//   对固定长度 L，只保留最小结尾不会丢掉任何未来最优解：若未来 x 能接在某个更大的同长度结尾后，那么 x 也一定能接在更小结尾后；反过来更小结尾还可能接受更多未来值，所以大结尾被永久支配。替换第一个 >=x 的位置时，前一档结尾（若存在）严格小于 x，因此确实存在一个长度为 pos+1、以 x 结尾的递增子序列；而不替换更靠后的长度，保证没有凭空增长长度。只有 x 大于所有 tails 时，才有证据把最长长度增加一。
//
// 10. 边界与易错点
//   严格递增必须用 lower_bound（第一个 >=x），重复元素不能扩展长度。tails[k] 表示最小结尾，不表示第 k 个 LIS 元素，也不保证整个 tails 就是一条原数组中的 LIS；若要还原具体序列，需要额外记录前驱与位置。不要跳过 O(n²) DP 的含义，否则很难理解 tails 到底压掉了什么状态。
//
// 11. 举一反三
//   先独立回答，再用例子核对是哪条推理发生了变化：
//
//   1. 只把“严格递增”改成“不下降”，为什么应找第一个 >x，而不是 >=x？
//      因为相等值现在可以接续。[2,2] 在原题答案为 1，在不下降变式中为 2。
//   2. 要输出一条真实的最长子序列，能直接返回 tails 吗？
//      不能；[3,5,6,2,4] 已给出反例，需要额外保存位置与前驱等路径信息。
//   3. 要计算最长递增子序列的数量，还能每种长度只留一个最小结尾吗？
//      不能直接照搬：候选支配保留了“最优长度”，却可能丢掉不同方案的数量贡献。
//   4. 复盘两个不同的压缩依据：
//      结尾 DP 是“同一位置结尾，保留最长”；tails 是“同一长度，保留最小结尾”。
//      说清楚比较前提，才能判断类似状态压缩是否有效，而不是只记一个数组名。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：最长递增子序列长度。
// test.in 的预期输出：4
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int lengthOfLIS(vector<int>& nums) {
        // tails[len-1] 表示：当前已扫描前缀中，长度恰为 len 的严格递增子序列
        // 所能取得的最小结尾值。它是“各长度的最优摘要”，不保证整个 tails 本身对应同一条真实 LIS。
        vector<int> tails;

        for (int value : nums) {
            // tails 严格递增，因此可以二分定位第一个 >= value 的位置。
            // 严格递增必须用 lower_bound：相等值只能改善同一长度的结尾，不能把长度延长。
            auto position = lower_bound(tails.begin(), tails.end(), value);

            // 若 value 大于所有已有最小结尾，它可以接在当前最长序列之后，LIS 长度真正 +1；
            // 否则只把同一长度的结尾改善成更小/相同的 value，为未来留下更多可接续空间，长度不变。
            if (position == tails.end()) tails.push_back(value);
            else *position = value;
        }

        // tails 的槽位数与“当前存在多少种长度 1..L”一一对应，因此 size 就是 LIS 长度。
        return static_cast<int>(tails.size());
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.lengthOfLIS(a) << "\n";
    return 0;
}
