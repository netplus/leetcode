// ============================================================================
// LC-215：数组中的第 K 个最大元素
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 4 周 / 第 25 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定整数数组 nums 和整数 k，请返回数组中第 k 个最大的元素。
// 请注意，你需要找的是数组排序后的第 k 个最大的元素，而不是第 k 个不同的元素。
// 你必须设计并实现时间复杂度为 O(n) 的算法解决此问题。
//
// 约束与要求：
//   - 1 <= k <= nums.length <= 10^5
//   - -10^4 <= nums[i] <= 10^4
//
// 复杂度目标：O(n) 平均 (快速选择) 或 O(n log k)（heap）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜顺序统计量：从完整排序收缩到只定位第 k 大
//
// 0. 优化是怎么来的
//   最自然的正确做法是完整排序后返回 nums[n-k]，时间 O(n log n)。
//   但答案只读取一个排名位置，排序却额外确定了其他 n-1 个元素的大量相对次序。
//   Quickselect / nth_element 只保留仍可能覆盖目标排名的分区：一次 partition 后，
//   目标在左就永久丢右边，目标在右就永久丢左边。省掉的是“建立无用全序”。
//
// 1. 图像直觉
//   nums=[3,2,1,5,6,4], k=2，升序目标下标 n-k=4。
//   完整排序：1 2 3 4 [5] 6
//                     ^ 只真正关心这里
//   选择算法只需要让 [5] 落到正确排名；左右内部怎么排列并不重要。
//
// 2. 一句话核心
//   只定位第 k 大所在的排名位置，不为答案永远不会读取的其他元素建立完整排序。
//
// 3. 公式 / 不变量
//   targetIndex = n - k。
//   nth_element 结束后，nums[targetIndex] 等于完整升序排序后该位置的值；
//   左侧元素不大于它、右侧元素不小于它，但两侧内部不保证有序。
//   Quickselect 视角的不变量：目标排名始终位于当前仍保留的分区。
//
// 4. 执行步骤
//   1. 把“第 k 大”转换成升序下标 targetIndex=n-k。
//   2. 调用 nth_element，只要求目标位置就位，而不是完整排序。
//   3. 返回 nums[targetIndex]；不要依赖左右两侧已经有序。
//   记忆：只问一个排名，就只把那个排名放对。
//
// 5. 为什么不会漏 / 不会重
//   nth_element 保证目标迭代器处的元素与完整排序后的同位置元素相同，因此它就是
//   升序第 n-k 小，也就是第 k 大。选择算法只淘汰排名范围不含 targetIndex 的一侧，
//   所以不会漏掉目标；重复值按出现次数参与排名，正好符合题意。
//
// 6. 边界与易错点
//   题目要第 k 个元素，不是第 k 个不同值。nth_element 会修改 nums。
//   不要把 nth_element 当成 sort；左右两侧只有分区关系，没有内部有序保证。
//   nth_element 是 C++17 及更早标准库 API；若要求手写，可实现随机化 Quickselect。
//
// 7. 举一反三
//   与 LC-347 对照：静态数组只要一个排名时适合 Quickselect/nth_element；
//   数据流或只愿保留 k 个候选时常用大小为 k 的堆。两者都在避免维护完整全序。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n k。
//   第 2 行：n 个以空格分隔的整数。
//   输出：第 k 大元素。
// test.in 的预期输出：5
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int findKthLargest(vector<int>& nums, int k) {
        const int targetIndex = static_cast<int>(nums.size()) - k;
        nth_element(nums.begin(), nums.begin() + targetIndex, nums.end());
        return nums[targetIndex];
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, k;
    if (!(cin >> n >> k)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.findKthLargest(a, k) << "\n";
    return 0;
}
