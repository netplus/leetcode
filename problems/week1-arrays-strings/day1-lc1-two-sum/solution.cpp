// ============================================================================
// LC-1：两数之和
// 难度：简单
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 1 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个整数数组 nums 和一个整数目标值 target，请你在该数组中找出和为目标值 target 的那两个整数，并返回它们的数组下标。
// 你可以假设每种输入只会对应一个答案，并且你不能使用两次相同的元素。
// 你可以按任意顺序返回答案。
//
// 约束与要求：
//   - 2 <= nums.length <= 10^4
//   - -10^9 <= nums[i] <= 10^9
//   - -10^9 <= target <= 10^9
//   - 只会存在一个有效答案
//
// 复杂度目标：O(n) 时间，O(n) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜哈希表：边扫描边查补数
// - 核心要点：
//   1. 思路起点：暴力枚举两下标是 O(n^2)；把已访问元素映射为“值 -> 下标”，当前数只需查询 target - nums[i]。
//   2. 执行逻辑：1. 初始化空哈希表；2. 从左到右先查补数，命中就返回两个下标；3. 未命中再记录当前值。
//   3. 为什么这样做：查询发生在插入当前元素之前，因此同一元素不会被复用；唯一解保证某次扫描到较晚下标时一定能找到较早下标。
// - 边界与易错点：不能用 set，因为答案需要下标；重复值应用覆盖或保留任一下标均可；先插入再查询会在 target=2*x 时误用自己。
// - 举一反三：“在线扫描 + 查询历史状态”也用于前缀和计数、Two Sum 数据流和补数配对问题。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n target。
//   第 2 行：n 个以空格分隔的整数。
//   输出：两个下标，以空格分隔并升序排列。
// test.in 的预期输出：0 1
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> twoSum(vector<int>& nums, int target) {
        unordered_map<int, int> indexOf;
        indexOf.reserve(nums.size() * 2);

        for (int i = 0; i < static_cast<int>(nums.size()); ++i) {
            const int complement = target - nums[i];
            auto it = indexOf.find(complement);  // 只在已经看过的元素中查找
            if (it != indexOf.end()) {
                return {it->second, i};
            }
            indexOf[nums[i]] = i;                // 查询后插入，避免复用 nums[i]
        }
        return {};  // 题目保证有唯一解；保留兜底使本地接口更健壮
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, target;
    if (!(cin >> n >> target)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto ans = sol.twoSum(a, target);
    for (size_t i = 0; i < ans.size(); ++i) cout << ans[i] << " \n"[i + 1 == ans.size()];
    return 0;
}

