// ============================================================================
// LC-1109：航班预订统计
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 4 天
// ----------------------------------------------------------------------------
// 题目描述：
// 这里有 n 个航班，它们分别从 1 到 n 进行编号。
// 有一份航班预订表 bookings，表中第 i 条预订记录 bookings[i] = [first_i, last_i, seats_i] 意味着在从 first_i 到 last_i （包含
// first_i 和 last_i）的每个航班上预订了 seats_i 个座位。
// 请你返回一个长度为 n 的数组 answer，里面的元素是每个航班预定的座位总数。
//
// 约束与要求：
//   - 1 <= n <= 2 * 10^4
//   - 1 <= bookings.length <= 2 * 10^4
//   - bookings[i].length == 3
//   - 1 <= first_i <= last_i <= n
//   - 1 <= seats_i <= 10^4
//
// 复杂度目标：O(n + m) 使用 差分数组。
//
// ----------------------------------------------------------------------------
// 解法精讲｜差分数组：区间更新转端点更新
//
// 1. 图像直觉
//   先不要背“左端 +x、右端后一位 -x”，从差分数组的定义把它推出来。
//
//   第一步：只看一条预订 [2,4,10]。
//   它希望给 2、3、4 号航班各增加 10：
//
//   航班：          1    2    3    4    5
//   增加量 A：      0   10   10   10    0
//
//   现在不记录 A 本身，而只记录“当前位置相对前一个位置改变了多少”：
//
//   diff[1] = A[1]             = 0
//   diff[2] = A[2] - A[1]      = +10   <- 从这里开始多 10
//   diff[3] = A[3] - A[2]      = 0
//   diff[4] = A[4] - A[3]      = 0
//   diff[5] = A[5] - A[4]      = -10   <- 从这里开始不再多 10
//
//   所以图上真正留下的只有两个“事件”：
//
//   航班：           1    2    3    4    5
//                    |   +10             -10
//                    |    |                |
//   diff：           0   10    0    0   -10
//   前缀累加：       0   10   10   10     0
//
//   这已经解释了为什么最后必须做前缀和：
//   diff 只告诉我们“这里发生了多少变化”，running 才表示“走到这里时当前总影响是多少”。
//
//   第二步：为什么区间内部完全不用改？
//   假设原值是 A，对闭区间 [L,R] 整体加 x。
//   区间内部任意相邻位置 i-1、i 都同时加 x：
//
//   (A[i] + x) - (A[i-1] + x)
//   = A[i] - A[i-1]
//
//   两个 x 抵消了，因此 L+1..R 的 diff 全都不变。
//   只有两个地方没有成对抵消：
//
//   进入区间：diff[L]     += x
//   离开区间：diff[R + 1] -= x
//
//   所以“改两个端点”不是技巧口诀，而是差分定义直接推出的结果。
//
//   第三步：把本题三条预订叠起来：
//   bookings = [[1,2,10], [2,3,20], [2,5,25]]
//
//   每条预订只留下开始/结束两个事件：
//   [1,2,10] -> 1 号开始 +10，3 号开始 -10
//   [2,3,20] -> 2 号开始 +20，4 号开始 -20
//   [2,5,25] -> 2 号开始 +25，6 号开始 -25
//
//   把同一位置事件相加：
//   航班/边界：      1    2     3     4    5     6(哨兵)
//   diff：          10   45   -10   -20   0    -25
//
//   从左到右累计，只取前 n 个位置：
//   running：       10   55    45    25   25
//
//   这就是每个航班最终的预订座位数。
//
// 2. 一句话核心
//   差分记录的不是“这个航班有多少座位”，而是“从这个航班开始，总座位数要改变多少”；区间内部的 +x 会在相邻差值里两两抵消，因此一次区间更新最终只剩“开始 +x、结束后一位 -x”两个事件。
//
// 3. 公式 / 不变量
//   先看数学定义。若 answer 使用 0-based 下标：
//
//   diff[0] = answer[0]
//   diff[i] = answer[i] - answer[i-1]   (i > 0)
//
//   于是前缀和正好是逆运算：
//   answer[i] = diff[0] + diff[1] + ... + diff[i]
//
//   若对 0-based 闭区间 [L,R] 整体加 x：
//   diff[L]     += x
//   diff[R + 1] -= x
//
//   本题输入却是 1-based 的 [first,last]。
//   映射到代码：
//
//   L = first - 1
//   R = last - 1
//   R + 1 = last
//
//   所以代码恰好写成：
//   first = booking[0] - 1
//   afterLast = booking[1]
//   diff[first]     += seats
//   diff[afterLast] -= seats
//
//   注意 afterLast 这个名字很重要：
//   它不是“last 的数组下标”，而是“last 对应的 0-based 下标再向右一格”。
//
//   扫描时维护不变量：
//   running = diff[0] + ... + diff[i]
//           = 当前仍处于生效区间内的所有 seats 之和
//   answer[i] = running
//
// 4. 执行步骤
//   1. 先把题目识别成“很多次连续区间统一 +seats，最后一次性询问所有点”的离线区间更新问题
//   2. 建立长度 n+1 的 diff；第 n 个额外位置专门容纳 last=n 时的“结束后一位”事件
//   3. 处理每条 booking：把 1-based first 转成 first-1，在这里执行 +seats
//   4. 把原题 last 直接作为 0-based 的 afterLast，在这里执行 -seats；不要再额外 +1
//   5. 所有 booking 处理完后，从 i=0 到 n-1 累加 running += diff[i]
//   6. 把当前 running 写入 answer[i]；它就是此时仍然生效的所有预订贡献之和
//   记忆：先问 diff 记录什么：相邻位置的变化。闭区间 [L,R] 加 x -> L 开门 +x，R+1 关门 -x -> 最后一路前缀累加。
//
// 5. 为什么不会漏 / 不会重
//   对任意一条 booking=[first,last,seats]，它在 first 对应的数组位置放入 +seats，因此从这里开始 running 会多出 seats；直到 last 对应的位置为止都没有遇到它的 -seats，所以这份贡献持续存在。扫描到 last 后面的第一个位置时才遇到 -seats，于是贡献恰好失效。换句话说，这条 booking 对所有满足 first <= 航班号 <= last 的位置贡献一次 seats，对区间外贡献 0。每条 booking 都独立满足这一性质，而加法可以线性叠加，因此把所有边界事件先相加再统一做一次前缀和，和逐条真正修改整个区间得到的结果完全相同。
//
// 6. 边界与易错点
//   最容易错的是三种下标混在一起：题面 [first,last] 是 1-based 闭区间；vector 的实际航班位置是 [first-1,last-1]；关闭事件在 one-past-right，也就是下标 last。因此代码是 diff[first-1]+=seats、diff[last]-=seats。使用 n+1 后，last==n 时 diff[n] 合法且只作哨兵，不需要 if 分支。不要忘记最终前缀累加，否则 diff 只是变化事件而不是答案。按官方约束，单个航班最多累计 2*10^4 * 10^4 = 2*10^8 个座位，32 位 int 足够。
//
// 7. 举一反三
//   差分与前缀和是一对逆操作：前缀和把“每点值”变成“累计值”，差分把“每点值”变成“相邻变化”。看到“很多次区间加，最后统一得到每个点”时优先考虑差分；若更新和查询在线交错，就需要 Fenwick Tree / Segment Tree；若更新对象变成矩形，可继续扩展到二维差分。公交上下客、会议室人数变化、区间覆盖次数、扫描线事件都可以用同一个“进入 +x、离开 -x”模型理解。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n (航班数) m (预订记录)。
//   接下来 m 行：first last seats。
//   输出：n 个以空格分隔的整数，表示从 1 开始编号的每个航班的座位数。
// test.in 的预期输出：10 55 45 25 25 0 0 0 0 0
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> corpFlightBookings(vector<vector<int>>& bookings, int n) {
        vector<int> diff(n + 1, 0);
        for (const auto& booking : bookings) {
            const int first = booking[0] - 1;
            const int afterLast = booking[1];
            diff[first] += booking[2];
            diff[afterLast] -= booking[2];
        }
        vector<int> answer(n);
        int running = 0;
        for (int i = 0; i < n; ++i) {
            running += diff[i];
            answer[i] = running;
        }
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, m; if (!(cin >> n >> m)) return 0;
    vector<vector<int>> bk(m, vector<int>(3));
    for (int i = 0; i < m; ++i) cin >> bk[i][0] >> bk[i][1] >> bk[i][2];
    auto ans = sol.corpFlightBookings(bk, n);
    for (int i = 0; i < n; ++i) cout << ans[i] << " \n"[i + 1 == n];
    return 0;
}
