// ============================================================================
// LC-215：数组中的第K个最大元素
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 4 周 / 第 25 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定整数数组 nums 和整数 k，请返回数组中第 k 个最大的元素。
// 请注意，你需要找的是数组排序后的第 k 个最大的元素，而不是第 k 个不同的元素。
// 你必须设计并实现时间复杂度为 O(n) 的算法解决此问题。
//
// 题目示例：
// 示例 1：
//   Input: nums = [3,2,1,5,6,4], k = 2
//   Output: 5
//
// 示例 2：
//   Input: nums = [3,2,3,1,2,4,5,5,6], k = 4
//   Output: 4
//
// 约束与要求：
//   - 1 <= k <= nums.length <= 10^5
//   - -10^4 <= nums[i] <= 10^4
//
// 复杂度目标：O(n) 平均 (快速选择) 或 O(n log k)（heap）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜顺序统计量：从完整排序收缩到只定位第 k 大
//
// 0. 优化是怎么来的
//   最自然的正确做法是完整排序：sort(nums.begin(), nums.end()) 后返回 nums[n-k]，时间 O(n log n)。它正确，但真正需要的信息只有一个顺序统计量；排序额外确定了其他 n-1 个元素之间的大量相对次序。
//
//   把目标写成升序下标 target=n-k。一次 partition 以后，pivot 已经落到最终排名位置：若 pivotIndex==target 就结束；若 target 在左边，右分区的内部顺序以后永远无关，反之亦然。于是每轮都丢掉一整个不可能包含目标排名的分区，只继续处理一侧，这就是 Quickselect。标准库 nth_element 提供同一类选择语义：目标位置变成完整排序后应有的值，但两侧内部无需排序。优化类型：候选淘汰 + 避免建立无用全序。
//
// 1. 图像直觉
//   nums = [3,2,1,5,6,4], k=2
//   升序目标下标：n-k = 4
//
//   完整排序会得到：
//   1 2 3 4 [5] 6
//             ^ 只真正关心这里
//
//   选择算法的目标不是把整行排好，而是做到：
//   [ <= 5 的若干元素 ] [5] [ >= 5 的若干元素 ]
//                         ^ target
//
//   左右内部顺序可以完全乱，因为答案不会读取它们。
//
// 2. 一句话核心
//   只定位第 k 大所在的排名位置，不为答案永远不会读取的其他元素建立完整排序。
//
// 3. 公式 / 不变量
//   升序视角：
//   targetIndex = n - k
//
//   nth_element(first, first + targetIndex, last) 结束后：
//   nums[targetIndex] 等于完整升序排序后该位置的值；
//   其左侧元素不大于它，右侧元素不小于它，但两侧内部不保证有序。
//
//   Quickselect 不变量：目标排名始终位于当前仍被保留的分区内。
//
// 4. 执行步骤
//   1. 把‘第 k 大’转换为升序中的 targetIndex=n-k
//   2. 调用 nth_element，只要求 targetIndex 对应元素就位，而不是完整排序
//   3. 直接返回 nums[targetIndex]；不要依赖左右两侧已经有序
//   记忆：只问一个排名，就只把那个排名放对；别替答案排序整个世界。
//
// 5. 为什么不会漏 / 不会重
//   nth_element 保证目标迭代器处的元素与完整排序后的同位置元素相同，因此它就是升序第 n-k 小、也就是第 k 大。选择算法只丢弃排名区间不包含 targetIndex 的一侧，所以不会漏掉目标；重复值按出现次数参与排名，正好符合题意。
//
// 6. 边界与易错点
//   题目要第 k 个元素，不是第 k 个不同值。nth_element 会修改 nums。不要把 nth_element 误认为 sort：目标两侧只有分区关系，没有内部排序保证。当前实现依赖 C++ 标准库合法的 C++17 API；若要求手写，可实现随机化 Quickselect。
//
// 7. 举一反三
//   与 LC-347 的 Top-K 对照：静态数组只要一个排名时可用 Quickselect/nth_element；数据流或只愿保留 k 个候选时常用大小为 k 的堆。核心都不是‘堆模板’，而是拒绝维护答案不需要的完整全序。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n k。
//   第 2 行：n 个以空格分隔的整数。
//   输出：第 k 大元素。
// test.in 的预期输出：5
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int findKthLargest(vector<int>& nums, int k) {
        // “第 k 大”在完整升序序列中的下标是 n-k；重复值仍按出现次数参与排名。
        const int targetIndex = static_cast<int>(nums.size()) - k;

        // nth_element 只保证 targetIndex 这个排名位置放上完整排序后应在这里的元素：
        // 左侧元素不大于它、右侧元素不小于它，但两侧内部都不保证有序。
        // 因此它避免了 sort 为其余 n-1 个位置建立无用的完整全序，并会原地修改 nums。
        nth_element(nums.begin(), nums.begin() + targetIndex, nums.end());
        return nums[targetIndex];
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, k;
    if (!(cin >> n >> k)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.findKthLargest(a, k) << "\n";
    return 0;
}
