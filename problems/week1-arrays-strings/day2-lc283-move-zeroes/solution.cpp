// ============================================================================
// LC-283：移动零
// 难度：简单
// 优先级：P1（进阶）
// 学习进度：第 1 周 / 第 2 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个数组 nums，编写一个函数将所有 0 移动到数组的末尾，同时保持非零元素的相对顺序。
// 请注意，必须在不复制数组的情况下原地对数组进行操作。
//
// 题目示例：
// 示例 1：
//   Input: nums = [0,1,0,3,12]
//   Output: [1,3,12,0,0]
//
// 示例 2：
//   Input: nums = [0]
//   Output: [0]
//
// 约束与要求：
//   - 1 <= nums.length <= 10^4
//   - -2^31 <= nums[i] <= 2^31 - 1
//
// 复杂度目标：O(n) 时间，O(1) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜快慢指针：稳定压缩
//
// 前置概念
//   这里的“稳定（stable）”指：被保留下来的元素必须保持它们在原数组中的相对顺序。
//
//   例如 [1,0,3,2,0] 移零后，非零部分必须仍是 [1,3,2]；[3,1,2] 虽然也把 0 放到了末尾，但破坏了稳定性，因此不合法。
//
//   所以 write 指针不能随意从后面拿元素填洞；它只能按 read 从左到右发现非零元素的顺序依次写入。
//
// 0. 优化是怎么来的
//   一个最容易写对的办法，是新建数组，把所有非零元素按原顺序复制过去，再补足 0；时间 O(n)，但额外空间 O(n)，不满足题目的原地要求。
//
//   如果不允许新数组，其实不需要记住全部输出，只需要记住“下一个非零元素应该落到哪里”。扫描到 read 时，前面已经处理过的非零元素顺序不会再变化，因此一个 write 下标就足以表示整个已压缩前缀。
//
//   遇到非零时，把它放到 write；遇到 0 时 write 不动。当前实现用 swap，使被覆盖位置自然留下 0，于是既保持稳定顺序，又不需要第二个数组。
//
//   优化类型：完整结果缓冲 -> 只保留下一写入位置这一小段状态，即原地稳定压缩。
//
// 1. 图像直觉
//   把数组想成“已压紧的非零区 + 中间零洞 + 尚未扫描区”：
//
//   nums = [1, 0, 0, 3, 12]
//           [ 已压紧 ] [零洞] [未扫描]
//                1      0 0    3 12
//                       ^      ^
//                     write   read
//
//   read 找到 3 时，把它交换到 write 指向的第一个零洞：
//   [1, 3, 0, 0, 12]
//          ^     ^
//        write  read继续
//
//   write 永远指向“下一个非零数应该落下的位置”；read 负责向前寻找下一个非零数。
//
// 2. 一句话核心
//   read 负责找非零元素，write 负责把它们按原顺序压紧到数组前缀；两者之间留下的自然都是零。
//
// 3. 公式 / 不变量
//   扫描到 read 之前始终维护：
//   [0, write)   = 已扫描部分的所有非零元素，且保持原相对顺序
//   [write, read)= 0
//
//   若 nums[read] != 0：
//   swap(nums[write], nums[read]);
//   write++
//
// 4. 执行步骤
//   1. write=0，表示第一个非零元素应落到下标 0
//   2. read 从左到右扫描全部元素
//   3. 遇到 0：read 继续，write 不动
//   4. 遇到非零：与 nums[write] 交换，然后 write++
//   5. 扫描结束后，[0,write) 是稳定的非零前缀，剩余位置全是 0
//   记忆：read 找要保留的，write 指向它该落的位置。
//
// 5. 为什么不会漏 / 不会重
//   write 只在遇到非零时递增，所以写入前缀的非零元素顺序与 read 的发现顺序完全一致；
//   而 write 到 read 之间的位置只可能是之前留下或交换过来的 0，因此交换不会把尚未处理的非零元素弄乱。
//
// 6. 边界与易错点
//   题目要求保持非零元素相对顺序，因此不能用普通 partition；write==read 时 swap 自己仍然正确，只是可省略；
//   这里的“快慢指针”本质是稳定过滤/压缩，而不是相向排除。
//
// 7. 举一反三
//   删除指定值、数组原地去重、按条件保留元素，都可以先问：read 负责筛选什么，write 负责把保留下来的元素写到哪里。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：移动零之后的数组，元素以空格分隔。
// test.in 的预期输出：1 3 12 0 0
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    void moveZeroes(vector<int>& nums) {
        int write = 0;
        for (int read = 0; read < static_cast<int>(nums.size()); ++read) {
            if (nums[read] != 0) {
                swap(nums[write], nums[read]);
                ++write;
            }
        }
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    sol.moveZeroes(a);
    for (int i = 0; i < n; ++i) cout << a[i] << " \n"[i + 1 == n];
    return 0;
}
