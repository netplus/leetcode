// ============================================================================
// LC-84：柱状图中最大的矩形
// 难度：困难
// 优先级：P1（进阶）
// 学习进度：第 2 周 / 第 12 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定 n 个非负整数，用来表示柱状图中各个柱子的高度。
// 每个柱子彼此相邻，且宽度为 1。
// 求在该柱状图中，能够勾勒出来的矩形的最大面积。
//
// 题目示例：
// 示例 1：
//   Input: heights = [2,1,5,6,2,3]
//   Output: 10
//   Explanation: The above is a histogram where width of each bar is 1.
//   The largest rectangle is shown in the red area, which has an area = 10 units.
//
// 示例 2：
//   Input: heights = [2,4]
//   Output: 4
//
// 约束与要求：
//   - 1 <= heights.length <=10^5
//   - 0 <= heights[i] <= 10^4
//
// 复杂度目标：O(n) 时间（单调栈）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜单调递增栈：从区间最小值模型推到左右边界
//
// 0. 优化是怎么来的
//   先写一个正确的 O(n^2) 基线：固定每根柱子 heights[i] 作为矩形的限制高度，分别向左、向右扩展，只要相邻柱高仍 >= heights[i] 就继续；这样能得到“以这根柱高为最低高度”时的最大区间。
//
//   这个基线已经把矩形问题变成了边界问题，真正慢的是：不同柱子会反复扫描同一片区域，只为了寻找左右阻挡位置。
//
//   从左到右扫描时，可以只保存“右侧更低终止事件尚未出现”的历史柱。当前高度严格低于栈顶时，当前 i 第一次终止栈顶高度继续向右扩展，因此可以 pop 并结算；pop 后的新栈顶提供当前实现使用的左侧阻挡位置。
//
//   注意等高策略：当前实现只在 `>` 时弹栈，所以等高柱可以共存，pop 后栈顶不保证严格更矮。较晚的等高柱可能先得到较窄范围，而更早的同高柱随后会得到更宽范围，求全局最大值仍不会遗漏。
//
//   优化类型：重复扩边界 -> 单调栈保存未封口高度，在边界事件到来时一次结算；每个下标只入栈、出栈一次，总时间 O(n)。
//
// 1. 图像直觉
//   这题不要从单调栈开始。先问：一个连续区间为什么能够形成某个矩形？
//
//   任意区间 [L,R]：
//   宽度 = R-L+1
//   高度 = min(heights[L..R])
//   area(L,R) = (R-L+1) * min(heights[L..R])
//
//   例如 heights = [2,1,5,6,2,3]，选区间 [2,3]：
//   高度由较矮的 5 决定，宽度为 2，所以面积是 5*2=10。
//
//   暴力枚举所有区间有 O(n^2) 个候选。更好的视角是反过来枚举“谁来当矩形的限制高度”：
//   固定 index=2, h=5，问它最多能向左右扩多远。
//
//   index:   0  1 | 2  3 | 4  5
//   height: [2, 1 | 5, 6 | 2, 3]
//                 ^ h=5
//
//   左边 index=1 的 1 < 5，不能进入矩形；
//   右边 index=4 的 2 < 5，也不能进入矩形；
//   中间 [2,3] 的高度都 >=5，所以可用范围是开区间 (1,4)。
//
//   若直接为每根柱子分别向左、向右扫描最近更矮柱，模型已经正确，但最坏仍是 O(n^2)。单调栈只是用来消除这些重复边界扫描。
//
//   扫描到 index=4, current=2 前，栈里的未决高度可为 [1,5,6]：
//   2 < 6 -> 高度 6 的右侧阻挡事件第一次出现，pop
//   2 < 5 -> 高度 5 的右侧阻挡事件第一次出现，pop
//   1 < 2 -> 停止
//
//   一个新的更矮柱可以一次结算多根历史柱，这才是单调栈进入本题的原因。
//
// 2. 一句话核心
//   先把“枚举矩形”改写成“每根柱子作为限制高度时能覆盖多宽”，再把反复寻找左右更矮边界的 O(n^2) 工作压缩成未决柱子的单调栈；栈是优化工具，不是题目的起点。
//
// 3. 公式 / 不变量
//   概念模型：若 left/right 是目标高度两侧第一个不能进入矩形的更矮阻挡位置，则真实可用闭区间是：
//   [left+1, right-1]
//
//   由闭区间长度公式 end-start+1：
//   width
//   = (right-1) - (left+1) + 1
//   = right-left-1
//
//   所以 `-1` 不是需要背的技巧，而是因为左右两个阻挡柱本身不能进入矩形。
//
//   一趟扫描实现中，当 currentHeight < heights[stack.top()] 时弹出 mid：
//   rightBoundary = i
//   leftBoundary  = stack.empty() ? -1 : stack.top()
//   height        = heights[mid]
//   width         = i - leftBoundary - 1
//   area          = height * width
//
//   这里还必须区分“数学上的最近严格更矮边界”和“具体实现的等高归属策略”。当前代码使用严格 `>` 弹栈，因此等高柱可以共存；pop 后的 leftBoundary 可能与 height 相等，不一定是严格更矮柱。后一根等高柱可能先得到较窄区间，但更早的等高柱后续会覆盖更宽范围，因此全局最大面积仍不会遗漏。
//
// 4. 执行步骤
//   1. 先从 area(L,R)=(R-L+1)*min(...) 建模，再把问题改写成：固定每根柱为限制高度，寻找它能覆盖的连续区间；这样 width 的含义先于单调栈建立
//   2. 识别 O(n^2) 基线慢在每根柱都重复寻找左右阻挡边界；从左到右扫描时，用栈保存“右侧终止边界尚未出现”的历史柱下标
//   3. 当前高度严格低于栈顶时反复 pop：当前 i 是该高度向右第一次遇到的更低事件；pop 后的新栈顶给出本实现的左侧阻挡位置，再由 `i-leftBoundary-1` 计算本次矩形
//   4. 扫描到 n 时把当前高度视作 0 的右哨兵，强制结算仍留在栈中的递增尾巴；若 pop 后栈空则用虚拟左边界 -1，使同一宽度公式继续成立
//   记忆：先建模“某个高度能覆盖哪段区间”，再问“边界什么时候第一次被未来元素确定”；不要从 `while + pop` 模板倒推题意。
//
// 5. 为什么不会漏 / 不会重
//   右侧为什么正确：mid 直到 i 才因更低高度被弹，说明从 mid+1 到 i-1 从未出现过能触发它出栈的更低高度，因此 i 是本次右侧终止事件。
//   区间为什么可用：在 mid 被弹时，leftBoundary 之后到 i-1 的柱子都没有被当前高度淘汰掉，能够支撑本次 height；两侧阻挡位置本身不计入，因此宽度是 i-leftBoundary-1。
//   等高为什么不漏：严格 `>` 允许相等高度保留，所以某个较晚等高柱的左边界可能也是等高柱；它得到的区间可以较窄，但较早的同高柱会在更晚的下降事件中继续向左代表同一高度并得到不小于它的范围，故求全局 maximum 时不丢答案。
//   复杂度为什么 O(n)：每个真实下标只入栈一次、出栈一次；while 的所有 pop 合计 O(n)。
//
// 6. 边界与易错点
//   最容易错的四点：一是还没理解区间模型就死记 `i-top-1`；二是把严格 `>` 实现中的 pop 后栈顶误说成永远“严格更矮”；三是忽略相等高度的归属策略；四是忘记末尾虚拟 0 / 左侧 -1 都是为了让边界复用主公式。栈要存 index，因为宽度来自位置差。
//
// 7. 举一反三
//   学习顺序建议固定为：LC-739 先理解“未决问题 + pop 时确定右侧答案”；LC-84 再理解“限制高度 + 左右边界 + width”；以后遇到 LC-907/LC-2104 一类贡献题，再把左右边界距离变成 `leftChoices*rightChoices`，并用一严一松的比较关系解决等值元素重复归属。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：柱状图中的最大矩形面积。
// test.in 的预期输出：10
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int largestRectangleArea(vector<int>& heights) {
        // increasing 存尚未确定右侧更矮边界的柱子下标；对应高度从栈底到栈顶单调不降。
        stack<int> increasing;
        long long best = 0;
        const int n = static_cast<int>(heights.size());

        // 多跑一轮 i==n，并把它视作高度 0 的虚拟右哨兵，
        // 用来强制结算那些直到数组末尾都没遇到更矮柱的历史高度。
        for (int i = 0; i <= n; ++i) {
            const int currentHeight = (i == n) ? 0 : heights[i];

            // 当前柱更矮时，被弹柱子的右侧第一个“严格更矮”位置刚刚确定为 i。
            while (!increasing.empty() && heights[increasing.top()] > currentHeight) {
                const int height = heights[increasing.top()];
                increasing.pop();

                // 弹栈后的新栈顶是当前实现计算这根柱宽度时的左阻挡位置；
                // 因为这里使用严格 > 弹栈，相等高度允许共存，所以它可能与 height 相等，
                // 不一定是“左侧第一个严格更矮柱”。若栈空则使用虚拟边界 -1。
                const int leftBoundary = increasing.empty() ? -1 : increasing.top();

                // 两个边界下标本身不计入本次矩形，宽度为 i-leftBoundary-1。
                // 对等高柱而言，较晚那根可能先得到较窄宽度；更早的等高柱随后弹出时会覆盖更宽范围，
                // 因而全局最大面积仍不会遗漏。
                best = max(best, 1LL * height * (i - leftBoundary - 1));
            }

            // 当前下标加入未封口集合。i==n 的虚拟哨兵只在最后压栈，循环随即结束，
            // 因此后续不会用它访问 heights[n]。
            increasing.push(i);
        }

        return static_cast<int>(best);
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.largestRectangleArea(a) << "\n";
    return 0;
}