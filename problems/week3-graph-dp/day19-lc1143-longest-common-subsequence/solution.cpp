// ============================================================================
// LC-1143：最长公共子序列
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 3 周 / 第 19 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定两个字符串 text1 和 text2，返回这两个字符串的最长公共子序列的长度。
// 如果不存在公共子序列，返回 0。
// 一个字符串的子序列是指这样一个新的字符串：它是由原字符串在不改变字符的相对顺序的情况下删除某些字符（也可以不删除任何字符）后组成的新字符串。
// 例如，"ace" 是 "abcde" 的子序列，但 "aec" 不是 "abcde" 的子序列。
// 两个字符串的公共子序列是这两个字符串所共同拥有的子序列。
//
// 题目示例：
// 示例 1：
//   Input: text1 = "abcde", text2 = "ace"
//   Output: 3
//   Explanation: The longest common subsequence is "ace" and its length is 3.
//
// 示例 2：
//   Input: text1 = "abc", text2 = "abc"
//   Output: 3
//   Explanation: The longest common subsequence is "abc" and its length is 3.
//
// 示例 3：
//   Input: text1 = "abc", text2 = "def"
//   Output: 0
//   Explanation: There is no such common subsequence, so the result is 0.
//
// 约束与要求：
//   - 1 <= text1.length, text2.length <= 1000
//   - text1 和 text2 仅由小写英文字符组成。
//
// 复杂度目标：O(m*n) 时间，O(min(m,n)) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜双序列 DP：两个前缀形成二维网格，用 diagonal 保存被一维覆盖的左上角
//
// 0. 优化是怎么来的
//   自然的正确递归是从两个字符串末尾开始：
//   - 若末字符相等，就把这个匹配计入答案，然后递归处理两个更短前缀；
//   - 若末字符不同，就分别尝试丢掉 text1 的末字符或 text2 的末字符，取两种结果较大者。
//
//   它正确，但不同分支会反复询问相同的前缀对 (i,j)。例如一次先删 text1 字符、下一层再删 text2，与先删 text2、再删 text1，都会走到同一个 (i-1,j-1) 子问题。直接递归因此会产生大量重复子问题。
//
//   把每个前缀对只算一次，就得到二维 DP：共有 (m+1)*(n+1) 个状态，时间 O(m*n)。
//
//   接着观察转移只依赖上一行 dp[i-1][j]、当前行左边 dp[i][j-1]、上一行左上 dp[i-1][j-1]。所以不需要保存更早的所有行，可以压成一维数组。
//
//   但压缩带来一个新的实现问题：从左到右覆盖 dp[j] 后，旧的左上角会消失。因此额外用 diagonal 保存“更新前上一列的旧 dp[j-1]”。每次先把旧 dp[j] 保存为 oldAbove，完成当前格更新后，再令 diagonal=oldAbove，为下一列准备新的左上角。
//
//   优化链：指数递归 -> 重复前缀对子问题 -> 二维 O(m*n) DP -> 依赖仅上/左/左上 -> 一维滚动 + diagonal。
//
// 1. 图像直觉
//   把两个字符串放成网格坐标：
//
//             text2:  a  c  e
//                   0  1  2  3
//   text1:      0   0  0  0  0
//    a          1   0  \  .  .
//    b          2   .   X  .  .
//    c          3   .   .  .  .
//    ...
//
//   当前格 X 需要三个方向：
//
//   左上 diagonal    上 old dp[j]
//           \          |
//            \         v
//             ---->   当前 X
//                     ^
//                     |
//                左 new dp[j-1]
//
//   一维数组从左到右更新时：
//   dp[j]     在覆盖前 = 上方
//   dp[j-1]   已覆盖后   = 左方
//   diagonal  额外保存   = 左上方
//
//   这三个时间版本不能混。
//
// 2. 一句话核心
//   把两个前缀作为二维状态；字符相等走左上 +1，不等在上/左中取 max；压成一维后用 diagonal 专门保存即将被覆盖的旧左上角。
//
// 3. 公式 / 不变量
//   二维状态：
//   LCS[i][j] = text1 前 i 个字符与 text2 前 j 个字符的最长公共子序列长度。
//
//   边界：
//   LCS[0][j] = 0
//   LCS[i][0] = 0
//
//   若 text1[i-1] == text2[j-1]：
//   LCS[i][j] = LCS[i-1][j-1] + 1
//
//   否则：
//   LCS[i][j] = max(LCS[i-1][j], LCS[i][j-1])
//
//   一维更新前：
//   dp[j]   = LCS[i-1][j]     // 上
//   dp[j-1] = LCS[i][j-1]    // 左
//   diagonal = LCS[i-1][j-1] // 左上
//
//   先保存 oldAbove=dp[j]，再写 dp[j]，最后 diagonal=oldAbove。
//
// 4. 执行步骤
//   1. 创建 text2.size()+1 个 0，额外的第 0 列表示任何字符串与空前缀的 LCS 长度为 0
//   2. 逐个扫描 text1 的字符；每进入新一行时把 diagonal 重置为 0，对应这一行最左侧的旧左上边界
//   3. 对 j 从 1 向右扫描，第一件事先保存 oldAbove=dp[j]，因为覆盖后下一列仍需要它作为旧左上角
//   4. 若两个当前字符相等，写 dp[j]=diagonal+1；否则写 dp[j]=max(dp[j],dp[j-1])，分别对应上与左
//   5. 当前格写完后再执行 diagonal=oldAbove，让下一列得到正确的上一行左上状态；最后返回 dp.back()
//   记忆：双前缀画网格：相等左上+1，不等上左取大；压一维时先救出 oldAbove，再覆盖，再把它交给 diagonal。
//
// 5. 为什么不会漏 / 不会重
//   若两个前缀末字符相等，存在一个最优 LCS 可以把这个共同字符作为新增末尾，其余部分来自两个更短前缀的 LCS，因此左上 +1。若末字符不同，它们不可能同时作为同一个匹配末尾；任意公共子序列至少不使用其中一个末字符，所以一定包含在“删 text1 末字符”或“删 text2 末字符”的某个子问题中，取 max 覆盖全部可能。滚动数组只是复用存储位置；oldAbove 与 diagonal 保证覆盖前需要的上/左上值没有丢失。
//
// 6. 边界与易错点
//   最常见错误是 diagonal 更新时机：必须先保存 oldAbove，再计算当前 dp[j]，最后才 diagonal=oldAbove。dp[j-1] 是当前行新值，dp[j] 在更新前是上一行旧值，两者不能混淆。子序列允许删除但保持相对顺序，不要求连续；不要和最长公共子串混为一题。当前实现空间是 O(text2.length)，若严格追求 O(min(m,n)) 可先让较短字符串作为列，但不必为此改变已正确主实现。
//
// 7. 举一反三
//   直接复用 LC-62/64 的二维网格阅读法：先画依赖箭头，再决定遍历顺序。LC-62/64 只有上和左；LCS 多了左上，因此一维压缩必须额外保存 diagonal。之后学习编辑距离时仍然是同一张“两个前缀”网格，只会改变三个方向的转移含义。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：text1。
//   第 2 行：text2。
//   输出：最长公共子序列长度。
// test.in 的预期输出：3
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int longestCommonSubsequence(string text1, string text2) {
        // dp[j] 表示当前扫描进度下，text1 前缀与 text2 前 j 个字符的 LCS 长度。
        // 额外第 0 列恒为 0，对应任意字符串与空前缀的 LCS 长度为 0。
        vector<int> dp(text2.size() + 1, 0);

        for (char a : text1) {
            // 每进入 text1 的新一行，diagonal 从 0 开始，表示二维表这一行最左侧的旧左上角 LCS[i-1][0]。
            int diagonal = 0;

            for (int j = 1; j <= static_cast<int>(text2.size()); ++j) {
                // 覆盖 dp[j] 之前必须先保存它：此刻它仍是上一行同列“上方”状态，
                // 而下一列会把这个旧值当作自己的“左上角”。
                int oldAbove = dp[j];

                // 更新当前格之前三个状态的时间版本分别是：
                // diagonal = 旧左上；dp[j] = 旧上方；dp[j-1] = 已更新的当前行左方。
                if (a == text2[j - 1]) dp[j] = diagonal + 1;
                else dp[j] = max(dp[j], dp[j - 1]);

                // 当前格完成后，才把原来的上方 oldAbove 交给 diagonal，
                // 使它在下一列恰好代表新的“旧左上”。顺序提前会丢失二维依赖。
                diagonal = oldAbove;
            }
        }

        // 扫描完两个完整前缀后，最后一列就是两个完整字符串的 LCS 长度。
        return dp.back();
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    string a, b; if (!(cin >> a >> b)) return 0;
    cout << sol.longestCommonSubsequence(a, b) << "\n";
    return 0;
}
