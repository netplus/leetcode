// ============================================================================
// LC-347：前 K 个高频元素
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 4 周 / 第 25 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 nums 和一个整数 k，请你返回其中出现频率前 k 高的元素。
// 你可以按任意顺序返回答案。
//
// 题目示例：
// 示例 1：
//   Input: nums = [1,1,1,2,2,3], k = 2
//
//   Output: [1,2]
//
// 示例 2：
//   Input: nums = [1], k = 1
//
//   Output: [1]
//
// 示例 3：
//   Input: nums = [1,2,1,2,1,2,3,1,3,2], k = 2
//
//   Output: [1,2]
//
// 约束与要求：
//   - 1 <= nums.length <= 10^5
//   - -10^4 <= nums[i] <= 10^4
//   - k 的取值范围是 [1, 数组中不相同的元素的个数]
//   - 题目数据保证答案唯一，换句话说，数组中前 k 个高频元素的集合是唯一的
//
// 复杂度目标：O(n log k) 时间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜频次哈希 + 大小为 k 的最小堆：只保留当前最强 Top-K
//
// 0. 优化是怎么来的
//   自然正确做法是哈希统计频率后，把所有 distinct 元素按 frequency 排序，再取前 k 个。若不同元素数为 m，排序成本 O(m log m)，但答案只需要 Top-K 集合，Top-K 内部也无需排序。
//
//   扫描每个 (value,frequency) 时，假设已经保留当前见过元素中的最强 k 个。把新候选临时放进来后只有 k+1 个候选；其中频率最小的那个不可能属于这 k+1 项的 Top-K，而且以后其他旧元素的频率已经固定，它也没有机会‘后来变强’，因此可以永久删除。于是始终只保存 k 个候选，用最小堆 O(log k) 找到并淘汰最弱者。优化类型：候选支配 + 避免完整排序。
//
// 1. 图像直觉
//   频次：
//   A:5  B:2  C:4  D:1，k=2
//
//   处理 A：heap=[5]
//   处理 B：heap=[2,5]
//   处理 C：临时 [2,5,4]
//                ^ 最弱=2，弹掉 B
//            heap=[4,5]
//   处理 D：临时 [1,4,5]
//                ^ 弹掉 1
//
//   最终只剩频率 4、5 的两个元素。
//
//   为什么用最小堆而不是最大堆？
//   因为我们保留的是强者，反复需要快速删除的是‘保留集合中的最弱者’。
//
// 2. 一句话核心
//   先统计频率，再让大小为 k 的最小堆充当 Top-K 门槛：新候选进来，超过 k 就立刻淘汰当前最弱者。
//
// 3. 公式 / 不变量
//   frequency[value] = value 的总出现次数
//
//   处理任意若干 distinct 元素后：
//   heap = 这些已处理元素中频率最高的 min(k, seen) 个候选。
//
//   对新候选 push 后若 size>k：
//   pop 最小频率项。
//
//   因此最终 heap 恰为全体 Top-K。
//   时间：统计 O(n)，堆处理 O(m log k)，m=distinct 数；空间 O(m+k)。
//
// 4. 执行步骤
//   1. 一次扫描 nums，用 unordered_map 统计每个 value 的最终 frequency
//   2. 遍历频次表，把 {frequency,value} 放进最小堆
//   3. 每次入堆后若大小超过 k，立即 pop；堆顶就是当前保留集合中最弱、最该淘汰的候选
//   4. 扫描结束后弹出堆中 k 个 value 作为答案；题目允许任意顺序
//   记忆：要留最强 k 个，就让最弱那个站在堆顶，随时准备被淘汰。
//
// 5. 为什么不会漏 / 不会重
//   归纳假设处理前 heap 已保存此前元素的 Top-K。加入新元素后，真正需要考虑的候选只有旧 Top-K 加新元素：任何此前已被淘汰元素都不强于旧 Top-K 门槛，频率又已经固定，不可能重新反超。对这至多 k+1 个候选删除最弱者后，剩余恰是新前缀的 Top-K。重复到结束即可得到全局答案，不漏也不重。
//
// 6. 边界与易错点
//   先完成频率统计再做 Top-K，因为扫描原数组期间 frequency 还会变化。答案顺序任意。priority_queue<pair<int,int>,...,greater<...>> 会在频率相同后继续比较 value，但题目保证 Top-K 集合唯一，因此不影响合法性。结构化绑定和 greater<pair<...>> 都是 C++17 合法能力。
//
// 7. 举一反三
//   与 LC-215 对照选择工具：只要第 k 大一个静态排名，可用 Quickselect；要保留 Top-K 集合且 k 小，用大小 k 的堆；频率范围较小时还可桶排序。选结构前先问：我真正需要维护完整顺序、一个排名，还是只有 k 个强候选？
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n k。
//   第 2 行：n 个以空格分隔的整数。
//   输出：频率最高的 k 个元素，以空格分隔，顺序任意。
// test.in 的预期输出：1 2
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> topKFrequent(vector<int>& nums, int k) {
        // 必须先完成最终频率统计；若边扫描 nums 边做 Top-K，某个 value 后续还会继续增频，
        // 当前“弱者”并不一定真的弱，不能安全淘汰。
        unordered_map<int, int> frequency;
        for (int value : nums) ++frequency[value];

        // top 是大小最多为 k 的最小堆，pair.first=count；
        // 堆顶始终是“当前 Top-K 候选里最弱的一个”，方便候选过多时 O(log k) 淘汰门槛元素。
        priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> top;
        for (auto [value, count] : frequency) {
            top.push({count, value});
            // 新候选加入后若有 k+1 个，只需删除其中频率最低者；
            // 被删元素不可能属于已处理元素的 Top-K，且最终频率已固定，以后也不会重新变强。
            if (static_cast<int>(top.size()) > k) top.pop();
        }

        vector<int> answer;
        // 题目允许任意顺序，所以直接逐个弹出剩余 k 个候选即可；无需再排序。
        while (!top.empty()) {
            answer.push_back(top.top().second);
            top.pop();
        }
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, k; if (!(cin >> n >> k)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto ans = sol.topKFrequent(a, k);
    for (size_t i = 0; i < ans.size(); ++i) cout << ans[i] << " \n"[i + 1 == ans.size()];
    return 0;
}
