// ============================================================================
// LC-455：分发饼干
// 难度：简单
// 优先级：P0（必做）
// 学习进度：第 4 周 / 第 24 天
// ----------------------------------------------------------------------------
// 题目描述：
// 假设你是一位很棒的家长，想要给你的孩子们一些小饼干。
// 但是，每个孩子最多只能给一块饼干。
// 对每个孩子 i，都有一个胃口值 g[i]，这是能让孩子满足胃口的饼干的最小尺寸；并且每块饼干 j 都有一个尺寸 s[j]。
// 如果 s[j] >= g[i]，我们可以将饼干 j 分配给孩子 i，这个孩子会得到满足。
// 你的目标是满足尽可能多的孩子，并输出这个最大数值。
//
// 约束与要求：
//   - 1 <= g.length <= 3 * 10^4
//   - 0 <= s.length <= 3 * 10^4
//   - 1 <= g[i], s[j] <= 2^31 - 1
//
// 复杂度目标：O(g log g + s log s) 时间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜排序 + 双指针贪心：让最小够用资源匹配最小需求
//
// 1. 图像直觉
//   g = [1,2,3]
//   s = [1,1,3]
//   排序后从最小端看：
//
//   孩子:  1   2   3
//          ^ child
//   饼干:  1   1   3
//          ^ cookie
//
//   cookie=1 能满足 child=1：把这块最小够用饼干交出去。
//   接着 cookie=1 连胃口 2 都满足不了；后面的孩子胃口只会更大，
//   所以这块饼干可以永久丢弃。最后 cookie=3 满足胃口 2，答案为 2。
//
// 2. 一句话核心
//   始终处理最小未满足需求：资源太小就丢掉，资源够用就立刻匹配，因为更大的资源应留给更难满足的需求。
//
// 3. 公式 / 不变量
//   排序后维护：
//   child  = 当前最小未满足孩子下标
//   cookie = 当前最小未处理饼干下标
//
//   若 s[cookie] < g[child]：
//       该饼干也不可能满足任何更大的胃口 => 只移动 cookie。
//   若 s[cookie] >= g[child]：
//       用它满足当前孩子 => child++, cookie++。
//
//   不变量：已经处理过的饼干中，不存在还能让当前或之后孩子额外获益的资源；
//   child 之前的孩子已经以不牺牲最优解的方式满足。
//
// 4. 执行步骤
//   1. 分别升序排序 g 和 s，让最容易满足的孩子与最小剩余饼干位于双指针前端。
//   2. 当前饼干太小时，只移动 cookie；它对所有剩余孩子都不可能有用。
//   3. 当前饼干足够时，立即分给当前孩子，同时移动 child 和 cookie。
//   4. 任一数组扫描完就停止，child 恰好等于已满足孩子数量。
//   记忆：最小需求先服务；资源太小丢资源，资源够用两边一起走。
//
// 5. 为什么不会漏 / 不会重
//   若最小饼干 s<最小剩余胃口 g，因为后续胃口都 >=g，s 不可能进入任何可行匹配，丢弃不会漏解。
//   若 s>=g，考虑任意最优方案：总可以通过交换让 s 去满足 g，而不减少满足人数；
//   因此当前匹配可以安全固定。重复该交换论证即可得到全局最优。
//
// 6. 边界与易错点
//   排序会修改输入；每块饼干和每个孩子都只能使用一次。饼干太小时不要移动 child，
//   否则会无理由放弃一个仍可能被后续大饼干满足的孩子。空饼干数组自然返回 0。
//
// 7. 举一反三
//   这是典型的有序资源匹配：最小够用资源服务最小需求。以后遇到“资源有能力值、任务有最低需求、
//   最大化匹配数”，优先尝试排序 + 双指针，并用交换论证说明局部匹配为什么不牺牲全局最优。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：ng ns。
//   第 2 行：ng 个以空格分隔的整数 (g)。
//   第 3 行：ns 个以空格分隔的整数 (s)。
//   输出：可以满足的孩子数量。
// test.in 的预期输出：1
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int findContentChildren(vector<int>& g, vector<int>& s) {
        sort(g.begin(), g.end());
        sort(s.begin(), s.end());
        int child = 0, cookie = 0;
        while (child < static_cast<int>(g.size()) && cookie < static_cast<int>(s.size())) {
            if (s[cookie] >= g[child]) ++child;
            ++cookie;
        }
        return child;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int ng, ns; if (!(cin >> ng >> ns)) return 0;
    vector<int> g(ng), s(ns);
    for (int i = 0; i < ng; ++i) cin >> g[i];
    for (int i = 0; i < ns; ++i) cin >> s[i];
    cout << sol.findContentChildren(g, s) << "\n";
    return 0;
}
