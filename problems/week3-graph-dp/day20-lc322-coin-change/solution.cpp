// ============================================================================
// LC-322：零钱兑换
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 3 周 / 第 20 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 coins，表示不同面额的硬币；以及一个整数 amount，表示总金额。
// 计算并返回可以凑成总金额所需的最少的硬币个数。
// 如果没有任何一种硬币组合能组成总金额，返回 -1。
// 你可以认为每种硬币的数量是无限的。
//
// 约束与要求：
//   - 1 <= coins.length <= 12
//   - 1 <= coins[i] <= 2^31 - 1
//   - 0 <= amount <= 10^4
//
// 复杂度目标：O(n*amount) 时间（完全背包）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜完全背包：最少硬币数
// - 核心要点：
//   1. 思路起点：dp[a] 表示组成金额 a 的最少硬币数；每个状态枚举最后使用的硬币，来源为 dp[a-coin]+1。
//   2. 执行逻辑：1. dp[0]=0，其余设为 amount+1；2. 金额从 1 到 amount，枚举 coin<=a；3. 取最小转移，哨兵未改变则返回 -1。
//   3. 为什么这样做：任意最优方案取出最后一枚 coin 后，剩余必是金额 a-coin 的最优方案，否则可替换得更优；枚举所有 coin 覆盖全部可能。
// - 边界与易错点：硬币可无限使用，所以状态可从较小金额反复转移；无解必须返回 -1；amount=0 返回 0。
// - 举一反三：完全背包的遍历顺序允许当前物品重复使用；求方案数时还要区分组合顺序与排列顺序。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n amount。
//   第 2 行：n 个以空格分隔的硬币面额。
//   输出：最少硬币数；无法凑出时输出 -1。
// test.in 的预期输出：3
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int coinChange(vector<int>& coins, int amount) {
        vector<int> dp(amount + 1, amount + 1);
        dp[0] = 0;
        for (int current = 1; current <= amount; ++current) {
            for (int coin : coins) {
                if (coin <= current) dp[current] = min(dp[current], dp[current - coin] + 1);
            }
        }
        return dp[amount] == amount + 1 ? -1 : dp[amount];
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, amount; if (!(cin >> n >> amount)) return 0;
    vector<int> c(n);
    for (int i = 0; i < n; ++i) cin >> c[i];
    cout << sol.coinChange(c, amount) << "\n";
    return 0;
}

