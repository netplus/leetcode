// ============================================================================
// LC-1：两数之和
// 难度：简单
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 1 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个整数数组 nums 和一个整数目标值 target，请你在该数组中找出和为目标值 target 的那两个整数，并返回它们的数组下标。
// 你可以假设每种输入只会对应一个答案，并且你不能使用两次相同的元素。
// 你可以按任意顺序返回答案。
//
// 约束与要求：
//   - 2 <= nums.length <= 10^4
//   - -10^9 <= nums[i] <= 10^9
//   - -10^9 <= target <= 10^9
//   - 只会存在一个有效答案
//
// 复杂度目标：O(n) 时间，O(n) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜哈希表：边扫描边查补数
//
// 1. 图像直觉
//   例：nums = [2, 7, 11, 15], target = 9。扫描到 7 时：
//
//   历史                当前
//   [ 2 ]                7
//     ^                  |
//     +---- 2 = 9 - 7 ---+
//
//   当前数只需要到“已经看过的历史”里找自己的补数。
//
// 2. 一句话核心
//   当前拿到 x，不去未来枚举配对，只问历史里是否已经出现 target-x。
//
// 3. 公式 / 不变量
//   x + old = target
//   old = target - x
//
// 4. 执行步骤
//   1. 初始化“值 -> 下标”的哈希表
//   2. 扫描当前 nums[i]，先计算 complement = target-nums[i]
//   3. 只在历史哈希表里查 complement；命中就返回两个下标
//   4. 未命中时，再把 nums[i] -> i 记录到历史
//   记忆：先查补数 -> 命中就返回 -> 未命中再记录当前值。
//
// 5. 为什么不会漏 / 不会重
//   唯一答案中的两个位置总有一个先被扫描、另一个后被扫描；扫描到后者时，前者已经在哈希表里，所以一定能命中。
//   又因为“先查、后插”，当前元素尚未进入历史，因此不会在 target=2*x 时把同一个下标使用两次。
//
// 6. 边界与易错点
//   不能只用 set，因为答案需要返回下标；查询必须发生在插入当前元素之前；重复值可以覆盖旧下标，题目的唯一解仍能被找到。
//
// 7. 举一反三
//   这是“在线扫描 + 查询历史状态”的最小模型。LC-560 的前缀和计数也是同一结构：当前拿到一个状态，再去历史里寻找它需要配对的状态。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n target。
//   第 2 行：n 个以空格分隔的整数。
//   输出：两个下标，以空格分隔并升序排列。
// test.in 的预期输出：0 1
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> twoSum(vector<int>& nums, int target) {
        unordered_map<int, int> indexOf;
        indexOf.reserve(nums.size() * 2);

        for (int i = 0; i < static_cast<int>(nums.size()); ++i) {
            const int complement = target - nums[i];
            auto it = indexOf.find(complement);  // 只在已经看过的元素中查找
            if (it != indexOf.end()) {
                return {it->second, i};
            }
            indexOf[nums[i]] = i;                // 查询后插入，避免复用 nums[i]
        }
        return {};  // 题目保证有唯一解；保留兜底使本地接口更健壮
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, target;
    if (!(cin >> n >> target)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto ans = sol.twoSum(a, target);
    for (size_t i = 0; i < ans.size(); ++i) cout << ans[i] << " \n"[i + 1 == ans.size()];
    return 0;
}
