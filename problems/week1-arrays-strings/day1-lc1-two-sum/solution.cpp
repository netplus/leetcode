// ============================================================================
// LC-1：两数之和
// 难度：简单
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 1 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个整数数组 nums 和一个整数目标值 target，请你在该数组中找出和为目标值 target 的那两个整数，并返回它们的数组下标。
// 你可以假设每种输入只会对应一个答案，并且你不能使用两次相同的元素。
// 你可以按任意顺序返回答案。
//
// 约束与要求：
//   - 2 <= nums.length <= 10^4
//   - -10^9 <= nums[i] <= 10^9
//   - -10^9 <= target <= 10^9
//   - 只会存在一个有效答案
//
// 复杂度目标：O(n) 时间，O(n) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜从暴力配对到哈希索引：边扫描边查补数
//
// 1. 图像直觉
//   先从最自然的暴力想法开始。例：nums = [2, 7, 11, 15], target = 9。
//
//   固定 2 后，只能向后一个个试：
//
//   2 + 7  = 9   -> 命中
//   2 + 11 = 13
//   2 + 15 = 17
//
//   如果第一次没命中，换下一个数又要继续扫描后面的候选。
//   两层枚举慢的地方其实很具体：我们在反复做“到数组里找某一个确定的值”。
//
//   因为当前拿到 x 时，另一个数并不是未知的：
//
//   x + old = target
//   old     = target - x
//
//   所以可以反过来扫描：不再拿 x 去未来逐个试，而是给“已经看过的值”建立索引。
//
//   扫描 nums = [2, 7, 11, 15]：
//
//   历史索引 indexOf          当前 x=7
//   { 2 -> 0 }                    |
//         ^                       |
//         +---- 查找 9-7 = 2 -----+
//
//   find(2) 直接告诉我们：值 2 以前出现过，而且下标是 0。
//   于是当前下标 1 和历史下标 0 就是答案。
//
//   优化的关键不是“用了 unordered_map”这件事本身，而是：
//   把暴力中的“反复线性找一个确定值”换成了“先建立索引，再直接查这个值”。
//
// 2. 一句话核心
//   暴力慢在每次都线性寻找一个已经确定的补数；把已扫描元素建立成“值 -> 下标”索引后，当前 x 只需去历史里直接查 target-x。
//
// 3. 公式 / 不变量
//   当前值：x = nums[i]
//   需要的历史值：
//
//   x + old = target
//   old = target - x = complement
//
//   暴力：
//   对一个 x，在候选位置中逐个比较是否等于 complement
//   => 一次寻找 O(n)，总共 O(n^2)
//
//   哈希索引：
//   indexOf[value] = 这个 value 已出现过的下标
//   indexOf.find(complement) = 平均 O(1)
//   => 整个数组只扫描一次，平均 O(n)
//
//   扫描不变量：
//   处理下标 i 之前，indexOf 只保存下标 < i 的历史元素。
//
// 4. 执行步骤
//   1. 初始化 unordered_map<int,int> indexOf；它不是只记录“出现过没有”，而是保存“值 -> 历史下标”
//   2. 扫描当前 nums[i]，先计算唯一需要的补数 complement = target - nums[i]
//   3. 用 indexOf.find(complement) 做纯查询；命中说明历史下标与当前 i 已经组成答案，立即返回
//   4. 只有查询未命中时，才执行 indexOf[nums[i]] = i，把当前元素加入历史，供后面的元素查询
//   记忆：先从暴力问：我到底在反复找什么？算出 complement -> find 历史 -> 命中返回 -> 未命中再记录当前。
//
// 5. 为什么不会漏 / 不会重
//   任意合法答案都有一个较早下标 i 和较晚下标 j。扫描到 j 之前，nums[i] 已经进入 indexOf；而 nums[i]=target-nums[j]，所以扫描 j 时一定能通过 complement 命中它。
//   反过来，哈希表里只保存当前下标之前的元素，因此一次命中一定使用两个不同下标。整个过程只是把暴力枚举的配对顺序改成“较晚元素到来时寻找较早元素”，没有删掉任何合法配对。
//
// 6. 边界与易错点
//   最重要的是“先查后记”。例如 nums=[3,3], target=6：第一个 3 查询不到后才记录；第二个 3 再查 3，才能得到两个不同下标。若先插入当前元素再查，在第一个 3 处就可能错误地拿自己配自己。
//   不能只用 set，因为题目要返回下标；find() 表达纯查询，operator[] 用在真正要写入 indexOf[nums[i]]=i 的地方，二者语义不要混在一起。重复值覆盖旧下标没有问题：题目保证存在唯一答案，只要保留一个合法历史下标即可。
//   reserve() 只是减少 rehash 的性能细节，不参与正确性。
//
// 7. 举一反三
//   这一题最值得迁移的不是“Two Sum 就用哈希表”，而是一个更通用的优化动作：先看暴力算法在重复查什么；如果每次都在历史数据里寻找一个可直接算出的 key，就考虑为历史建立索引。
//   LC-560 会把 key 从“元素值”升级成“前缀状态”：当前 prefix 到历史里寻找 prefix-k。实现层再记住两个技巧：纯查询用 find()/contains()，有意创建或更新状态时再用 operator[]。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n target。
//   第 2 行：n 个以空格分隔的整数。
//   输出：两个下标，以空格分隔并升序排列。
// test.in 的预期输出：0 1
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> twoSum(vector<int>& nums, int target) {
        unordered_map<int, int> indexOf;  // 已扫描历史：value -> index
        indexOf.reserve(nums.size() * 2); // 仅减少扩容/rehash，不影响算法正确性

        for (int i = 0; i < static_cast<int>(nums.size()); ++i) {
            const int complement = target - nums[i];

            // 纯查询：只问“需要的补数以前出现过吗？”，不希望缺失 key 被自动创建。
            auto it = indexOf.find(complement);
            if (it != indexOf.end()) {
                return {it->second, i};
            }

            // 查询之后才把当前元素加入历史，保证后续命中时一定使用不同下标。
            indexOf[nums[i]] = i;
        }
        return {};  // 题目保证有唯一解；保留兜底使本地接口更健壮
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, target;
    if (!(cin >> n >> target)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto ans = sol.twoSum(a, target);
    for (size_t i = 0; i < ans.size(); ++i) cout << ans[i] << " \n"[i + 1 == ans.size()];
    return 0;
}
