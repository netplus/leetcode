// ============================================================================
// LC-239：滑动窗口最大值
// 难度：困难
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 7 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 nums，有一个大小为 k 的滑动窗口从数组的最左侧移动到数组的最右侧。
// 你只可以看到在滑动窗口内的 k 个数字。
// 滑动窗口每次只向右移动一位。
// 返回滑动窗口中的最大值。
//
// 题目示例：
// 示例 1：
//   Input: nums = [1,3,-1,-3,5,3,6,7], k = 3
//   Output: [3,3,5,5,6,7]
//   Explanation:
//   Window position Max
//   --------------- -----
//   [1 3 -1] -3 5 3 6 7 3
//   1 [3 -1 -3] 5 3 6 7 3
//   1 3 [-1 -3 5] 3 6 7 5
//   1 3 -1 [-3 5 3] 6 7 5
//   1 3 -1 -3 [5 3 6] 7 6
//   1 3 -1 -3 5 [3 6 7] 7
//
// 示例 2：
//   Input: nums = [1], k = 1
//   Output: [1]
//
// 约束与要求：
//   - 1 <= nums.length <= 10^5
//   - -10^4 <= nums[i] <= 10^4
//   - 1 <= k <= nums.length
//
// 复杂度目标：O(n) 时间（单调队列）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜单调队列：保存仍可能成为最大值的下标
//
// 0. 优化是怎么来的
//   最自然的做法是每滑动一个长度 k 的窗口，就重新扫描窗口里的 k 个数求最大值，时间 O(nk)。相邻两个窗口共享 k-1 个元素，这些最大值候选被一遍遍重复比较。
//
//   真正没必要保存的是“已经被新元素完全支配”的旧候选：若旧元素更小或相等，而且下标更早，那么只要新元素还在窗口里，旧元素就不可能成为最大值；等新元素离开时，旧元素反而更早已经过期。
//
//   因此窗口不再保存所有元素，只保存仍有资格成为未来最大值的候选，并额外从队首删除过期下标。
//
//   优化类型：重复扫描 + 候选被支配 -> 单调队列。每个下标只入队一次、出队一次，总复杂度 O(n)。
//
// 1. 图像直觉
//   先把窗口想成一个不断向右移动的观察框。真正的问题不是“窗口里有哪些数”，而是：
//
//   哪些数还有资格在未来某一刻成为最大值？
//
//   例如 nums = [1,3,-1,-3,5]，k = 3。
//
//   看到 1：
//   候选队列（存下标，对应值）：[1]
//
//   看到 3：
//   1 比 3 小，而且 1 还更早离开窗口。
//   只要 3 还在窗口里，1 永远不可能压过 3；等 3 离开时，1 早就先离开了。
//   所以 1 可以永久淘汰：
//   [1] -> [] -> [3]
//
//   看到 -1：
//   3 > -1，二者都保留：
//   [3, -1]
//   队首 3 就是当前窗口最大值。
//
//   后来看到 5：
//   队尾 -3、-1、3 都 <= 5，并且都比 5 更早过期，因此全部失去未来竞争资格：
//   [3,-1,-3] -> [] -> [5]
//
//   单调队列不是保存窗口本身，而是在保存一条“仍有机会成为最大值”的候选名单。
//
// 2. 一句话核心
//   新元素进入时，把队尾所有“更小且更早过期”的候选永久淘汰；队首始终是当前窗口中最强且仍未过期的最大值候选。
//
// 3. 公式 / 不变量
//   deque 存下标 i0,i1,...,im，并始终满足：
//
//   i0 < i1 < ... < im                  （时间顺序）
//   nums[i0] > nums[i1] > ... > nums[im] （值严格递减）
//
//   当前扫描位置为 i，窗口左边界为 i-k+1。
//
//   过期条件：
//   candidates.front() < i-k+1
//   等价于：
//   candidates.front() <= i-k
//
//   新元素 i 入队前：
//   while nums[candidates.back()] <= nums[i]:
//       pop_back()
//
//   窗口形成后：
//   max(window) = nums[candidates.front()]
//
//   核心支配关系：旧下标 j < i 且 nums[j] <= nums[i] 时，j 比 i 更小/相等，又更早过期，所以 j 永远不可能在 i 之前重新成为最大值。
//
// 4. 执行步骤
//   1. 扫描到下标 i 时，先从队首删除已经离开当前窗口的下标
//   2. 从队尾反复删除值 <= nums[i] 的旧候选，因为它们已经被更晚、更大的 nums[i] 支配
//   3. 把当前下标 i 压入队尾，此时队列重新保持下标递增、对应值严格递减
//   4. 当 i >= k-1，窗口已经形成，队首对应值就是这一窗的最大值
//   记忆：队首管过期，队尾管淘汰；更小又更老，就永远出局。
//
// 5. 为什么不会漏 / 不会重
//   队首为什么不会漏掉真正最大值：窗口内任何比队首更早的元素都已过期；任何仍在队首后面的候选值都更小，所以队首必为最大值。队尾删除为什么安全：若旧元素 j 被新元素 i 删除，则 nums[j] <= nums[i] 且 j<i；从此直到 j 过期前，i 都与 j 同窗且不小于 j，而 j 还会更早过期，因此 j 再也不可能成为窗口最大值。每个下标只入队一次，并且至多从队首或队尾删除一次，所以不会重复处理成 O(n^2)。
//
// 6. 边界与易错点
//   队列必须存下标而不能只存值，否则无法判断元素何时滑出窗口。重复值使用 <= 淘汰旧下标更自然：保留更晚的相同值可以活得更久；使用 < 也能设计正确版本，但队列会保留重复候选。窗口答案从 i==k-1 才开始输出。先处理过期还是先处理队尾支配都可以构造正确版本，但代码中的不变量要前后一致。
//
// 7. 举一反三
//   它和此前滑动窗口的区别很重要：LC-209/76/438 的 deque/指针是在维护“窗口是否合法”，LC-239 维护的是“窗口内部谁还有资格成为最优解”。这个“删掉被新状态完全支配的旧候选”会迁移到单调队列 DP、受长度限制的前缀最值，以及后续单调栈问题。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n k。
//   第 2 行：n 个以空格分隔的整数。
//   输出：n-k+1 个以空格分隔的窗口最大值。
// test.in 的预期输出：3 3 5 5 6 7
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> maxSlidingWindow(vector<int>& nums, int k) {
        deque<int> candidates;
        vector<int> answer;
        for (int i = 0; i < static_cast<int>(nums.size()); ++i) {
            if (!candidates.empty() && candidates.front() <= i - k) {
                candidates.pop_front();
            }
            while (!candidates.empty() && nums[candidates.back()] <= nums[i]) {
                candidates.pop_back();
            }
            candidates.push_back(i);
            if (i >= k - 1) answer.push_back(nums[candidates.front()]);
        }
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, k; if (!(cin >> n >> k)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto ans = sol.maxSlidingWindow(a, k);
    for (size_t i = 0; i < ans.size(); ++i) cout << ans[i] << " \n"[i + 1 == ans.size()];
    return 0;
}
