// ============================================================================
// LC-78：子集
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 2 周 / 第 13 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 nums，数组中的元素互不相同。
// 返回该数组所有可能的子集 （幂集）。
// 解集不能包含重复的子集。
// 你可以按任意顺序返回解集。
//
// 题目示例：
// 示例 1：
//   Input: nums = [1,2,3]
//   Output: [[],[1],[2],[1,2],[3],[1,3],[2,3],[1,2,3]]
//
// 示例 2：
//   Input: nums = [0]
//   Output: [[],[0]]
//
// 约束与要求：
//   - 1 <= nums.length <= 10
//   - -10 <= nums[i] <= 10
//   - nums 中的所有元素互不相同
//
// 复杂度目标：O(n * 2^n)。
//
// ----------------------------------------------------------------------------
// 解法精讲｜从题目直觉到可复用算法
//
// 1. 题目直觉 / 图形模型
//   对 [1,2,3]，每个元素只有两个语义：选或不选。
//
//                    []
//                /        ╲
//             不选1       选1
//              / ╲         / ╲
//           ...  ...     ...  ...
//
//   也可以规定只按下标递增地‘再加入一个元素’，这样每个节点当前 path 本身就是一个子集。
//
// 2. 最自然的一般性解法
//   从空集合开始，记录当前选择；然后只从当前下标之后选择下一个元素，加入后继续扩展。每个中间 path 都是合法答案，因此进入一层时就应记录，而不必等到叶子。
//
// 3. 一般解法的问题与限制
//   答案本身就有 2^n 个，不能把搜索规模降成多项式。真正要避免的是同一集合被不同顺序重复构造，例如 [1,2] 与 [2,1]；另外只在叶子记录会漏掉较短子集。
//
// 4. 从具体问题抽象规律
//   对‘顺序不重要’的集合型枚举，给元素规定唯一的递增选择顺序，就能让每个集合只对应一条构造路径。
//
// 5. 必要背景知识
//   子集（subset）只关心“选了哪些元素”，不关心这些元素的排列顺序。
//
//   例如 {1,2} 与 {2,1} 是同一个子集，不应输出两次。空集 {} 和全集 nums 本身也都是合法子集。
//
//   这正是 `start` 存在的原因：人为规定只按原下标递增选择，为每个子集保留唯一构造顺序。
//
// 6. 专项算法｜子集搜索：用 start 固定唯一选择顺序，每个搜索节点都是答案
//   前面的推理已经得到可复用机制；现在才给它一个检索名称：回溯：递增下标消除集合的顺序重复。通用机制见 docs/algorithms/backtracking.md。回到本题时，只需要把其中的状态、边界和更新事件映射到当前题意，不要反过来用模板猜题。
//
// 7. 核心算法
//   给每个子集规定“按原下标递增选择”的唯一写法；当前 path 一形成就是一个合法子集，然后只从 start 之后继续扩展。
//
// 8. 公式 / 不变量
//   状态：search(nums, start)
//
//   path 中对应的原下标严格递增。
//   下一元素只能选择：
//   i ∈ [start, n)
//   选择后递归：
//   search(nums, i + 1)
//
//   因此同一个下标不会重复使用，也不会回头形成不同顺序的同一子集。
//
//   答案数量：
//   每个元素独立有“选 / 不选”两种状态
//   => 子集总数 = 2^n。
//
//   当前递归树把这些 2^n 个子集分布在不同深度的节点上，所以：
//   进入每个 search 时都执行 answer.push_back(path)。
//
// 9. 执行步骤
//   1. 从 path=[]、start=0 开始；进入 search 后立即记录当前 path，所以空集首先被收集
//   2. 从 i=start 到 n-1 枚举下一个加入子集的元素；push nums[i] 后，path 仍按原下标递增
//   3. 递归传 i+1，明确当前元素以后不能再选，且更小下标永远不会回头进入这个分支
//   4. 子树探索完成后 pop 当前元素，恢复父 path，再枚举下一个可能的子集分支
//   记忆：子集不看顺序，就给它规定唯一顺序：只往右选；每走到一个节点就先收答案。
//
// 10. 为什么不会漏 / 不会重
//   任意子集都能把自己的元素按原数组下标升序写成唯一序列 i1<i2<...<ik；搜索从 start=0 可以依次选择 i1、i2...，所以不会漏。反过来，搜索路径的下标严格递增，因此一个元素不会重复出现；同一个下标集合也不可能用另一种顺序再次生成，所以不会重。空集对应根节点，非空子集对应唯一的非根搜索节点，因此在每层入口记录正好覆盖全部 2^n 个答案。
//
// 11. 边界与易错点
//   最容易把 LC-46 的“只在叶子记录”照搬过来，这会漏掉长度小于 n 的子集；本题每个 path 都合法，所以必须在进入每层时记录。递归必须传 i+1 而不是 start+1，也不能传 i（会重复使用同一个元素）。题目元素互异；若允许重复值，则还需要排序并在同一层跳过相同值。O(n·2^n) 中的 n 来自把每个 path 复制进答案，输出规模决定这部分成本无法省掉。
//
// 12. 举一反三
//   和 LC-46 对照最重要：排列关心顺序，所以每层都能从所有“未使用元素”中选；子集不关心顺序，所以用 start 强制下标递增，直接消除 [1,2]/[2,1] 这类重复表示。LC-39 会继续复用 start，但把 i+1 改成 i，从而表达“当前候选可以重复使用”。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：所有子集，每行一个且元素以空格分隔（空集输出空行）。
// test.in 的预期输出：<empty> | 1 | 2 | 1 2 | 3 | 1 3 | 2 3 | 1 2 3
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
    vector<vector<int>> answer;

    // path 是当前已经选中的子集；与排列不同，path 的任意长度都已经构成一个合法答案。
    vector<int> path;

    // start 规定下一步只能从哪个原数组下标开始选。
    // 因此 path 中元素对应的原下标始终严格递增，为每个“无序子集”建立唯一构造顺序。
    void search(const vector<int>& nums, int start) {
        // 当前搜索节点本身就是一个合法子集；根节点 path=[] 也会在这里收集为空集。
        answer.push_back(path);

        // 只允许从 start 向右枚举下一元素，不再回头选择更小下标。
        for (int i = start; i < static_cast<int>(nums.size()); ++i) {
            // 做选择后，下一层传 i+1：当前下标不能重复使用，也不会生成 [2,1] 这种同集合的另一顺序。
            path.push_back(nums[i]);
            search(nums, i + 1);

            // 子树探索完后撤销当前元素，恢复父节点对应的子集，再尝试下一个兄弟候选。
            path.pop_back();
        }
    }

public:
    vector<vector<int>> subsets(vector<int>& nums) {
        // 成员状态在每次公开调用前重置，保证同一个 Solution 对象可重复使用。
        answer.clear();
        path.clear();

        // start=0 表示根节点还没有排除任何候选；search 会先收集空集。
        search(nums, 0);
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto res = sol.subsets(a);
    for (auto& s : res) {
        for (size_t i = 0; i < s.size(); ++i) cout << s[i] << " \n"[i + 1 == s.size()];
        if (s.empty()) cout << "\n";
    }
    return 0;
}
