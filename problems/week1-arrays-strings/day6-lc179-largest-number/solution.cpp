// ============================================================================
// LC-179：最大数
// 难度：中等
// 优先级：P1（进阶）
// 学习进度：第 1 周 / 第 6 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一组非负整数 nums，重新排列每个数的顺序（每个数不可拆分）使之组成一个最大的整数。
// 注意：输出结果可能非常大，所以你需要返回一个字符串而不是整数。
//
// 题目示例：
// 示例 1：
//   Input: nums = [10,2]
//   Output: "210"
//
// 示例 2：
//   Input: nums = [3,30,34,5,9]
//   Output: "9534330"
//
// 约束与要求：
//   - 1 <= nums.length <= 100
//   - 0 <= nums[i] <= 10^9
//
// 复杂度目标：O(n log n * L)。
//
// ----------------------------------------------------------------------------
// 解法精讲｜拼接序的自定义排序
//
// 前置概念
//   C++ 字符串的 `>` 按字典序比较。对于长度相同、且都只含十进制数字的字符串，字典序大小与对应整数大小一致。
//
//   本题比较的 `a+b` 与 `b+a` 总长度一定相同，因此可以直接用字符串字典序决定哪个拼接结果数值更大。
//
//   例如 a="3", b="30"：
//   "330" > "303"，所以 3 应排在 30 前。
//
// 0. 优化是怎么来的
//   一个完全直接且正确的思路，是枚举所有排列、把每种排列拼成字符串后取最大；它说明了目标函数是什么，但排列数是 n!，无法实际使用。
//
//   观察任意相邻的两个元素 a、b：在其他前缀和后缀固定时，这两项只存在 ab 与 ba 两种局部顺序。如果 ab < ba，那么交换这两个相邻元素一定让整个结果变大；因此最优排列中不允许存在这种可改进的相邻逆序。
//
//   于是全局排列搜索可以压缩成一个两两比较规则：a 应排在 b 前面，当且仅当 a+b > b+a。排序负责系统地消除所有这类局部逆序。
//
//   优化类型：从全局排列目标推出局部交换准则 -> 自定义排序。
//
// 1. 图像直觉
//   这题不是问“哪个数字更大”，而是问“谁放前面能让最终拼接串更大”。
//
//   例如 3 和 30：
//
//   3 在前：  "3" + "30" = "330"
//   30 在前： "30" + "3" = "303"
//
//   330 > 303，所以排序时必须让 3 排在 30 前面。
//
//   再看 9 和 34：
//   9 在前：  "934"
//   34 在前： "349"
//   => 9 在前。
//
//   因此比较两个元素 a、b 时，真正参与比较的不是 a 和 b 本身，而是两个可能的局部拼接：
//
//   a+b  VS  b+a
//
//   哪一种更大，就采用哪一种相对顺序。排序完成后，所有相邻对都处于“更优拼接顺序”，顺次连接就是全局最大结果。
//
// 2. 一句话核心
//   从最终拼接目标反推排序规则：对任意 a、b，若 a+b > b+a，就让 a 排在 b 前面。
//
// 3. 公式 / 不变量
//   定义排序关系：
//   a ≺ b  当且仅当  a+b > b+a
//
//   这里 a、b 都是十进制字符串。
//
//   例如：
//   a="3", b="30"
//   "330" > "303"
//   => 3 应排在 30 前。
//
//   排序后结果：
//   answer = part[0] + part[1] + ... + part[n-1]
//
//   若 part[0] == "0"，因为 0 已经是排序后的最大首项，所以全部元素都只能是 0，答案规范化为 "0"。
//
// 4. 执行步骤
//   1. 把每个整数转成字符串，避免最终结果溢出整数范围
//   2. 排序时对两个字符串 a、b 比较 a+b 与 b+a，而不是比较数值大小或普通字典序
//   3. 若排序后的第一个字符串是 0，直接返回单个字符串 0
//   4. 否则按排序后的顺序依次拼接所有字符串
//   记忆：别问谁本身大；问 ab 和 ba 哪个大。
//
// 5. 为什么不会漏 / 不会重
//   考虑最终序列中任意相邻的 a、b。其他前缀和后缀保持不变时，这两个元素只有 ab 与 ba 两种局部排列；若 ab < ba，却仍让 a 在 b 前，那么交换它们会让整个结果字典序严格变大，因此原排列不可能最优。按 ab > ba 排序消除了所有这种可改进的相邻逆序；该比较关系具有排序所需的一致性，所以最终序列达到最大拼接结果。
//
// 6. 边界与易错点
//   不能直接按整数降序，也不能按字符串字典序降序，3 与 30 就是反例。比较器必须使用严格 >，相等时返回 false，满足 strict weak ordering。结果可能远超整数类型。全零输入若直接拼接会得到 000，应规范成 0。
//
// 7. 举一反三
//   这题训练的是“目标函数决定比较器”，而不是记住 a+b>b+a。若目标改成最小拼接数，只需把比较方向反过来；类似思想也出现在按字符串组合效果、自定义任务优先级排序的问题中。与前三题共同点是：都先通过排序重新组织问题，但前三题利用的是坐标单调性，这题利用的是交换后对目标值的直接影响。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：可拼接出的最大数字符串。
// test.in 的预期输出：210
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    string largestNumber(vector<int>& nums) {
        // 最终答案可能远超整数范围；先转成十进制字符串，后续只讨论“拼接顺序”。
        vector<string> parts;
        parts.reserve(nums.size());
        for (int value : nums) parts.push_back(to_string(value));

        sort(parts.begin(), parts.end(), [](const string& a, const string& b) {
            // 固定其它前后文时，a/b 只有 ab 与 ba 两种局部顺序。
            // 若 a+b 更大，就必须让 a 在 b 前，否则交换二者会让最终拼接结果变大。
            // 使用严格 > 很重要：当 a+b == b+a 时返回 false，满足 std::sort 的严格比较要求。
            return a + b > b + a;
        });

        // 排序后的 parts[0] 已经是最应该放在最前面的元素。
        // 若它仍为 "0"，说明没有任何非零字符串能排到 0 前面，因此所有输入都只能是 0；
        // 规范化返回单个 "0"，而不是 "000..."。
        if (parts[0] == "0") return "0";

        string answer;
        // 比较器已经确定了全局相对顺序；这里按该顺序直接拼接即可。
        for (const string& part : parts) answer += part;
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.largestNumber(a) << "\n";
    return 0;
}
