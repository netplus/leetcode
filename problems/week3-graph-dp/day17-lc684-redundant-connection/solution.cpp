// ============================================================================
// LC-684：冗余连接
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 3 周 / 第 17 天
// ----------------------------------------------------------------------------
// 题目描述：
// 树可以看成是一个连通且无环的无向图。
// 给定一个图，该图从一棵 n 个节点 (节点值 1～n ) 的树中添加一条边后获得。
// 添加的边的两个不同顶点编号在 1 到 n 中间，且这条附加的边不属于树中已存在的边。
// 图的信息记录于长度为 n 的二维数组 edges，edges[i] = [a_i, b_i] 表示图中在 ai 和 bi 之间存在一条边。
// 请找出一条可以删去的边，删除后可使得剩余部分是一个有着 n 个节点的树。
// 如果有多个答案，则返回数组 edges 中最后出现的那个。
//
// 约束与要求：
//   - n == edges.length
//   - 3 <= n <= 1000
//   - edges[i].length == 2
//   - 1 <= ai < bi <= edges.length
//   - ai != bi
//   - edges 中无重复元素
//   - 给定的图是连通的
//
// 复杂度目标：O(n * alpha(n)) 并查集。
//
// ----------------------------------------------------------------------------
// 解法精讲｜在线无向判环：加边前先问两端是否已经连通
//
// 0. 优化是怎么来的
//   一个自然且正确的在线算法是：维护目前已经加入的邻接表。处理新边 (u,v) 前，从 u 做一次 DFS/BFS；若能到 v，说明旧图中已有 u->...->v 路径，新边会成环；否则把新边加入图继续。
//
//   问题在于每来一条边都可能重新遍历大量已经看过的节点和边。我们并不关心那条旧路径具体经过谁，只关心一个二值事实：u、v 是否已经连通。
//
//   LC-547 的 DSU 正好把整个连通分量压缩成代表根：
//   - find(u) != find(v)：旧图不存在连接两端的路径，可以安全 union；
//   - find(u) == find(v)：旧图已经有路径，再加当前边必形成环。
//
//   优化类型：重复图搜索 -> 持久维护连通分量代表。每条边不再重新 DFS，变成少量 find/union，整体 O(n·alpha(n))。
//
// 1. 图像直觉
//   依次加入：
//
//   1 -- 2
//        |
//        3
//
//   此时：
//   find(1) == find(3)
//   因为旧边里已经有路径 1-2-3。
//
//   现在下一条边是：
//   1 -- 3
//
//   在真正 union 之前先问：
//   find(1) == find(3) ?
//   答案为 true。
//
//   这意味着：
//   旧路径 1 -> 2 -> 3
//   加上新边 3 -> 1
//   恰好闭成一个环。
//
//   因此“成环边”不是看当前边长什么样，而是看它加入前，两端是否已经属于同一连通分量。
//
// 2. 一句话核心
//   每条边加入前先比较两端代表根：同根说明旧图已有一条连接两端的路径，当前边就是闭环边；不同根才执行合并。
//
// 3. 公式 / 不变量
//   处理当前边 (u,v) 前：
//   ru = find(u)
//   rv = find(v)
//
//   若 ru == rv：
//   u、v 已经通过旧边连通
//   => 旧路径 + 当前边形成环
//   => 当前边冗余。
//
//   若 ru != rv：
//   旧图中 u、v 分属两个连通分量
//   => 加当前边不可能形成环
//   => parent[ru] = rv（或按 rank/size 合并）。
//
//   不变量：处理到第 i 条边之前，DSU 精确表示 edges[0..i-1] 的连通性。
//
// 4. 执行步骤
//   1. 建立 1..n 的 parent，并令每个节点初始自成集合
//   2. 按题目给定顺序扫描 edges；对当前边先分别 find 两端，而不是先 union
//   3. 若两个根相同，说明当前边会在已有路径上闭环，立即返回这条边
//   4. 若两个根不同，把两个集合合并，再继续处理下一条边
//   5. 题目保证由树额外加入一条边，因此一定能找到一条成环边
//   记忆：先问再合并：不同根 = 连接两个块；同根 = 旧路径已经存在，当前边闭环。
//
// 5. 为什么不会漏 / 不会重
//   在处理当前边前，由不变量可知同根等价于两端在此前边集合中已经存在路径。若同根，再加入当前无向边便得到一条闭合回路，因此它一定冗余；若不同根，当前边连接两个原本互不连通的分量，不可能产生环，合并后 DSU 又与新图连通性一致。因为原图来自树加一条边，第一次出现同根的当前边正是按照给定顺序完成唯一环的那条边，也满足题目要求的返回规则。
//
// 6. 边界与易错点
//   检查必须发生在 union 之前，否则任何边 union 后两端都会同根，判定失去意义。节点编号是 1..n，因此 parent 要开 n+1。这里 `parent[a]=b` 没有按大小合并，但路径压缩已经保证题目规模内性能满足要求；若做通用 DSU，可统一使用 rank/size。不要把有向图 LC-685 直接按本题处理，因为“每个非根节点恰有一个父亲”是额外约束。
//
// 7. 举一反三
//   LC-547 的 `components--` 关注“不同集合何时合并”；LC-684 关注恰好相反的事件——“本来已经同集合，却又来了一条连接”。Kruskal 最小生成树也完全复用这个判断：同根边跳过，不同根边才选入。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：m (边数，等于 n)。
//   接下来 m 行：u v。
//   输出：冗余边 "u v"。
// test.in 的预期输出：1 4
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> findRedundantConnection(vector<vector<int>>& edges) {
        // 节点编号是 1..n，因此下标 0 不参与算法，parent 需要开到 n+1。
        vector<int> parent(edges.size() + 1);
        iota(parent.begin(), parent.end(), 0);

        // find 返回当前连通分量代表根，并用路径压缩缩短后续查询链。
        function<int(int)> find = [&](int x) {
            return parent[x] == x ? x : parent[x] = find(parent[x]);
        };

        for (const auto& edge : edges) {
            // 一定要在把当前边加入 DSU 之前查询两端代表根。
            // 此时 a==b 等价于：仅靠此前已经处理的边，edge[0] 与 edge[1] 之间就已经存在路径。
            int a = find(edge[0]);
            int b = find(edge[1]);

            // 旧路径已经存在，再加入当前无向边就会闭合成环；当前边正是需要删除的冗余边。
            if (a == b) return edge;

            // 只有两端原本属于不同连通分量时才合并；这类边是在连接两个块，不会形成环。
            parent[a] = b;
        }

        // 题目保证输入由一棵树额外加入一条边得到，因此正常情况下不会走到这里。
        return {};
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int m; if (!(cin >> m)) return 0;
    vector<vector<int>> e(m, vector<int>(2));
    for (int i = 0; i < m; ++i) cin >> e[i][0] >> e[i][1];
    auto ans = sol.findRedundantConnection(e);
    cout << ans[0] << " " << ans[1] << "\n";
    return 0;
}
