def files_for(p: dict) -> dict[Path, str]:
    base = Path("problems") / "week2-list-tree-bsp" / f"day{p['day']}-lc{p['num']}-{p['name']}"
    files = {
        base / "solution.cpp": render_solution(p),
        base / "test.in": p["testin"],
        base / "Makefile": render_makefile(p),
        base / ".judge": p["judge"],
    }
    for i, (stdin, stdout) in enumerate(p["cases"], 1):
        files[base / "cases" / f"{i}.in"] = stdin
        files[base / "cases" / f"{i}.out"] = stdout
    return files


def all_files() -> dict[Path, str]:
    result: dict[Path, str] = {}
    for problem in SUPPLEMENTS:
        for path, content in files_for(problem).items():
            if path in result:
                raise RuntimeError(f"duplicate generated path: {path}")
            result[path] = content
    return result


def write_all() -> None:
    files = all_files()
    for relative, content in files.items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"Generated {len(SUPPLEMENTS)} exam-gap supplement(s), {len(files)} files.")


def check_all() -> None:
    errors = []
    files = all_files()
    for relative, expected in files.items():
        path = ROOT / relative
        if not path.exists():
            errors.append(f"missing {relative}")
        elif path.read_text(encoding="utf-8") != expected:
            errors.append(f"drift: {relative}")
    if errors:
        raise SystemExit("exam-gap fidelity failed:\n  - " + "\n  - ".join(errors))
    print(f"Exam-gap fidelity OK: {len(SUPPLEMENTS)} supplement(s), {len(files)} files.")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()
    if args.check:
        check_all()
    else:
        write_all()


if __name__ == "__main__":
    main()
