// ============================================================================
// LC-560：和为 K 的子数组
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 1 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 nums 和一个整数 k，请你统计并返回该数组中和为 k 的子数组的个数。
// 子数组是数组中元素的连续非空序列。
//
// 约束与要求：
//   - 1 <= nums.length <= 2 * 10^4
//   - -1000 <= nums[i] <= 1000
//   - -10^7 <= k <= 10^7
//
// 复杂度目标：O(n) 时间，O(n) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜前缀和 + 频次哈希表
//
// 1. 图像直觉
//   把两个前缀和画成两段累计长度：
//
//   |---------------- 当前 prefix ----------------|
//   |---------- 历史 prefix-k ----------|
//                                         ^
//                                 中间连续区间的和恰好为 k
//
//   所以并不是直接枚举子数组，而是在当前累计值下寻找一个合适的历史累计值。
//
// 2. 一句话核心
//   我现在累计到了 prefix，历史上有多少次累计到了 prefix-k？
//
// 3. 公式 / 不变量
//   当前累计 - 过去累计 = 中间连续区间的和
//   prefix - oldPrefix = k
//   oldPrefix = prefix - k
//
// 4. 执行步骤
//   1. frequency[0]=1，先记录“数组开始前”的空前缀
//   2. 扫描当前 value，执行 prefix += value，先算出“现在”累计到了多少
//   3. 用 find(prefix-k) 查询历史；若存在，把它的出现频次全部加入答案
//   4. 最后 ++frequency[prefix]，把当前 prefix 加入历史
//   记忆：先算现在 -> 再查过去 -> 最后把现在加入历史。
//
// 5. 为什么不会漏 / 不会重
//   每一个以当前位置结尾、和为 k 的连续子数组，都唯一对应一个它开始位置之前的历史前缀 oldPrefix=prefix-k；
//   同一个 prefix-k 如果出现多次，就代表多个不同起点，所以必须累加“频次”，而不是只判断存在。
//
// 6. 边界与易错点
//   frequency[0]=1 才能统计从下标 0 开始的区间；哈希表必须保存频次；查询 prefix-k 使用 find()，避免 operator[] 在纯查询时插入无意义的 0；
//   当前 prefix 必须在查询之后再加入历史；数组含负数时窗口和不具有单调性，普通滑动窗口不能替代本解法。
//
// 7. 举一反三
//   凡是“连续区间 + 指定累计差”，都可以尝试把区间条件改写成“当前前缀状态 - 历史前缀状态”。LC-1248 就是先把奇数映射成 1、偶数映射成 0，再原样复用本题。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n k。
//   第 2 行：n 个以空格分隔的整数。
//   输出：和等于 k 的连续子数组数量。
// test.in 的预期输出：2
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int subarraySum(vector<int>& nums, int k) {
        unordered_map<long long, int> frequency;
        frequency.reserve(nums.size() * 2 + 1);
        frequency[0] = 1;  // 空前缀：让从 0 开始的合法子数组也能被统计

        long long prefix = 0;
        int answer = 0;
        for (int value : nums) {
            prefix += value;
            auto it = frequency.find(prefix - k);  // 纯查询：不希望缺失 key 被自动插入
            if (it != frequency.end()) {
                answer += it->second;
            }
            ++frequency[prefix];                   // 记录现在：不存在时创建正是预期行为
        }
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, k;
    if (!(cin >> n >> k)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.subarraySum(a, k) << "\n";
    return 0;
}
