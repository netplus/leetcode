// ============================================================================
// LC-41：缺失的第一个正数
// 难度：困难
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 7 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个未排序的整数数组 nums，请你找出其中没有出现的最小的正整数。
// 请你实现时间复杂度为 O(n) 并且只使用常数级别额外空间的解决方案。
//
// 题目示例：
// 示例 1：
//   Input: nums = [1,2,0]
//   Output: 3
//   Explanation: The numbers in the range [1,2] are all in the array.
//
// 示例 2：
//   Input: nums = [3,4,-1,1]
//   Output: 2
//   Explanation: 1 is in the array but 2 is missing.
//
// 示例 3：
//   Input: nums = [7,8,9,11,12]
//   Output: 1
//   Explanation: The smallest positive integer 1 is missing.
//
// 约束与要求：
//   - 1 <= nums.length <= 10^5
//   - -2^31 <= nums[i] <= 2^31 - 1
//
// 复杂度目标：O(n) 时间，O(1) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜原地哈希：把值 x 放到下标 x-1
//
// 0. 优化是怎么来的
//   一个很自然的 O(n) 解法，是先把所有正整数放进 unordered_set，再从 1 开始查询第一个不存在的值；它已经满足时间目标，但需要 O(n) 额外空间。
//
//   题目进一步要求 O(1) 额外空间。关键观察是：长度为 n 的数组，答案只可能在 1..n+1；而值 x∈[1,n] 恰好可以映射到唯一槽位 x-1。既然数组本身就有 n 个槽位，就无需再额外建立哈希桶。
//
//   把每个合法值原地送到自己的槽位后，数组本身就变成了“值是否出现”的索引表。
//
//   优化类型：额外哈希表 -> 利用值域与下标的一一映射，把输入数组原地当作哈希表。
//
// 1. 图像直觉
//   先忽略题目的大整数范围，只问：长度为 n 的数组，最小缺失正数可能在哪里？
//
//   如果 1,2,...,n 全都出现了，答案就是 n+1；否则答案一定属于 1..n。
//
//   于是数组本身刚好有 n 个槽位，可以把它当成一张不用额外空间的哈希表：
//
//   值 1 应住下标 0
//   值 2 应住下标 1
//   值 3 应住下标 2
//   ...
//   值 x 应住下标 x-1
//
//   例如：[3,4,-1,1]
//
//   下标:  0  1  2  3
//   期望:  1  2  3  4
//   当前: [3, 4,-1, 1]
//
//   位置 0 的 3 应去位置 2：
//   [-1,4,3,1]
//
//   位置 1 的 4 应去位置 3：
//   [-1,1,3,4]
//   位置 1 现在是 1，又应去位置 0：
//   [1,-1,3,4]
//
//   最终扫描：位置 0 是 1，正确；位置 1 不是 2，所以 2 就是第一个缺失正数。
//   0、负数、>n 的值都没有合法“住址”，直接留在原处即可。
//
// 2. 一句话核心
//   答案只可能在 1..n+1；把每个出现过的 x∈[1,n] 原地送到唯一槽位 x-1，最后第一个槽位和值不匹配的位置就是答案。
//
// 3. 公式 / 不变量
//   n = nums.size()。
//
//   候选答案范围：
//   answer ∈ {1,2,...,n,n+1}
//
//   原地映射：
//   x ∈ [1,n]  <=>  home(x) = x-1
//
//   归位条件：
//   nums[x-1] == x
//
//   在位置 i 上，若当前 x=nums[i] 满足：
//   1 <= x <= n
//   且 nums[x-1] != x
//   则交换：swap(nums[i], nums[x-1])
//
//   最终：
//   第一个 nums[i] != i+1  =>  answer=i+1
//   若全部匹配             =>  answer=n+1
//
//   循环中的 nums[x-1] != x 是重复值保险：目标槽已经放着 x 时，不再交换。
//
// 4. 执行步骤
//   1. 令 n=nums.size()；遍历每个位置 i，把 nums[i] 看成一个可能需要搬家的值 x
//   2. 只要 x 落在 [1,n] 且自己的目标槽 x-1 还没有 x，就把 x 与目标槽中的值交换
//   3. 交换后不要立刻前进 i，因为换回来的新 nums[i] 也可能有自己的合法槽位；继续 while 归位
//   4. 所有位置处理后，从左到右寻找第一个 nums[i] != i+1，返回 i+1
//   5. 如果 1..n 全部归位，返回 n+1
//   记忆：1 住 0，2 住 1，x 住 x-1；先把住户送回家，再找第一个空错号。
//
// 5. 为什么不会漏 / 不会重
//   任何出现过的 x∈[1,n]，只要它尚未归位，扫描到承载它的位置时都会把它送向 x-1；交换回来的值继续在同一个 i 上处理，因此不会因为一次交换跳过新值。重复值不会死循环，因为如果 x 的目标槽已经是 x，条件立即停止。最终若 nums[i]!=i+1，说明值 i+1 没能占据它唯一的槽位，也就说明输入中不存在 i+1；而更小的槽位都已经匹配，所以它正是最小缺失正数。每次真正交换至少让一个合法值进入自己的最终槽位，最多只有 n 个槽位，因此总交换次数 O(n)。
//
// 6. 边界与易错点
//   最关键的不是 for，而是里面必须用 while：一次交换后当前位置可能又来了一个需要继续归位的合法值。重复值必须检查 nums[nums[i]-1] != nums[i]，否则 [1,1] 一类输入会无限交换。不要处理 <=0 或 >n 的值，它们与答案槽位无关。该算法会修改原数组，这是换取 O(1) 额外空间的代价。
//
// 7. 举一反三
//   这和 Day 2 的 move-zeroes 都是“让元素回到它应该占据的位置”，但 LC-283 的目标位置由扫描顺序动态决定，LC-41 则由值 x 直接决定 home=x-1。看到“值域大小与数组长度同阶 + 要求 O(1) 空间”的缺失/重复问题，应优先想到数组本身能否充当哈希桶。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：缺失的最小正整数。
// test.in 的预期输出：3
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int firstMissingPositive(vector<int>& nums) {
        const int n = static_cast<int>(nums.size());

        for (int i = 0; i < n; ++i) {
            // 只有 1..n 可能对应真实答案槽位；x 的唯一“家”是下标 x-1。
            // <=0 或 >n 的值不可能影响 1..n 哪个缺失，因此无需搬动。
            //
            // 第三个条件 nums[nums[i]-1] != nums[i] 是重复值保险：
            // 若目标槽已经放着同一个 x，继续 swap 只会在两个相同值之间来回，造成死循环。
            while (nums[i] >= 1 && nums[i] <= n && nums[nums[i] - 1] != nums[i]) {
                // 把当前合法值 x 送到唯一槽位 x-1。
                // 交换后当前位置 i 会换回来另一个值；它也可能属于 [1,n] 且尚未归位，
                // 所以这里必须继续 while，而不能一次 swap 后直接进入下一个 i。
                swap(nums[i], nums[nums[i] - 1]);
            }
        }

        // 归位结束后，若值 x 出现过，则它必然占据槽位 x-1。
        // 因此从左到右第一个 nums[i] != i+1 的位置，正好对应最小缺失正数 i+1。
        for (int i = 0; i < n; ++i) {
            if (nums[i] != i + 1) return i + 1;
        }

        // 1..n 全部出现时，最小缺失正数只能是 n+1。
        return n + 1;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.firstMissingPositive(a) << "\n";
    return 0;
}
