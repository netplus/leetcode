// ============================================================================
// LC-322：零钱兑换
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 3 周 / 第 20 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 coins，表示不同面额的硬币；以及一个整数 amount，表示总金额。
// 计算并返回可以凑成总金额所需的最少的硬币个数。
// 如果没有任何一种硬币组合能组成总金额，返回 -1。
// 你可以认为每种硬币的数量是无限的。
//
// 题目示例：
// 示例 1：
//   Input: coins = [1,2,5], amount = 11
//   Output: 3
//   Explanation: 11 = 5 + 5 + 1
//
// 示例 2：
//   Input: coins = [2], amount = 3
//   Output: -1
//
// 示例 3：
//   Input: coins = [1], amount = 0
//   Output: 0
//
// 约束与要求：
//   - 1 <= coins.length <= 12
//   - 1 <= coins[i] <= 2^31 - 1
//   - 0 <= amount <= 10^4
//
// 复杂度目标：O(n*amount) 时间（完全背包）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜完全背包最优化：从重复 remainder 子问题到金额 DP，并看清为何允许复用硬币
//
// 0. 优化是怎么来的
//   一个自然且正确的直接算法是 DFS：还剩 remainder 时，尝试每一种 coin<=remainder，递归求 remainder-coin 的最少硬币数，再取所有选择中的最小值。它枚举了所有可能的硬币序列，因此能找到最优答案。
//
//   浪费在于同一个 remainder 会从许多不同路径反复出现。例如 coins=[1,2,5] 时，金额 6 可以通过先选 1 再到 5，也可以先选 2 再经过其他金额；一旦递归落到 remainder=4，从那里到 0 的最少硬币数只由 4 决定，与此前选择顺序无关。直接 DFS 会重复求这些 remainder。
//
//   于是定义 dp[a]=凑出金额 a 的最少硬币数，让每个金额只求一次。固定一个目标金额 a，任何非空最优方案都可以按最后一枚硬币 coin 分类；拿掉它后得到金额 a-coin。如果那部分不是 dp[a-coin] 所代表的最优方案，用更优前缀替换后会让原方案更优，产生矛盾。因此：
//   dp[a] = min(dp[a-coin] + 1)。
//
//   这与 LC-416/494 有一个值得刻意比较的地方：那里每个数组下标只能使用一次，所以压缩后要避免同一轮读取刚更新的状态；这里每种硬币数量无限，读取由同一个 coin 反复参与得到的较小金额完全合法。当前实现按 amount 从小到大、每个 amount 枚举所有 coin，本质上就是按状态拓扑递增求解；它自然允许 coin 被使用任意次。
//
//   优化链：枚举硬币序列 -> 相同 remainder 被重复求解 -> 每个金额只保留一个最少硬币摘要 -> 枚举最后一枚硬币 -> 自底向上完全背包 / 金额 DP。
//
// 1. 图像直觉
//   coins=[1,2,5], amount=11。
//
//   把每个金额画成一个节点：
//   0 -> 1 -> 2 -> ... -> 11
//   每枚 coin 都提供一条“从 a-coin 跳到 a、代价 +1”的边。
//
//   例如计算 dp[6]：
//
//   最后用 1：dp[5] + 1
//   最后用 2：dp[4] + 1
//   最后用 5：dp[1] + 1
//
//   只要 dp[1]、dp[4]、dp[5] 已经是最优，dp[6] 取三者最小即可。
//
//   这里和 LC-416 的方向差异要从语义理解：
//   LC-416：一个 nums 下标只能拿一次，不能让当前 value 在本轮反复喂给自己。
//   LC-322：硬币面额只是‘类型’，同一面额本来就可以无限拿，因此从小金额继续扩到大金额完全合法。
//
//   当前代码按 current=1..amount 递增，所以 dp[current-coin] 一定已经求好。
//
// 2. 一句话核心
//   每个金额只保留“凑成它的最少硬币数”；枚举最优方案的最后一枚硬币，从已经求好的更小金额转移，而硬币无限供应允许同一面额反复参与。
//
// 3. 公式 / 不变量
//   状态：
//   dp[a] = 凑出金额 a 所需的最少硬币数。
//
//   基础：
//   dp[0] = 0
//   其余先设 INF = amount + 1。
//
//   转移：
//   dp[a] = min(dp[a], dp[a-coin] + 1), 其中 coin<=a。
//
//   当前实现顺序：
//   for a = 1 ... amount:
//       for coin in coins:
//           if coin <= a:
//               dp[a] = min(dp[a], dp[a-coin] + 1)
//
//   不变量：开始计算金额 a 时，所有 dp[0..a-1] 都已经是最终最优值；因此枚举最后一枚硬币后得到的 dp[a] 也是最终最优。
//
//   若 dp[amount] 仍为 amount+1，则无解。
//
// 4. 执行步骤
//   1. 建立 amount+1 个状态，把 dp[0] 设为 0，其余设为 amount+1；由于最小面额至少为 1，这个值严格大于任何可能的有效最少枚数，可安全充当 INF
//   2. 让 current 从 1 递增到 amount，保证所有 current-coin 都是已经求好的更小状态
//   3. 枚举每个 coin；只有 coin<=current 时，它才可能作为组成 current 的最后一枚硬币
//   4. 用 dp[current-coin]+1 尝试改善 dp[current]；这允许同一面额在不同层次重复出现，因为题目明确硬币数量无限
//   5. 最终若 dp[amount] 仍为 INF 返回 -1，否则返回该最小值；amount=0 会自然返回 dp[0]=0
//   记忆：金额递增，枚举最后一枚 coin；无限硬币允许重复读更小金额，不要把 0/1 背包的倒序口诀硬套进来。
//
// 5. 为什么不会漏 / 不会重
//   取任意金额 a 的最优方案，并看它最后一枚硬币 coin。删除 coin 后，剩余硬币必然组成 a-coin；如果该剩余方案不是最少枚数 dp[a-coin]，就可以换成更少硬币的方案，再把 coin 放回，从而得到比原最优方案更好的解，矛盾。因此某个最优答案一定出现在 dp[a-coin]+1 的枚举中。反过来，每个被枚举的 coin 与一个可达的 a-coin 方案组合后都确实组成 a，所以转移不会制造非法解。
//
// 6. 边界与易错点
//   不要把 LC-416 的‘容量必须倒序’机械搬过来：那条规则来自“每个输入元素最多一次”，而这里同一面额可无限使用。当前金额优先的双循环求的是最少枚数，顺序不会改变最优值；若将来改成方案计数，则‘硬币在外还是金额在外’会影响统计组合还是排列，不能照抄。amount=0 应返回 0，无解要把 INF 转成 -1。
//
// 7. 举一反三
//   和 LC-416/494 对照学习最有效：三题都在一个一维容量轴上做 DP，但 416 的值是 bool、494 的值是 count、322 的值是 min；同时 416/494 的输入下标只能用一次，而 322 的硬币类型可无限复用。先问‘状态值聚合什么’和‘物品能用几次’，再决定 OR/+ /min 以及遍历方向。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n amount。
//   第 2 行：n 个以空格分隔的硬币面额。
//   输出：最少硬币数；无法凑出时输出 -1。
// test.in 的预期输出：3
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int coinChange(vector<int>& coins, int amount) {
        // amount+1 是安全的“不可能”哨兵：若 amount 可由正面额硬币组成，
        // 最差也只需 amount 枚面额 1 的硬币，因此任何有效最少枚数都不会达到 amount+1。
        vector<int> dp(amount + 1, amount + 1);

        // 凑出金额 0 不需要任何硬币，这是所有正金额转移的唯一基础可达状态。
        dp[0] = 0;

        // 金额从小到大，保证处理 current 时所有 current-coin 都是已经求好的更小金额状态。
        for (int current = 1; current <= amount; ++current) {
            for (int coin : coins) {
                // 把 coin 看作最优方案的最后一枚硬币：若 coin<=current，
                // 候选就是“凑出 current-coin 的最少枚数 + 当前这一枚”。
                // 同一面额可以无限使用，所以 dp[current-coin] 即使已经包含 coin 也完全合法；
                // 这正是与 LC-416/494 的 0/1 倒序语义不同之处。
                if (coin <= current) dp[current] = min(dp[current], dp[current - coin] + 1);
            }
        }

        // 哨兵未被改善说明 amount 不可达；否则 dp[amount] 就是最少硬币枚数。
        return dp[amount] == amount + 1 ? -1 : dp[amount];
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, amount; if (!(cin >> n >> amount)) return 0;
    vector<int> c(n);
    for (int i = 0; i < n; ++i) cin >> c[i];
    cout << sol.coinChange(c, amount) << "\n";
    return 0;
}
