// ============================================================================
// LC-252：会议室
// 难度：简单
// 优先级：P1（进阶）
// 学习进度：第 1 周 / 第 6 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一组会议时间区间 intervals，判断一个人能否参加全部会议。
// 本地适配器把会议表示为半开区间 [start, end)；两个区间有时间重叠时，无法同时参加。
//
// 题目示例：
// 示例 1：
//   Input: intervals = [[0,30],[5,10],[15,20]]
//   Output: false
//   Explanation: The meetings [0,30] and [5,10] overlap, so one person cannot attend all meetings.
//
// 示例 2：
//   Input: intervals = [[7,10],[2,4]]
//   Output: true
//   Explanation: The two meetings do not overlap.
//
// 约束与要求：
//   - 0 <= intervals.length <= 10^4
//   - intervals[i].length == 2
//   - 0 <= start < end <= 10^6
//
// 复杂度目标：O(m log m) 时间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜按开始时间排序检测相邻冲突
//
// 前置概念
//   半开区间 [start,end) 包含 start，但不包含 end。
//
//   例如 [1,3) 表示从 1 开始、到 3 之前结束；[1,3) 与 [3,5) 不重叠，因为前一段在 3 这个时刻已经结束。
//
//   因此会议恰好在上一场结束时开始是允许的：
//   previous.end == current.start 仍然不冲突。
//   这直接决定代码使用 `current.start < previous.end` 判断冲突，而不是 `<=`。
//
// 0. 优化是怎么来的
//   没有排序时，最直接的判断方法是比较每一对会议区间是否重叠，时间 O(m^2)。这很自然，因为任意两场会议看起来都可能冲突。
//
//   排序真正省掉的是“大量远距离区间对的比较”。按 start 排序后，如果当前会议和紧邻的前一场都不冲突，那么更早的会议不可能越过这条已经按时间排好的边界来制造新的冲突；潜在冲突被压缩到相邻边界。
//
//   于是全局的“两两关系”先通过排序获得单调顺序，再退化成一次线性相邻检查。
//
//   优化类型：无序全局比较 -> 排序制造单调性，把 O(m^2) 的任意两两检查压缩为 O(m log m) 排序 + O(m) 扫描。
//
// 1. 图像直觉
//   先不要急着比较所有会议对。把会议按开始时间排成一条时间线：
//
//   原来： [5,8)  [0,4)  [3,6)
//   排序： [0,4)  [3,6)  [5,8)
//              ^      ^
//
//   排序之后，最先可能发生的冲突一定出现在相邻会议之间。
//
//   为什么？看当前会议 [3,6)：它前面的会议开始得都更早。如果紧挨着它的前一场都已经在 3 之前结束，那么更早的会议也不可能越过它；反过来，只要 previous.end > current.start，相邻两场已经直接冲突。
//
//   因此排序做了一件很重要的事：把“任意两场会议是否冲突”的全局问题，压缩成“相邻两场是否冲突”的局部检查。
//
// 2. 一句话核心
//   先按开始时间排序，让所有潜在冲突沿时间线排好；随后只检查相邻会议是否满足 previous.end <= current.start。
//
// 3. 公式 / 不变量
//   排序后：
//   start[0] <= start[1] <= ... <= start[n-1]
//
//   半开区间 [start,end) 下，相邻会议 i-1 与 i 不冲突当且仅当：
//   end[i-1] <= start[i]
//
//   只要存在：
//   start[i] < end[i-1]
//   就可以立即判定有冲突。
//
// 4. 执行步骤
//   1. 按会议开始时间排序；vector 的字典序排序同时把结束时间作为次关键字，但这里不影响结论
//   2. 从第二场会议开始，只比较当前 start 与前一场 end
//   3. 若 current.start < previous.end，立即返回 false
//   4. 全部相邻对都通过，则返回 true
//   记忆：先排时间线，再看相邻边界；start < previous.end 就撞车。
//
// 5. 为什么不会漏 / 不会重
//   若所有相邻会议都满足 end[i-1] <= start[i]，那么第 i 场开始时第 i-1 场已经结束；由于更早会议又依次不晚于它们后面的会议结束，整条时间线不存在交叠。若存在任何冲突，把参与冲突且开始时间更晚的那场记为 i；沿排序后的前驱向前看，至少会出现一个尚未在 start[i] 前结束的相邻边界，因此冲突不会被漏掉。
//
// 6. 边界与易错点
//   本仓库把会议按半开区间 [start,end) 理解，所以一场在 10 结束、下一场在 10 开始不冲突，判断必须是 current.start < previous.end，而不是 <=。空数组或只有一场会议自然返回 true；排序会修改输入顺序。
//
// 7. 举一反三
//   这是 Day 6 的区间母模型：排序把全局关系变成局部关系。LC-56 不再只问“有没有冲突”，而是遇到重叠时把相邻区间合成一个更大的当前区间；LC-57 则进一步利用输入本来就有序，连排序步骤都可以省掉。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：m (区间数量)。
//   接下来 m 行：start end。
//   输出：能参加全部会议（无重叠）时输出 1，否则输出 0。
// test.in 的预期输出：0
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    bool canAttendMeetings(vector<vector<int>>& intervals) {
        sort(intervals.begin(), intervals.end());
        for (int i = 1; i < static_cast<int>(intervals.size()); ++i) {
            if (intervals[i][0] < intervals[i - 1][1]) return false;
        }
        return true;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int m; if (!(cin >> m)) return 0;
    vector<vector<int>> iv(m, vector<int>(2));
    for (int i = 0; i < m; ++i) cin >> iv[i][0] >> iv[i][1];
    cout << (sol.canAttendMeetings(iv) ? 1 : 0) << "\n";
    return 0;
}
