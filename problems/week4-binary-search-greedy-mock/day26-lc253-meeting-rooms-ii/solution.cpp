// ============================================================================
// LC-253：会议室 II
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 4 周 / 第 26 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一组会议时间区间 intervals，返回为了安排所有会议至少需要的会议室数量。
// 本地适配器使用半开区间 [start, end)：一场会议在另一场开始时结束，可以复用同一间会议室。
//
// 约束与要求：
//   - 0 <= intervals.length <= 10^4
//   - intervals[i].length == 2
//   - 0 <= start < end <= 10^6
//
// 复杂度目标：O(m log m) 时间（sweep line / heap）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜时间线资源复用：按开始时间扫描 + 最早结束时间堆
//
// 0. 优化是怎么来的
//   一个直接正确的做法是先按开始时间排序；处理每场会议时，扫描此前所有会议，重新判断哪些仍与当前会议重叠，再计算当前同时进行的会议数。它不会算错，但每到一个新开始时间都重复检查大量已经处理过的会议，最坏 O(m^2)。
//
//   观察一场旧会议一旦满足 end <= currentStart，它不仅对当前会议已经结束，对以后开始得更晚的所有会议也永久结束，再也没有保留价值。反过来，仍活跃的会议只需要记住 end；下一批能被淘汰的一定是 end 最小者。于是把“反复扫描历史会议”改成“最小堆维护仍活跃的结束时间”：不断弹出所有 end <= currentStart，再加入当前 end。优化类型：状态可延续 + 永久失效候选淘汰。
//
// 1. 图像直觉
//   会议按 start 排序：
//   A: [0,30)
//   B: [5,10)
//   C: [15,20)
//
//   处理 A：heap=[30]                 活跃 1
//   处理 B：5 < 30，heap=[10,30]      活跃 2
//   处理 C：先弹 10，因为 10 <= 15
//           heap=[30] -> push 20
//           heap=[20,30]               活跃 2
//
//   堆里不是“所有历史会议”，而只是此刻仍占房间的会议结束时间。
//
// 2. 一句话核心
//   按开始时间推进时间线，永久删除已经结束的会议；堆大小就是当前占用的房间数，历史最大堆大小就是最少所需房间数。
//
// 3. 公式 / 不变量
//   处理当前会议 [start,end) 前：
//   while heap.top() <= start:
//       pop()
//
//   push(end)
//   active = heap.size()
//   answer = max(answer, active)
//
//   不变量：push 当前会议之后，heap 中恰好保存所有已经开始但尚未结束的会议的 end。
//   半开区间 [start,end) 下，end == start 时两场会议不重叠，所以可以复用房间。
//
// 4. 执行步骤
//   1. 按 start 升序排序会议，使后续开始时间只会向右移动
//   2. 处理当前会议前，反复弹出 end<=currentStart 的堆顶，因为这些会议从现在起永久失效
//   3. 把当前会议的 end 压入最小堆，表示它开始占用一个房间
//   4. 用堆大小更新历史最大同时占用数 best，最终返回 best
//   记忆：时间向右走；结束过的永不回头，堆里只留还占房的会议。
//
// 5. 为什么不会漏 / 不会重
//   开始时间单调递增，所以一旦某会议 end<=currentStart，它也必然在所有未来会议开始前结束，可以永久删除。删除完后，堆中每个 end 都大于 currentStart，对应一场与当前时刻重叠的已开始会议；加入当前会议后，堆大小正好等于此刻同时占用的房间数。任何时刻同时进行 r 场会议至少需要 r 间房，而按最早释放资源复用恰能用这么多房间，因此全程最大活跃数就是最优答案。
//
// 6. 边界与易错点
//   结束等于下一场开始时可复用，所以条件必须是 <= 而不是 <。要弹出所有已结束会议，不是只弹一个。空输入返回 0。排序会修改 intervals。LC-253 在仓库中使用半开区间语义，解释和实现必须一致。
//
// 7. 举一反三
//   直接复用 Day 25 的“只维护未来仍有资格的 frontier”：LC-23 的堆顶是多个有序来源的下一个值，这里堆顶是多个占用资源里最早释放者。机器调度、连接池容量、并发请求峰值都可用同一时间线模型；若只求峰值，也可改成 start/end 事件扫描。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：m (区间数量)。
//   接下来 m 行：start end。
//   输出：最少会议室数量。
// test.in 的预期输出：2
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int minMeetingRooms(vector<vector<int>>& intervals) {
        sort(intervals.begin(), intervals.end());
        priority_queue<int, vector<int>, greater<int>> endTimes;
        int best = 0;
        for (const auto& meeting : intervals) {
            while (!endTimes.empty() && endTimes.top() <= meeting[0]) endTimes.pop();
            endTimes.push(meeting[1]);
            best = max(best, static_cast<int>(endTimes.size()));
        }
        return best;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int m; if (!(cin >> m)) return 0;
    vector<vector<int>> iv(m, vector<int>(2));
    for (int i = 0; i < m; ++i) cin >> iv[i][0] >> iv[i][1];
    cout << sol.minMeetingRooms(iv) << "\n";
    return 0;
}
