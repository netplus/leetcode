// ============================================================================
// LC-39：组合总和
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 2 周 / 第 13 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个无重复元素的整数数组 candidates 和一个目标整数 target，找出 candidates 中可以使数字和为目标数 target 的所有不同组合，并以列表形式返回。
// 你可以按任意顺序返回这些组合。
// candidates 中的同一个数字可以无限制重复被选取。
// 如果至少一个数字的被选数量不同，则两种组合是不同的。
// 对于给定的输入，保证和为 target 的不同组合数少于 150 个。
//
// 题目示例：
// 示例 1：
//   Input: candidates = [2,3,6,7], target = 7
//   Output: [[2,2,3],[7]]
//   Explanation:
//   2 and 3 are candidates, and 2 + 2 + 3 = 7. Note that 2 can be used multiple times.
//   7 is a candidate, and 7 = 7.
//   These are the only two combinations.
//
// 示例 2：
//   Input: candidates = [2,3,5], target = 8
//   Output: [[2,2,2,2],[2,3,3],[3,5]]
//
// 示例 3：
//   Input: candidates = [2], target = 1
//   Output: []
//
// 约束与要求：
//   - 1 <= candidates.length <= 30
//   - 2 <= candidates[i] <= 40
//   - candidates 的所有元素互不相同
//   - 1 <= target <= 40
//
// 复杂度目标：O(2^(target/min)) 时间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜从题目直觉到可复用算法
//
// 1. 题目直觉 / 图形模型
//   先确认什么才算不同答案，不急着写递归参数。
//
//   candidates = [2,3,6,7], target = 7
//
//   2 + 2 + 3 = 7
//   2 + 3 + 2 = 7   <- 这三行使用的数字及各自数量完全相同
//   3 + 2 + 2 = 7      因而只能输出一个组合 [2,2,3]
//   7         = 7   <- 使用数量不同，是另一个组合 [7]
//
//   题目允许重复使用同一个数，但不把选择顺序算作区别。
//   我们必须既找到所有合法组合，又保证每个组合只输出一次。
//   这两个要求要分别证明，不能把“搜索能到达目标”当成完整解法。
//
// 2. 最自然的一般性解法
//   先允许所有选择顺序，把去重放到结果端：
//
//   result = 一个保存整数序列的有序集合
//   枚举(当前路径, 剩余金额):
//       如果剩余金额为 0:
//           将当前路径的副本排序，插入 result
//           返回
//       对每个候选 x:
//           如果 x <= 剩余金额:
//               选择 x，递归枚举剩余金额-x，返回后撤销 x
//   最后把 result 转成答案列表。
//
//   这是真正正确的基线：任意合法组合至少有一条选择序列会被枚举；
//   同一组合的不同顺序排序后得到同一个序列键，由集合保证只输出一次。
//   排序的是路径副本，不能破坏正在回溯的原路径。
//
//   设 n 为候选数，D=floor(target/最小候选值)。候选全为正，所以剩余金额
//   严格下降，递归深度不超过 D。每层至多 n 个分支，最坏搜索树随深度
//   指数增长。若实际访问 V 个节点、得到 S 条成功序列、去重后有 K 个组合，
//   使用有序集合的保守时间上界为
//   O(n*V + S*D*(log(D+1)+log(K+1)))，包含候选检查、排序和序列查重；
//   路径与递归栈 O(D)，保存结果至多 O(K*D)。
//   这个实现适合建立正确性，不适合作为大规模输入的最终写法。
//
// 3. 一般解法的问题与限制
//   第一种重复工作发生在生成阶段：
//   [2,2,3]、[2,3,2]、[3,2,2] 三条成功路径，最终只留下一个组合。
//   集合保证了输出正确，却没有省掉枚举、排序和比较这些重复表示的代价。
//
//   第二种工作发生在候选检查阶段：基线已经跳过超过剩余金额的候选，
//   不会递归进入负数，但每层仍要逐个检查所有候选是否过大。
//   若候选按值排序，第一个过大值就足以排除其右侧整段。
//
//   这两项改进分别解决“不同顺序的重复表示”和“过大候选的重复检查”，
//   不能用一句“回溯剪枝”把原因混在一起。
//
// 4. 从具体问题抽象规律
//   先把结果端的统一表示，提前变成生成时的规则。
//
//   给候选固定一种下标顺序，只允许后续选择的下标不小于此前下标。
//   任意组合都能按该顺序排列，因此不会漏；候选值互不相同，所以同一组
//   使用数量只有这一条下标不减的路径，因此不会重。这样不再需要结果集合。
//
//   现在才引入 start：它表示后续最小允许下标，而不是“第几层”。
//   选择下标 i 后仍传 i，表示可以再次用它；传 i+1 则禁止再次使用这个输入元素。
//   数值排序并非去除顺序重复的必要条件；固定输入下标顺序已经足够。
//   当前实现还按值排序，是为了让过大候选可以整段 break。
//
//   状态为什么不能只剩 remaining？对于 candidates=[2,3,5]、target=10，
//   路径 [2,2,2] 和 [3,3] 都剩 4，但前者还允许用 2，后者已经不能回头用 2。
//   因此后续选择至少需要 (start, remaining)；path 则保存最终要输出的前缀。
//   不同前缀即使到达同一后续子问题，也不能被一个全局 visited 直接丢掉，
//   否则枚举结果可能漏掉不同组合；复用后缀计算与删除有效答案不是一回事。
//
// 5. 必要背景知识
//   组合（combination）与排列的关键区别是：组合不关心选择顺序。
//
//   例如 target=7 时，[2,2,3]、[2,3,2]、[3,2,2] 表示同一个组合，只能输出一次。
//
//   本题还额外允许同一个 candidate 被无限次重复使用，所以“顺序不重要”与“元素可重复使用”是两个独立规则。`start` 负责消除不同顺序的重复表示，而递归继续传 i（不是 i+1）负责允许再次选择当前值。
//
// 6. 专项算法｜组合回溯：先规定唯一构造顺序，再用正数与排序剪掉无效后缀
//   到这里才需要给这套规律命名：本题对应“组合回溯：先规定唯一构造顺序，再用正数与排序剪掉无效后缀”。通用机制见 docs/algorithms/backtracking.md；回到本题时只保留与当前题意直接相关的状态、边界和更新顺序。
//
// 7. 核心算法
//   把上面的规则落实为“选择、递归、撤销”：
//
//   已排序 candidates=[2,3,6,7]，初始 path=[]、remaining=7、start=0。
//   选择 2：path=[2]，剩 5，下次仍从 0 开始；
//   再选 2：path=[2,2]，剩 3，下次仍从 0 开始；
//   再选 3：path=[2,2,3]，剩 0，复制当前路径到答案。
//   回溯时撤销刚选的数，才能让兄弟分支从同一个父状态出发。
//
//   若先选到 3，start 就至少为 1，后续不能回到下标 0 的 2；
//   所以 [3,2,2] 不会生成，但其唯一代表 [2,2,3] 已经保留。
//   候选已排序且为正，当前值超过 remaining 时，右侧更大值也不可能成功，
//   所以直接结束本层，而不是结束整个搜索。
//
// 8. 公式 / 不变量
//   状态：search(candidates, start, remaining)
//
//   path 的候选下标单调不减。
//
//   成功条件：
//   remaining == 0  => 记录 path
//
//   本层候选：
//   i ∈ [start, n)
//
//   选择 candidates[i] 后：
//   remaining' = remaining - candidates[i]
//   start'     = i        // 不是 i+1：允许再次使用当前候选
//
//   因为 candidates 已升序且全部为正：
//   candidates[i] > remaining
//   => 对任意 j>=i，candidates[j] >= candidates[i] > remaining
//   => 当前及右侧候选全部不可能成功，直接 break。
//
// 9. 执行步骤
//   1. 先排序 candidates；排序既建立组合的统一非降序表示，也让“过大后 break”成为合法剪枝
//   2. 从 start 开始枚举候选 i；若 candidates[i]>remaining，利用排序证明后续更大候选也都失败，停止本层
//   3. 把 candidates[i] push 进 path，并递归 search(candidates, i, remaining-candidates[i])；仍传 i 表示该值可以重复使用
//   4. remaining==0 时复制当前 path 作为一个完整组合并返回；递归回来后 pop，恢复父状态
//   记忆：组合先规定唯一顺序；可复用传 i，只用一次传 i+1；排序后大于 remaining 就整段停。
//
// 10. 为什么不会漏 / 不会重
//   不会漏：任意合法组合都可以按 candidates 排序后的下标非降序排列；搜索允许从 start 选择当前或更右候选，并且选择 i 后仍可继续选择 i，因此这条规范路径一定存在。不会重：每条生成路径的候选下标都不减，同一个多重集合只有这一种非降序排列，所以不会产生不同顺序的重复答案。剪枝也安全：候选均为正且排序后，当前值已经大于 remaining 时，右边更大的值只会让剩余量更小，不可能恰好归零。
//
// 11. 边界与易错点
//   允许重复使用当前候选，所以递归必须传 i；若误传 i+1，就变成“每个元素最多一次”的另一类组合题。`break` 依赖排序，若不排序只能 continue/继续检查其他候选。当前实现会原地 sort(candidates)，这是可观察副作用；LeetCode 接口允许，但工程调用方若要求保留输入顺序应排序副本。题目保证候选互异且为正；若有重复候选值需要额外同层去重，若允许非正数则 remaining 严格下降和当前剪枝都不再成立。
//
// 12. 举一反三
//   先独立回答，再用反例检查规则是否真的理解：
//
//   1. 只改成“每个输入元素最多使用一次”，该改哪个参数？
//      递归改传 i+1。[2,3]、target=7 在原题有 [2,2,3]，修改后无解。
//   2. 候选不按值排序还能去重吗？
//      能，固定下标不减仍是唯一表示；但过大时应 continue，不能直接 break。
//      [7,2,3]、target=4 可作为反例：一开始对 7 执行 break 会漏掉 [2,2]。
//   3. 输入允许重复值会怎样？
//      相同值可来自不同下标，“值组合只有一条下标路径”的证明失效，需另行去重；
//      不能只把 i 改成 i+1 就宣称完成 LC40 的迁移。
//   4. 只求组合数量时呢？
//      可以不保存完整 path，但必须保持组合的统计口径；重复子问题的计算可以复用，
//      不同有效组合对总数的贡献仍要累计。这是连接 LC518 的关键问题。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n target。
//   第 2 行：n 个以空格分隔的候选数。
//   输出：所有组合，每行一个且元素以空格分隔。
// test.in 的预期输出：2 2 3 | 7
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
    vector<vector<int>> answer;
    vector<int> path;

    // start 让 path 中使用的候选下标保持不减，给“组合”规定唯一的非降序构造顺序；
    // remaining 表示当前路径距离 target 还差多少。
    void search(const vector<int>& candidates, int start, int remaining) {
        // remaining 恰好归零时，当前 path 才是一组完整答案；所有候选为正数，所以之后无需继续扩展。
        if (remaining == 0) {
            answer.push_back(path);
            return;
        }

        for (int i = start; i < static_cast<int>(candidates.size()); ++i) {
            // candidates 已升序；若当前值都超过 remaining，右侧候选只会更大，
            // 且所有数为正，不可能靠继续选择把 remaining 拉回 0，因此可直接停止本层。
            if (candidates[i] > remaining) break;

            path.push_back(candidates[i]);

            // 与 LC-78 的 i+1 不同：本题允许同一候选无限复用，所以递归仍传 i；
            // 但不会传更小下标，从而不会生成 [2,3,2] 这类同一组合的另一排列。
            search(candidates, i, remaining - candidates[i]);

            // 当前候选对应的整棵子树探索完后撤销，恢复父状态再尝试下一个候选。
            path.pop_back();
        }
    }

public:
    vector<vector<int>> combinationSum(vector<int>& candidates, int target) {
        // 排序有两个作用：建立组合的统一非降序表示，并使“过大就 break”的剪枝有单调性依据。
        // 这会原地改变调用方传入的 candidates 顺序，是当前实现可观察的副作用。
        sort(candidates.begin(), candidates.end());

        answer.clear();
        path.clear();
        search(candidates, 0, target);
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, target; if (!(cin >> n >> target)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto res = sol.combinationSum(a, target);
    for (auto& c : res) {
        for (size_t i = 0; i < c.size(); ++i) cout << c[i] << " \n"[i + 1 == c.size()];
    }
    return 0;
}
