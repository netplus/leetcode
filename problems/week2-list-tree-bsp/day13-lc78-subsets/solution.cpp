// ============================================================================
// LC-78：子集
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 2 周 / 第 13 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 nums，数组中的元素互不相同。
// 返回该数组所有可能的子集 （幂集）。
// 解集不能包含重复的子集。
// 你可以按任意顺序返回解集。
//
// 约束与要求：
//   - 1 <= nums.length <= 10
//   - -10 <= nums[i] <= 10
//   - nums 中的所有元素互不相同
//
// 复杂度目标：O(n * 2^n)。
//
// ----------------------------------------------------------------------------
// 解法精讲｜子集搜索：用 start 固定唯一选择顺序，每个搜索节点都是答案
//
// 前置概念
//   子集（subset）只关心“选了哪些元素”，不关心这些元素的排列顺序。
//
//   例如 {1,2} 与 {2,1} 是同一个子集，不应输出两次。空集 {} 和全集 nums 本身也都是合法子集。
//
//   这正是 `start` 存在的原因：人为规定只按原下标递增选择，为每个子集保留唯一构造顺序。
//
// 1. 图像直觉
//   最自然的想法是：每个元素只有“选 / 不选”两种决定，所以共有 2^n 个子集。
//   当前实现把这棵二叉决策树改写成“枚举下一个还想加入谁”：
//
//                    []          <- 空集也是答案
//                 /   |   \
//               [1]  [2]  [3]    <- 都是答案
//              /  \    |
//          [1,2] [1,3] [2,3]     <- 都是答案
//             |
//         [1,2,3]                 <- 也是答案
//
//   子集不关心顺序，所以给每个子集规定唯一写法：只允许按原数组下标递增选择。
//   选了下标 i 后，下一层从 i+1 开始；于是 {1,2} 只会生成 [1,2]，不会再生成 [2,1]。
//   与 LC-46 不同，这里当前 path 一形成就已经是一个合法子集，所以每个搜索节点都要记录。
//
// 2. 一句话核心
//   给每个子集规定“按原下标递增选择”的唯一写法；当前 path 一形成就是合法子集，然后只从 start 之后继续扩展。
//
// 3. 公式 / 不变量
//   状态：search(nums, start)
//   path 中对应的原下标严格递增。
//
//   下一元素只能选择 i ∈ [start,n)，选择后递归 search(nums,i+1)。
//   因此同一个下标不会重复使用，也不会回头形成不同顺序的同一子集。
//
//   每个元素独立有“选 / 不选”两种状态，所以子集总数 = 2^n。
//   当前搜索树把这些子集分布在不同深度的节点上，因此进入每个 search 都要记录 path。
//
// 4. 执行步骤
//   1. 从 path=[]、start=0 开始；进入 search 后立即记录当前 path，所以空集首先被收集
//   2. 从 i=start 到 n-1 枚举下一个加入子集的元素；push nums[i] 后，path 仍按原下标递增
//   3. 递归传 i+1，明确当前元素以后不能再选，且更小下标永远不会回头进入这个分支
//   4. 子树探索完成后 pop 当前元素，恢复父 path，再枚举下一个可能的子集分支
//   记忆：子集不看顺序，就规定只往右选；每走到一个节点就先收答案。
//
// 5. 为什么不会漏 / 不会重
//   任意子集都能按原数组下标升序写成唯一序列 i1<i2<...<ik；搜索可以依次选择这些下标，所以不会漏。
//   反过来，每条搜索路径的下标严格递增，因此一个元素不会重复出现；同一下标集合也不可能以另一种顺序再次生成，
//   所以不会重。空集对应根节点，非空子集对应唯一非根节点，进入每层时记录恰好覆盖全部答案。
//
// 6. 边界与易错点
//   不要把 LC-46 的“只在叶子记录”照搬过来，否则会漏掉较短子集；本题每个 path 都合法。
//   递归必须传 i+1，不是 start+1，也不能传 i（后者会重复使用当前元素）。题目元素互异；若允许重复值，
//   需要排序并在同一层跳过相同值。O(n·2^n) 中的 n 来自复制每个 path，属于输出成本。
//
// 7. 举一反三
//   和 LC-46 对照：排列关心顺序，所以每层从所有未使用元素中选；子集不关心顺序，所以用 start 强制下标递增。
//   LC-39 会继续复用 start，但把 i+1 改成 i，从而表达“当前候选可以重复使用”。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：所有子集，每行一个且元素以空格分隔（空集输出空行）。
// test.in 的预期输出：<empty> | 1 | 2 | 1 2 | 3 | 1 3 | 2 3 | 1 2 3
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
    vector<vector<int>> answer;
    vector<int> path;

    void search(const vector<int>& nums, int start) {
        answer.push_back(path);
        for (int i = start; i < static_cast<int>(nums.size()); ++i) {
            path.push_back(nums[i]);
            search(nums, i + 1);
            path.pop_back();
        }
    }

public:
    vector<vector<int>> subsets(vector<int>& nums) {
        answer.clear();
        path.clear();
        search(nums, 0);
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto res = sol.subsets(a);
    for (auto& s : res) {
        for (size_t i = 0; i < s.size(); ++i) cout << s[i] << " \n"[i + 1 == s.size()];
        if (s.empty()) cout << "\n";
    }
    return 0;
}
