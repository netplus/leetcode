// ============================================================================
// LC-739：每日温度
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 2 周 / 第 12 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个整数数组 temperatures，表示每天的温度，返回一个数组 answer，其中 answer[i] 是指对于第 i 天，下一个更高温度出现在几天后。
// 如果气温在这之后都不会升高，请在该位置用 0 来代替。
//
// 题目示例：
// 示例 1：
//   Input: temperatures = [73,74,75,71,69,72,76,73]
//   Output: [1,1,4,2,1,1,0,0]
//
// 示例 2：
//   Input: temperatures = [30,40,50,60]
//   Output: [1,1,1,0]
//
// 示例 3：
//   Input: temperatures = [30,60,90]
//   Output: [1,1,0]
//
// 约束与要求：
//   - 1 <= temperatures.length <= 10^5
//   - 30 <= temperatures[i] <= 100
//
// 复杂度目标：O(n) 时间（单调栈）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜每日温度：从逐日向右搜索推导到单调栈
//
// 1. 题目直觉 / 图形模型
//   先只看题目在问什么：对每一天，找到右边第一个严格更暖的日期。
//
//   temperatures = [73,74,75,71,69,72,76,73]
//
//   以 71 这一天为例：
//
//   71 -> 69 -> 72
//    ^           ^
//    当前日      第一个更暖日
//
//   答案是两者下标距离 2。
//
//   这个问题最直观的动作就是“站在某一天，向右走，直到第一次看到更高温度”。
//
// 2. 最自然的一般性解法
//   最自然的实现是对每个 day 单独向右扫描：
//
//   for each day:
//       for future = day+1 ... n-1:
//           if temperatures[future] > temperatures[day]:
//               answer[day] = future-day
//               break
//
//   它完全符合题意，也很容易证明正确；只是最坏情况下每一天都可能扫描很远，因此时间会达到 O(n^2)。
//
// 3. 一般解法的问题与限制
//   问题不在于“每次比较太慢”，而在于不同 day 会反复走过同一段未来。
//
//   例如下降序列后面突然出现一个高温：
//
//   75  71  69 | 76
//   75 要看 71、69、76
//   71 又看 69、76
//   69 又看 76
//
//   同一批未来位置被不同起点重复搜索。n 到 10^5 时，O(n^2) 无法接受。
//
// 4. 从具体问题抽象规律
//   把观察方向反过来：与其让每个历史日期主动向未来找答案，不如从左到右扫描未来。
//
//   扫描过程中，历史日期只有两类：
//
//   已经遇到第一个更暖日 -> 答案永久确定，不再需要
//   还没遇到更暖日       -> 继续保留，等待未来
//
//   当前温度到来时，如果它比某个未决历史日期更高，那么这个历史问题就在这一刻第一次可以结算。
//
//   于是一般规律是：只保存“尚未解决”的历史状态，由未来第一次满足条件的事件批量结算。
//
// 5. 专项算法背景
//   这正是单调栈的一类典型问题。完整专题见 `docs/algorithms/monotonic-stack.md`。
//
//   这里需要的栈知识只有两点：
//   1. 栈顶是最近加入、最先被检查的未决日期；
//   2. 当 current 能解决 top 时，pop 后可以继续检查更早的未决日期。
//
//   连续删除已经被解决的历史状态后，剩余温度自然从栈底到栈顶单调不增，因此它是一个单调递减栈。单调性是结果，不是出发点。
//
// 6. 核心算法
//   pending 只保存“还没找到右侧第一个严格更暖日”的下标。
//
//   当前 day 到来时：
//   - 若 temperatures[day] > temperatures[pending.top()]，当前 day 就是栈顶日期第一次等到的更暖日，立即记录距离并 pop；
//   - pop 后继续检查新的栈顶，当前温度可能一次结算多个历史日期；
//   - 最后把 day 自己压栈，因为它的未来答案此刻还不知道。
//
// 7. 公式 / 不变量
//   扫描到 day 前：
//   pending = 尚未找到第一个严格更暖日的历史下标
//   T[pending] 从栈底到栈顶单调不增
//
//   若：
//   T[day] > T[pending.top()]
//
//   则：
//   previous = pending.top()
//   answer[previous] = day - previous
//   pop(previous)
//
//   相等温度不能弹，因为题目要求 strictly warmer。
//   栈保存 index 而不是只保存温度，因为答案需要位置差。
//
// 8. 执行步骤
//   1. 初始化答案为 0、pending 为空；0 正好表示直到数组结束都没有更暖日
//   2. 从左到右扫描 day；只要当前温度严格高于栈顶日期，就记录 day-previous 并 pop，持续结算所有当前能够解决的历史日期
//   3. 把当前 day 压入 pending；扫描结束仍留栈的日期从未遇到更暖日，答案保持 0
//   记忆：先理解“历史问题在等什么、当前事件为什么能解决它”，再记单调栈。
//
// 9. 为什么不会漏 / 不会重
//   为什么 day 是第一个更暖日：如果 previous 与 day 之间更早出现过严格更暖的日期，previous 已经会在那个时刻被弹，不可能留到现在。
//   为什么一次可以连续 pop：每弹掉一个已解决日期后，新栈顶仍是另一个尚未解决的历史日期；只要 current 仍更暖，就同样可以结算。
//   为什么 O(n)：每个下标只 push 一次、pop 至多一次，所有 while 的总 pop 次数不超过 n。
//
// 10. 边界与易错点
//   比较必须是 `>` 而不是 `>=`；必须存下标才能计算天数；不要把 pop 解释成单纯维护排序；for+while 的复杂度要按元素生命周期做摊还分析。
//
// 11. 举一反三
//   这是单调栈的第一层：未来事件到来时确定一个右侧答案。LC-84 会在同一模型上增加“左右边界”和区间宽度。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：n 个以空格分隔的等待天数。
// test.in 的预期输出：1 1 4 2 1 1 0 0
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> dailyTemperatures(vector<int>& temperatures) {
        // 默认 0 正好代表“直到末尾都没有更暖日期”；只有被未来事件结算的下标才会改写。
        vector<int> answer(temperatures.size(), 0);

        // pending 存“还没找到第一个更暖日期”的历史下标。
        // 下标从底到顶递增，对应温度单调不增；栈顶是最近、最先有机会被当前温度结算的日期。
        stack<int> pending;

        for (int day = 0; day < static_cast<int>(temperatures.size()); ++day) {
            // 当前温度严格高于栈顶时，day 就是该历史日期第一次遇到的更暖日：
            // 若更早已有答案，它早已在当时被弹栈，不可能继续留在 pending。
            // 相等温度不能弹，因为题目要求 strictly warmer。
            while (!pending.empty() && temperatures[day] > temperatures[pending.top()]) {
                const int previous = pending.top();
                pending.pop();

                // pending 存的是下标而非温度，正是为了直接得到等待天数 day-previous。
                answer[previous] = day - previous;
            }

            // 当前日期暂时不知道未来答案，加入未决集合；以后由第一个严格更暖的日期负责结算。
            pending.push(day);
        }

        // 扫描结束仍留在栈中的日期从未遇到更暖日，保持初始化的 0。
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto ans = sol.dailyTemperatures(a);
    for (size_t i = 0; i < ans.size(); ++i) cout << ans[i] << " \n"[i + 1 == ans.size()];
    return 0;
}