// ============================================================================
// LC-62：不同路径
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 3 周 / 第 19 天
// ----------------------------------------------------------------------------
// 题目描述：
// 一个机器人位于一个 m x n 网格的左上角 （起始点在下图中标记为 “Start”）。
// 机器人每次只能向下或者向右移动一步。
// 机器人试图达到网格的右下角（在下图中标记为 “Finish”）。
// 问总共有多少条不同的路径？
//
// 题目示例：
// 示例 1：
//   Input: m = 3, n = 7
//   Output: 28
//
// 示例 2：
//   Input: m = 3, n = 2
//   Output: 3
//   Explanation: From the top-left corner, there are a total of 3 ways to reach the bottom-right corner:
//   1. Right -> Down -> Down
//   2. Down -> Down -> Right
//   3. Down -> Right -> Down
//
// 约束与要求：
//   - 1 <= m, n <= 100
//   - 题目数据保证答案小于等于 2 * 10^9
//
// 复杂度目标：O(m*n) 时间，O(n) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜二维网格 DP：从重复路径递归到一行滚动状态
//
// 0. 优化是怎么来的
//   最自然的正确解法是递归：站在 (row,col)，若还没到终点，就分别尝试向右和向下，最后把两边返回的路径数量相加。它会枚举所有合法路径，所以正确。
//
//   真正的浪费是重复子问题。比如从多个不同路径都可能走到同一个格子 (r,c)；从这个格子到终点的剩余问题完全相同，却会被递归重新计算很多次。网格越大，重复越严重。
//
//   于是把问题反过来看：不再记录“我是怎么走到这里的”，只记录“到达这个格子一共有多少种方法”。设 ways[r][c] 为到达 (r,c) 的路径数，最后一步只可能来自上或左，所以每个格子只算一次：
//   ways[r][c] = ways[r-1][c] + ways[r][c-1]。
//   这把指数搜索压成 O(m*n) 个状态。
//
//   再看依赖：按行从左到右更新时，ways[r][c] 只需要上一行同列和当前行左列。把上一行保存在一维 dp 后：更新前 dp[c] 就是“上方”，已经更新后的 dp[c-1] 就是“左方”。因此二维表还能压成 O(n) 空间。
//
//   优化链：枚举所有路径 -> 相同格子后的剩余问题被重复计算 -> 每格只保存一次答案 -> 只依赖上方/左方 -> 一行滚动 DP。
//
// 1. 图像直觉
//   以 3 x 4 网格为例，每个格子写“到这里有多少条路径”：
//
//   1  1  1  1
//   1  2  3  4
//   1  3  6 10
//
//   看中间一个格子：
//
//           上方 old dp[c]
//                 |
//                 v
//   左方 --->   当前格
//   new dp[c-1]
//
//   当前格的每条路径最后一步必然从这两个方向之一进入。
//
//   一维压缩时，处理当前行某个 c 之前：
//   dp[c]   = 上一行 (r-1,c) 的路径数
//   dp[c-1] = 当前行 (r,c-1) 的路径数
//
//   因此直接执行：
//   dp[c] = dp[c] + dp[c-1]
//
//   从左到右的顺序本身就是状态语义的一部分。
//
// 2. 一句话核心
//   每个格子的路径只按最后一步分成“从上来”和“从左来”两类；按行左到右时，一维 dp 同时保存旧上方和新左方。
//
// 3. 公式 / 不变量
//   二维状态：
//   ways[r][c] = 到达格子 (r,c) 的路径数量。
//
//   边界：
//   ways[0][c] = 1
//   ways[r][0] = 1
//
//   内部格：
//   ways[r][c] = ways[r-1][c] + ways[r][c-1]
//
//   压成一维后，在更新 (r,c) 前：
//   dp[c]   = ways[r-1][c]   // 上方旧值
//   dp[c-1] = ways[r][c-1]   // 左方新值
//
//   所以：
//   dp[c] += dp[c-1]。
//
//   循环不变量：处理完当前行的列 c 后，dp[0..c] 已表示当前行，dp[c+1..] 仍表示上一行。
//
// 4. 执行步骤
//   1. 创建长度 n 的 dp，并全部初始化为 1；这等价于先写好第一行，也同时覆盖第一列只有一种走法的边界
//   2. 从第二行开始逐行处理；每一行都从 col=1 开始，因为 col=0 永远只能一路向下到达
//   3. 对每个 col，先认清旧 dp[col] 是上方，dp[col-1] 已经是本行左方，再执行 dp[col]+=dp[col-1]
//   4. 必须从左向右更新，这样左侧状态已经切换到当前行，而右侧仍保留上一行
//   5. 全部行处理后，dp[n-1] 就是右下角路径数量
//   记忆：画依赖箭头：旧 dp[col] 是上，新 dp[col-1] 是左；左到右更新才能同时拿到两者。
//
// 5. 为什么不会漏 / 不会重
//   任意到达内部格 (r,c) 的路径最后一步唯一属于两类：从 (r-1,c) 向下，或从 (r,c-1) 向右。两类互斥且覆盖全部路径，所以数量可以相加。第一行和第一列只有唯一方向，因此边界为 1。按左到右顺序滚动时，两个依赖值在读取时分别仍保持正确的“旧上方”和“新左方”语义；压缩只丢弃未来不会再访问的更早行，不会改变任何状态值。
//
// 6. 边界与易错点
//   一维压缩后最容易忽略的是遍历方向：若从右向左，dp[col-1] 还停留在上一行，就不再代表当前格的左方。m 或 n 为 1 时答案仍为 1，初始化已自然覆盖。官方保证答案 <= 2*10^9，因此当前 int 实现满足题面范围。
//
// 7. 举一反三
//   这是 Day 18 LC-70 的二维版本：LC-70 的状态只从前两个位置来，这里每个网格状态从上和左来。下一题 LC-64 完全复用同一张依赖图，只把“两个来源的方案数相加”换成“两个来源的最小成本取 min 再加当前格”。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：m n。
//   输出：不同路径数量。
// test.in 的预期输出：28
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int uniquePaths(int m, int n) {
        // 第一行每个格子都只能一路向右到达，因此初始化全 1；
        // 后续每一行的 dp[0] 也会一直保持 1，对应第一列只能一路向下。
        vector<int> dp(n, 1);

        for (int row = 1; row < m; ++row) {
            // 必须从左向右更新：处理 (row,col) 之前，
            // dp[col] 仍是上一行同列 ways[row-1][col]，
            // dp[col-1] 已更新成当前行左邻 ways[row][col-1]。
            for (int col = 1; col < n; ++col) {
                // 到当前格的路径按最后一步只分成“从上来”和“从左来”两类，所以两者相加。
                dp[col] += dp[col - 1];
            }
        }

        // 最后一行处理结束后，dp[n-1] 就是右下角格子的路径数。
        return dp[n - 1];
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int m, n; if (!(cin >> m >> n)) return 0;
    cout << sol.uniquePaths(m, n) << "\n";
    return 0;
}
