// ============================================================================
// LC-53：最大子数组和
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 1 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 nums，请你找出一个具有最大和的连续子数组（子数组最少包含一个元素），返回其最大和。
// 子数组是数组中的一个连续部分。
//
// 约束与要求：
//   - 1 <= nums.length <= 10^5
//   - -10^4 <= nums[i] <= 10^4
//
// 复杂度目标：O(n) 时间，O(1) 空间（Kadane）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜Kadane 动态规划：保留最优后缀
//
// 1. 图像直觉
//   走到当前位置 x 时，只比较两种连续子数组：
//
//   ... [前一位置的最佳后缀] | x
//             current          ^
//
//   继续接上：current + x
//   从这里重开：       x
//
//   如果前面的最佳后缀已经是负担，就没有必要继续带着它。
//
// 2. 一句话核心
//   走到每个位置，只决定一件事：前面的最佳后缀值得不值得继续带上。
//
// 3. 公式 / 不变量
//   current = max(nums[i], current + nums[i])
//   best    = max(best, current)
//
//   current 始终表示“必须以当前位置 i 结尾”的最大子数组和；best 表示目前见过的所有 current 中最大者。
//
// 4. 执行步骤
//   1. 用 nums[0] 初始化 current 和 best，保证子数组非空
//   2. 对每个 nums[i]，比较“从当前重新开始”和“接在旧 current 后面”
//   3. 得到新的 current 后，用它更新全局 best
//   记忆：每个位置先选“接上还是重开”，再用这个位置的最佳答案更新全局 best。
//
// 5. 为什么不会漏 / 不会重
//   任意非空连续子数组一定有一个结尾位置 i。对固定 i，最优答案只可能是 nums[i] 自己，或某个以 i-1 结尾的连续后缀再接上 nums[i]；
//   current 已经保留了第二类里的最优者。对所有结尾位置取最大值，就是全局最大子数组和。
//
// 6. 边界与易错点
//   current/best 不能初始化为 0，否则全负数组会错误地选择不存在的“空子数组”；题目明确要求子数组至少含一个元素。
//
// 7. 举一反三
//   这题最重要的不是背 Kadane，而是学会定义“必须以当前位置结尾”的状态。最大乘积子数组、带一次删除/修改的子数组 DP 也常从这个视角出发。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：最大子数组和。
// test.in 的预期输出：6
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int maxSubArray(vector<int>& nums) {
        int current = nums[0];
        int best = nums[0];
        for (int i = 1; i < static_cast<int>(nums.size()); ++i) {
            // 旧后缀为负时会拖累当前元素，此时从当前位置重新开始。
            current = max(nums[i], current + nums[i]);
            best = max(best, current);
        }
        return best;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.maxSubArray(a) << "\n";
    return 0;
}
