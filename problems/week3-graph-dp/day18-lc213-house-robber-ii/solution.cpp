// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 3 周 / 第 18 天
// ----------------------------------------------------------------------------
// 题目描述：
// 你是一个专业的小偷，计划偷窃沿街的房屋，每间房内都藏有一定的现金。
// 这个地方所有的房屋都围成一圈，这意味着第一个房屋和最后一个房屋是紧挨着的。
// 同时，相邻的房屋装有相互连通的防盗系统，如果两间相邻的房屋在同一晚上被小偷闯入，系统会自动报警。
// 给定一个代表每个房屋存放金额的非负整数数组，计算你在不触动警报装置的情况下，今晚能够偷窃到的最高金额。
//
// 约束与要求：
//   - 1 <= nums.length <= 100
//   - 0 <= nums[i] <= 1000
//
// 复杂度目标：O(n) 时间，O(1) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜环形约束拆分：先用首尾互斥把环断开，再原样复用 LC-198
//
// 0. 优化是怎么来的
//   最自然的正确算法仍然可以 DFS 枚举每间房偷/不偷，并额外记住第一间是否被偷；走到最后一间时若第一间已偷，就禁止再偷最后一间。它能覆盖所有合法方案，但仍是指数级枚举，而且把一个只有首尾额外冲突的问题处理得过于复杂。
//
//   如果尝试直接把 LC-198 的线性 recurrence 套到整个数组，又会出错：线性 DP 只知道相邻 i-1/i 的冲突，它不会记住第 0 间是否已选，因此可能同时选首尾。
//
//   关键结构只有一个：首尾不能同时被选。于是所有合法方案一定属于下面至少一类：
//   A. 不选择最后一间 -> 只考虑 [0, n-2]；
//   B. 不选择第一间 -> 只考虑 [1, n-1]。
//
//   这两个区间内部已经没有环，都是完整的 LC-198。即使某个方案首尾都不选，它会同时出现在 A/B 中也没关系，因为我们只取最大值，不是在计数方案。
//
//   优化/建模链：指数枚举环上选择 -> 抓住唯一跨边界冲突“首尾互斥” -> 用两个覆盖全部合法方案的线性区间断环 -> 复用 LC-198 O(n)/O(1)。
//
// 1. 图像直觉
//   环形房屋：
//
//          [0] -- [1] -- [2] -- ... -- [n-2] -- [n-1]
//           |                                      |
//           +--------------------------------------+
//                       首尾也相邻
//
//   只需要剪断这条额外的首尾边。
//
//   情况 A：保证不偷最后一间
//   [0] -- [1] -- ... -- [n-2]      [n-1] X
//   => 线性区间 [0,n-2]
//
//   情况 B：保证不偷第一间
//   [0] X      [1] -- ... -- [n-1]
//   => 线性区间 [1,n-1]
//
//   任何合法方案都至少落在一个情况里：
//   - 若偷首，则必不偷尾 -> A；
//   - 若不偷首 -> B。
//
//   所以答案只需 max(robRange(A), robRange(B))。
//
// 2. 一句话核心
//   环上唯一新增冲突是首尾不能同时选；分别禁止尾、禁止首，把问题拆成两个线性 LC-198，再取两者最大值。
//
// 3. 公式 / 不变量
//   n == 1：answer = nums[0]
//
//   n >= 2：
//   A = robLinear(nums, 0, n-2)
//   B = robLinear(nums, 1, n-1)
//   answer = max(A, B)
//
//   其中 robLinear(left,right) 完全复用 LC-198：
//   current = max(previous1, previous2 + nums[i])。
//
//   覆盖不变量：每个合法环形方案至少属于 A 或 B；A/B 内部都不存在首尾额外相邻关系。
//
// 4. 执行步骤
//   1. 先处理 n==1；此时不存在可供拆分的两个有效区间，唯一房屋直接返回
//   2. 定义 robRange(left,right)，内部不要改变 LC-198：previous2/previous1 从 0 开始滚动
//   3. 计算区间 [0,n-2]，它代表明确禁止最后一间房后的全部合法方案
//   4. 计算区间 [1,n-1]，它代表明确禁止第一间房后的全部合法方案
//   5. 返回两条线性最优值的 max；无需判断哪个区间实际偷了首/尾，因为覆盖关系已经保证答案存在其中
//   记忆：环只多了首尾这一条冲突：禁尾做一次 LC-198，禁首再做一次，取最大。
//
// 5. 为什么不会漏 / 不会重
//   任何环形合法方案不能同时包含房 0 和房 n-1。若它包含房 0，则必不包含房 n-1，因此完整落在区间 [0,n-2] 的 LC-198 搜索空间中；若它不包含房 0，则完整落在 [1,n-1] 中。故两个线性子问题的并集覆盖全部合法方案。反过来，每个子问题都删除了首尾冲突中的一个端点，内部只剩普通相邻约束，所以 LC-198 给出的方案在原环中也合法。取两者最大值恰为全局最优。
//
// 6. 边界与易错点
//   n==1 必须特判，否则 [0,n-2] / [1,n-1] 会形成无效区间。robRange 使用闭区间，调用端点必须保持一致。两个 case 不是互斥集合：首尾都不偷的方案会被计算两次，但我们取最大值而不是计数，所以不会影响正确性。不要为了环形问题复制一套新的复杂状态机；这里复用 LC-198 更清楚。
//
// 7. 举一反三
//   这是非常通用的“少量边界状态枚举 -> 断环 -> 复用线性模型”。环形染色、环形相邻选择、循环序列 DP 都可以先固定第一个位置的少量状态，使首尾依赖消失，再调用已经会做的线性 DP。下一步学习更复杂 DP 时，也应优先寻找能否先把新约束拆掉，再复用旧状态定义。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：可获得的最大金额。
// test.in 的预期输出：3
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
    // 这个 helper 就是 LC-198 的线性版本，区间采用闭区间 [left,right]。
    static int robRange(const vector<int>& nums, int left, int right) {
        int previous2 = 0, previous1 = 0;

        for (int i = left; i <= right; ++i) {
            // 在已经断开的线性区间内，递推与 LC-198 完全相同：
            // 不选 nums[i] -> previous1；选 nums[i] -> previous2 + nums[i]。
            int current = max(previous1, previous2 + nums[i]);
            previous2 = previous1;
            previous1 = current;
        }

        return previous1;
    }

public:
    int rob(vector<int>& nums) {
        // 单节点环没有“首尾两个不同端点”可供拆分，唯一合法最优就是这间房本身。
        if (nums.size() == 1) return nums[0];

        // 环形约束只比 LC-198 多一条边：房 0 与房 n-1 不能同时选。
        // case A 排除最后一间 -> [0,n-2]；case B 排除第一间 -> [1,n-1]。
        // 任意合法方案至少属于其中一个 case，因此两条线性最优取 max 就覆盖全局最优。
        return max(robRange(nums, 0, static_cast<int>(nums.size()) - 2),
                   robRange(nums, 1, static_cast<int>(nums.size()) - 1));
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.rob(a) << "\n";
    return 0;
}

