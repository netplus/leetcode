// ============================================================================
// LC-14：最长公共前缀
// 难度：简单
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 5 天
// ----------------------------------------------------------------------------
// 题目描述：
// 编写一个函数来查找字符串数组中的最长公共前缀。
// 如果不存在公共前缀，返回空字符串 ""。
//
// 题目示例：
// 示例 1：
//   Input: strs = ["flower","flow","flight"]
//   Output: "fl"
//
// 示例 2：
//   Input: strs = ["dog","racecar","car"]
//   Output: ""
//   Explanation: There is no common prefix among the input strings.
//
// 约束与要求：
//   - 1 <= strs.length <= 200
//   - 0 <= strs[i].length <= 200
//   - strs[i] 如果非空，则仅由小写英文字母组成
//
// 复杂度目标：O(S) 其中 S = 字符总数。
//
// ----------------------------------------------------------------------------
// 解法精讲｜从题目直觉到可复用算法
//
// 1. 题目直觉 / 图形模型
//   把所有字符串左对齐写成多行：
//
//   flower
//   flow
//   flight
//   ^^^^
//
//   公共前缀只能从第 0 列开始连续向右。某一列只要有一个字符串结束，或出现不同字符，公共前缀就在这一列之前结束。
//
// 2. 最自然的一般性解法
//   最自然的做法就是逐列检查：先看第 0 个字符是否所有字符串相同，再看第 1 个……第一次出现越界或不同就停止。最多检查到最短字符串长度，每个被检查位置只比较一次。
//
// 3. 一般解法的问题与限制
//   这个一般解法已经直接利用了“前缀必须从开头连续一致”的题意，渐进复杂度上没有需要消除的重复工作。真正的限制只是边界：任意字符串为空时答案立即为空；某列失败后后面的列完全没有继续检查的意义。
//
// 4. 从具体问题抽象规律
//   这是一类“共同起点 + 首次失败决定边界”的扫描问题。只要目标对象必须从同一起点连续满足条件，就可以同步推进，第一次失败即封口。
//
// 5. 专项算法｜纵向扫描：逐列验证公共前缀
//   这题不需要额外的高级数据结构；前面的逐列同步扫描已经是最直接的核心算法。专项文档体系在这里的意义是识别‘无需升级’，而不是强行套一个模板。
//
// 6. 核心算法
//   逐列检查所有字符串；前面每一列都通过，直到第一列失败，失败位置之前就是最长公共前缀。
//
// 7. 公式 / 不变量
//   设 first = strs[0]。
//   对位置 i：
//
//   若存在某个 j，使得
//     i == strs[j].size()
//   或
//     strs[j][i] != first[i]
//
//   则答案长度就是 i。
//
//   如果 first 的所有位置都通过，答案就是 first 本身。
//
// 8. 执行步骤
//   1. 把 strs[0] 当作公共前缀长度的最大上界
//   2. 从 i=0 开始逐列扫描 first
//   3. 对每一列 i，检查其余所有字符串是否仍有该位置且字符相同
//   4. 第一次越界或字符不同，立即返回 first.substr(0,i)
//   5. 如果 first 全部检查完成，返回 first
//   记忆：逐列验收；第一次失败就是答案边界。
//
// 9. 为什么不会漏 / 不会重
//   公共前缀要求从第 0 个字符开始连续一致，因此一旦第 i 列失败，任何长度大于 i 的字符串片段都不可能成为公共前缀；而 [0,i) 的每一列都已经经过所有字符串验证，所以返回它既不会短也不会长。
//
// 10. 边界与易错点
//   字符串数组非空，但某个字符串可以为空；空串会在第 0 列立即终止。不要把“公共子串”和“公共前缀”混淆：前缀必须从下标 0 开始，所以第一次失败后无需继续搜索。
//
// 11. 举一反三
//   这是“从共同起点向前推进，首次失败决定边界”的模型。共同路径、版本号共同前缀、Trie 中沿唯一公共分支向下走，都有相同直觉。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n (字符串数量)。
//   接下来 n 行：每行一个字符串。
//   输出：最长公共前缀。
// test.in 的预期输出：fl
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    string longestCommonPrefix(vector<string>& strs) {
        // 公共前缀不可能比任意一个字符串更长，因此先用 strs[0]
        // 作为“最长可能前缀”的上界，随后逐列让其他字符串来验收。
        const string& first = strs[0];

        for (int i = 0; i < static_cast<int>(first.size()); ++i) {
            // 进入第 i 列时，不变量是：所有字符串的 [0,i) 已经逐列验证完全相同。
            // 因此前面 i 个字符已经确定属于公共前缀；现在只需判断第 i 列能否继续延伸。
            for (int j = 1; j < static_cast<int>(strs.size()); ++j) {
                // 必须先判断 i 是否已经到达当前字符串末尾，再访问 strs[j][i]。
                // “有人没有第 i 个字符”与“第 i 个字符不同”都会立即终止前缀；
                // 一旦这里失败，任何更长前缀都不可能成立，所以可以直接返回 [0,i)。
                if (i == static_cast<int>(strs[j].size()) || strs[j][i] != first[i]) {
                    return first.substr(0, i);
                }
            }
        }

        // 若 first 的每一列都通过所有字符串验收，first 本身就是最长公共前缀。
        return first;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    vector<string> strs(n);
    string discard; getline(cin, discard);
    for (int i = 0; i < n; ++i) getline(cin, strs[i]);
    cout << sol.longestCommonPrefix(strs) << "\n";
    return 0;
}
