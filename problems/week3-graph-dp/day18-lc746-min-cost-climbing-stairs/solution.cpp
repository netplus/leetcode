// ============================================================================
// LC-746：使用最小花费爬楼梯
// 难度：简单
// 优先级：P1（进阶）
// 学习进度：第 3 周 / 第 18 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 cost，其中 cost[i] 是从楼梯第 i 个台阶向上爬需要支付的费用。
// 一旦你支付此费用，即可选择向上爬一个或者两个台阶。
// 你可以选择从下标为 0 或下标为 1 的台阶开始爬楼梯。
// 请你计算并返回达到楼梯顶部的最低花费。
//
// 题目示例：
// 示例 1：
//   Input: cost = [10,15,20]
//   Output: 15
//   Explanation: You will start at index 1.
//   - Pay 15 and climb two steps to reach the top.
//   The total cost is 15.
//
// 示例 2：
//   Input: cost = [1,100,1,1,1,100,1,1,100,1]
//   Output: 6
//   Explanation: You will start at index 0.
//   - Pay 1 and climb two steps to reach index 2.
//   - Pay 1 and climb two steps to reach index 4.
//   - Pay 1 and climb two steps to reach index 6.
//   - Pay 1 and climb one step to reach index 7.
//   - Pay 1 and climb two steps to reach index 9.
//   - Pay 1 and climb one step to reach the top.
//   The total cost is 6.
//
// 约束与要求：
//   - 2 <= cost.length <= 1000
//   - 0 <= cost[i] <= 999
//
// 复杂度目标：O(n) 时间，O(1) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜路径 DP：复用 LC-70 的前两状态，把计数改成最小累计代价
//
// 0. 优化是怎么来的
//   自然的正确做法是递归求“到达位置 i 的最低成本”：最后一步只可能从 i-1 或 i-2 来，因此分别递归求这两个位置的最低成本，再加上离开对应台阶的费用，最后取 min。
//
//   和 LC-70 一样，直接递归会重复计算同一个 minCost(i)。例如求顶部时会递归到 n-1、n-2，而 n-1 的递归内部又会再次求 n-2。重复子问题完全相同，只是聚合操作从加法变成了 min。
//
//   所以沿用 LC-70 的优化：每个位置最低成本只算一次。再观察 dp[i] 仍然只依赖 dp[i-1]、dp[i-2]，整张表可以继续压成 previous1/previous2。
//
//   真正需要先澄清的是状态边界：题目允许从 0 或 1 开始，这等价于“到达位置 0 和位置 1 都不需要支付任何费用”；费用是在从某个真实台阶离开时加入，而不是一到达就加入。
//
//   优化链仍是：重复递归 -> 线性 DP -> 两状态滚动；LC-70 的骨架可以直接复用。
//
// 1. 图像直觉
//   cost = [10,15,20]，把楼顶画成虚拟位置 3：
//
//   位置:   0 ---- 1 ---- 2 ---- TOP(3)
//   费用:  10     15     20
//
//   到 TOP 的最后一跳只有：
//
//   从 2 来：到达 2 的最低成本 + cost[2]
//   从 1 来：到达 1 的最低成本 + cost[1]
//
//   而题目允许一开始站在 0 或 1：
//   dp[0]=0
//   dp[1]=0
//
//   于是：
//   dp[2] = min(dp[1]+15, dp[0]+10) = 10
//   dp[3] = min(dp[2]+20, dp[1]+15) = 15
//
//   这里 dp[3] 才是“到达楼顶”，不是 dp[2]。
//
// 2. 一句话核心
//   把楼顶当成位置 n；到 i 的最低成本只来自 i-1/i-2，两条来源分别加上离开那个台阶的费用，再取较小者。
//
// 3. 公式 / 不变量
//   状态：
//   dp[i] = 到达位置 i 的最低累计花费，位置 n 是楼顶。
//
//   起点：
//   dp[0] = 0
//   dp[1] = 0
//
//   对 2 <= i <= n：
//   dp[i] = min(
//       dp[i-1] + cost[i-1],
//       dp[i-2] + cost[i-2]
//   )
//
//   滚动不变量：进入 i 时：
//   previous2 = dp[i-2]
//   previous1 = dp[i-1]。
//
//   计算 current 后再整体前移。
//
// 4. 执行步骤
//   1. 把 cost.size() 记作 n，并把 n 当成楼顶这个虚拟位置；目标是 dp[n]
//   2. 初始化 previous2=dp[0]=0、previous1=dp[1]=0，因为可以免费选择从 0 或 1 开始
//   3. 对 i=2..n，比较从 i-1 离开与从 i-2 离开两种最后一步成本，得到 current
//   4. 先完成 current=min(...)，再把 previous2/previous1 向前滚动，保持 LC-70 相同的更新顺序
//   5. 循环处理到 i=n 后，previous1 就是到达楼顶的最低花费
//   记忆：楼顶也当一个位置；从哪一阶离开，就加哪一阶 cost；两条最后来源取更便宜的。
//
// 5. 为什么不会漏 / 不会重
//   任意到达 i 的合法路径最后一步只能从 i-1 或 i-2 发出。若最后从 i-1 来，那么此前部分用 dp[i-1] 的最优路径不会比任何其它到 i-1 的路径更差，再支付 cost[i-1] 即得到这一类的最优值；i-2 同理。所有路径恰好落入这两类，因此取二者最小值不会漏掉更优路径。滚动压缩只丢弃未来递推再也不会读取的状态。
//
// 6. 边界与易错点
//   cost[i] 表示离开台阶 i 的费用，不要把它误加在“到达 i”时。楼顶是虚拟位置 n，因此循环必须允许 i==n；若只算到 n-1 会少最后一步。起始 dp[0]=dp[1]=0，不是 cost[0]/cost[1]。更新顺序仍要先算 current，再覆盖旧状态。
//
// 7. 举一反三
//   直接复用 LC-70：依赖图完全相同，都是当前位置只看前两位置。改变的只是聚合语义——LC-70 对互斥来源做计数相加；LC-746 对两条可行来源做最小化。以后遇到路径 DP，先分清状态表示“方案数、最小代价还是最大收益”。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：最小花费。
// test.in 的预期输出：15
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int minCostClimbingStairs(vector<int>& cost) {
        // 状态定义：dp[i] = 到达位置 i 的最低累计花费；位置 n 是楼顶这个虚拟位置。
        // 题目允许免费从 0 或 1 开始，所以 dp[0]=dp[1]=0。
        int previous2 = 0, previous1 = 0;

        for (int i = 2; i <= static_cast<int>(cost.size()); ++i) {
            // 进入 i 时：previous2=dp[i-2]，previous1=dp[i-1]。
            // cost[j] 是“从台阶 j 离开”时支付，因此最后一步从 i-1 来要加 cost[i-1]，
            // 从 i-2 来则加 cost[i-2]；两类合法最后来源取较小值。
            int current = min(previous1 + cost[i - 1], previous2 + cost[i - 2]);

            // 与 LC-70 一样，必须先算 current 再覆盖旧状态；否则会丢掉当前递推仍需要的 dp[i-2]/dp[i-1]。
            previous2 = previous1;
            previous1 = current;
        }

        // 循环允许 i==n，所以最终 previous1 对应 dp[n]，也就是已经到达楼顶而非最后一级台阶。
        return previous1;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.minCostClimbingStairs(a) << "\n";
    return 0;
}
