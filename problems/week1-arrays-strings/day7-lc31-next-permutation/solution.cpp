// ============================================================================
// LC-31：下一个排列
// 难度：中等
// 优先级：P1（进阶）
// 学习进度：第 1 周 / 第 7 天
// ----------------------------------------------------------------------------
// 题目描述：
// 整数数组的一个排列就是将其所有成员以序列或线性顺序排列。
// 例如，arr = [1,2,3]，以下这些都可以视作 arr 的排列：[1,2,3]、[1,3,2]、[3,1,2]、[2,3,1]。
// 整数数组的下一个排列是指其整数的下一个字典序更大的排列。
// 更正式地，如果数组的所有排列根据其字典顺序从小到大排列在一个容器中，那么数组的下一个排列就是在这个有序容器中排在它后面的那个排列。
// 如果不存在下一个更大的排列，那么这个数组必须重排为字典序最小的排列（即，其元素按升序排列）。
// 例如，arr = [1,2,3] 的下一个排列是 [1,3,2]。
// 类似地，arr = [2,3,1] 的下一个排列是 [3,1,2]。
// 而 arr = [3,2,1] 的下一个排列是 [1,2,3]，因为 [3,2,1] 不存在一个字典序更大的排列。
// 给你一个整数数组 nums，找出 nums 的下一个排列。
// 必须原地修改，只允许使用额外常数空间。
//
// 题目示例：
// 示例 1：
//   Input: nums = [1,2,3]
//   Output: [1,3,2]
//
// 示例 2：
//   Input: nums = [3,2,1]
//   Output: [1,2,3]
//
// 示例 3：
//   Input: nums = [1,1,5]
//   Output: [1,5,1]
//
// 约束与要求：
//   - 1 <= nums.length <= 100
//   - 0 <= nums[i] <= 100
//
// 复杂度目标：O(n) 时间，O(1) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜字典序下一排列：最小幅度增大
//
// 前置概念
//   字典序（lexicographical order）像查字典一样从左到右比较两个序列：
//   1. 找到第一个不同位置，谁在这个位置上的值更大，谁的字典序更大；
//   2. 如果公共部分全部相同，也就是一个序列是另一个的完整前缀，则较短序列更小。
//
//   例如：
//   [1,3] > [1,2,3]，因为第二位首次不同，3>2；
//   [1,2] < [1,2,3]，因为前两位完全相同，而较短序列先结束。
//
//   LC-31 的所有排列长度相同，因此实际求解时只会用到“第一个不同位置决定大小”这一部分。所谓 next permutation，就是所有排列按这种顺序排列后紧挨当前排列之后的那个。
//
// 0. 优化是怎么来的
//   一个完全直接但不可扩展的办法，是生成所有排列、按字典序排序，再找到当前排列的下一个；它准确表达了 next permutation 的定义，但排列数是 n!。
//
//   真正需要的不是知道所有排列，而是直接构造“刚刚比当前大”的那个。因为字典序由从左到右第一个不同位置决定，所以越靠左的位置变化，影响越大；想让变化最小，就应尽量保留更左前缀。
//
//   从右向左找到的最长非递增后缀已经是这些元素能组成的最大顺序，只改这个后缀不可能让整体继续增大。因此必须修改后缀左侧的 pivot，而且要让它只增大到后缀中最小的严格较大值；高位完成最小增量后，再把后缀降到最小排列。由于原后缀本来非递增，交换后仍可直接 reverse 成升序，无需再 sort。
//
//   优化类型：全排列搜索 -> 利用字典序“第一个不同位置决定大小”的高位支配性，直接构造最小严格后继。时间从阶乘级降为 O(n)，空间 O(1)。
//
// 1. 图像直觉
//   “下一个排列”不是随便找一个更大的排列，而是找刚刚大一点的那个。
//
//   因此要遵守两个优先级：
//   1. 尽量不要动高位；
//   2. 如果必须增大某一位，增幅要尽量小；之后的低位再尽量小。
//
//   看 [1, 3, 5, 4, 2]。
//
//   从右往左看：5,4,2 是非递增后缀。
//   这个后缀已经处于这些元素能形成的“最大排列”：
//   [5,4,2]
//   无论只重排它，都不可能得到更大的整体序列。
//
//   所以必须动它左边第一位 3：
//   [1, 3 | 5,4,2]
//       ^ pivot
//
//   要让整体只增大一点，应从后缀里找“比 3 大的最小值”。
//   由于后缀非递增，从最右往左遇到的第一个 >3 的就是 4：
//   [1, 4 | 5,3,2]
//
//   高位已经完成最小幅度增大。现在为了让整体尽可能小，把后缀排成最小顺序：
//   [5,3,2] 原本仍是非递增，只需 reverse：
//   [1,4,2,3,5]
//
//   这就是紧邻的下一个字典序。
//
// 2. 一句话核心
//   从右找最右还能增大的 pivot，用后缀中刚好比它大的最小值替换，再把后缀降到最小排列；这样高位变化最晚、增幅最小。
//
// 3. 公式 / 不变量
//   先找最长非递增后缀：
//   nums[pivot+1] >= nums[pivot+2] >= ... >= nums[n-1]
//
//   pivot 是最右满足：
//   nums[pivot] < nums[pivot+1]
//   的位置。
//
//   若 pivot 不存在：
//   整个数组非递增 = 当前最大排列
//   next = reverse(all) = 最小排列
//
//   若 pivot 存在，从右向左找第一个 successor 满足：
//   nums[successor] > nums[pivot]
//
//   由于后缀非递增，这个 successor 就是后缀中“最小的严格较大值”。
//   交换 pivot/successor 后，反转 pivot+1..end，即得到该新前缀下的最小后缀。
//
// 4. 执行步骤
//   1. 从 n-2 向左寻找最右的 pivot，使 nums[pivot] < nums[pivot+1]；越过的部分就是最长非递增后缀
//   2. 若找到 pivot，从数组最右端向左找第一个 nums[successor] > nums[pivot] 的位置
//   3. 交换 pivot 与 successor，使最靠右的可变高位产生最小的严格增量
//   4. 反转 pivot 之后的整个后缀，把低位变成当前前缀下的最小排列
//   5. 若一开始没有 pivot，同一个 reverse 会直接把整个最大排列变回最小排列
//   记忆：右边已经最大了才动左一位；换成刚大一点，再把右边降到最小。
//
// 5. 为什么不会漏 / 不会重
//   pivot 右侧是非递增后缀，它已经是这些元素的最大字典序，只改后缀不可能再增大，所以想得到更大排列至少必须修改 pivot 或更左的位置；选择最右 pivot 比修改任何更左高位造成的变化更小。在 pivot 确定后，选择后缀中最小的严格较大值让这一位增幅最小；最后把后缀变成升序最小排列，就排除了所有“同一新前缀下还能更小”的候选，因此得到的正是紧邻下一排列。
//
// 6. 边界与易错点
//   pivot 条件必须是严格 <；寻找 successor 也必须是严格 >，这样重复值才能正确处理，例如 [1,5,1]。后缀之所以可以 reverse 而无需 sort，是因为找到 pivot 时已知它非递增。长度 1 时 pivot=-1，reverse 整段仍正确。要求原地常量空间。
//
// 7. 举一反三
//   它延续了 Day 6 LC-179 的“从最终目标反推局部排序规则”，但这里不是给所有元素定义 comparator，而是利用字典序的高位支配性：先确定最右可改变高位，再让剩余后缀极小化。求上一排列时完全对称：找最右下降点、换成刚好更小值、后缀变最大。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：下一个排列，元素以空格分隔。
// test.in 的预期输出：1 3 2
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    void nextPermutation(vector<int>& nums) {
        int pivot = static_cast<int>(nums.size()) - 2;
        while (pivot >= 0 && nums[pivot] >= nums[pivot + 1]) --pivot;
        if (pivot >= 0) {
            int successor = static_cast<int>(nums.size()) - 1;

            /*找刚刚比pivot大的那个数*/
            while (nums[successor] <= nums[pivot]) --successor;

            swap(nums[pivot], nums[successor]);
        }
        /*尾部本来就是有序非递减数组， 因此可以直接倒过来即可*/
        reverse(nums.begin() + pivot + 1, nums.end());
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    sol.nextPermutation(a);
    for (int i = 0; i < n; ++i) cout << a[i] << " \n"[i + 1 == n];
    return 0;
}
