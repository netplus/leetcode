// ============================================================================
// LC-685：冗余连接 II
// 难度：困难
// 优先级：P1（进阶）
// 学习进度：第 3 周 / 第 17 天
// ----------------------------------------------------------------------------
// 题目描述：
// 在本问题中，有根树指满足以下条件的有向图。
// 该树只有一个根节点，所有其他节点都是该根节点的后继。
// 该树除了根节点之外的每一个节点都有且只有一个父节点，而根节点没有父节点。
// 输入一个有向图，该图由一个有着 n 个节点（节点值不重复，从 1 到 n）的树及一条附加的有向边构成。
// 附加的边包含在 1 到 n 中的两个不同顶点间，这条附加的边不属于树中已存在的边。
// 结果图是一个以边组成的二维数组 edges。
// 每个元素是一对 [u_i, v_i]，用以表示有向图中连接顶点 u_i 和顶点 v_i 的边，其中 u_i 是 v_i 的一个父节点。
// 返回一条能删除的边，使得剩下的图是有 n 个节点的有根树。
// 若有多个答案，返回最后出现在给定二维数组的答案。
//
// 题目示例：
// 示例 1：
//   Input: edges = [[1,2],[1,3],[2,3]]
//   Output: [2,3]
//
// 示例 2：
//   Input: edges = [[1,2],[2,3],[3,4],[4,1],[1,5]]
//   Output: [4,1]
//
// 约束与要求：
//   - n == edges.length
//   - 3 <= n <= 1000
//   - edges[i].length == 2
//   - 1 <= u_i, v_i <= n
//
// 复杂度目标：O(n) 并查集。
//
// ----------------------------------------------------------------------------
// 解法精讲｜有向树修复：先分类二父冲突，再用 DSU 验证是否仍有环
//
// 前置概念
//   有根有向树可以先用结构条件定义：
//   1. 恰好一个根节点，根的入度为 0；
//   2. 其它每个节点入度都恰好为 1，也就是只有一个父节点；
//   3. 从根可以沿有向边到达所有节点；
//   4. 不存在有向环。
//
//   边 parent -> child 表示父子方向。原题保证输入是在一棵这样的树上额外加入一条边，因此额外边造成的核心异常只会集中在“某节点出现两个父亲”或“形成环”这两类结构破坏上。
//
// 0. 优化是怎么来的
//   最直接的正确方法，是依次尝试删除每一条边；每次删除后重新检查剩余 n-1 条边是否构成一棵有根树：恰好一个根、其余节点各一个父亲、所有节点可达且无环。这样容易理解，但每个候选都要重新验证整张图，最坏 O(n^2)。
//
//   要减少重复验证，先利用“原始输入 = 一棵有根树 + 恰好一条额外边”这个强条件。额外边造成的破坏不可能任意复杂，只会落入：
//   1. 没有节点二父：那唯一问题就是一个环，退化成 LC-684；
//   2. 某节点有两个父亲：真正答案只可能是指向这个节点的两条入边之一。
//
//   于是候选从 n 条边缩成至多 2 条。把较晚的二父边 later 暂时跳过，再用 DSU 重放其余边：
//   - 若没有环，删 later 就已经恢复树；
//   - 若仍有环，说明 earlier 位于那个环中，必须删 earlier；
//   - 若根本没有二父，则直接返回 DSU 检出的成环边。
//
//   优化类型：枚举所有删除候选 + 重复整图验证 -> 先用局部结构约束把候选压缩到 1~2 条，再复用 LC-684 的判环器做一次验证。
//
// 1. 图像直觉
//   情况 A：只有二父，没有环
//
//   1 -> 2
//   3 -> 2
//
//   节点 2 有两条父边：
//   earlier = 1->2
//   later   = 3->2
//
//   先假设删除 later。
//   重放其余边若没有环：
//   => later 就是答案。
//
//   情况 B：二父 + 环
//
//   1 -> 2 -> 3
//   ^         |
//   |         v
//   +---------+
//   再额外有 4 -> 2
//
//   2 有两个父亲。
//   如果跳过较晚的 4->2，旧环仍然存在：
//   => 问题不是 later；
//   => earlier 那条指向 2 的边同时参与了环，必须删 earlier。
//
//   情况 C：没有二父
//   => 每点父节点数量正常，唯一可能破坏就是环
//   => 完全退化为 LC-684。
//
// 2. 一句话核心
//   先用“一个节点不能有两个父亲”把候选缩成两条；再假删较晚边并用 DSU 判环：仍有环删早边，无环删晚边；没有二父时直接删成环边。
//
// 3. 公式 / 不变量
//   若某节点 v 第一次收到父边 e1=[p1,v]，后来又收到 e2=[p2,v]：
//   earlier = e1
//   later   = e2
//
//   第二阶段跳过 later，按输入顺序对其他边做 DSU：
//
//   若出现 find(u)==find(v)：
//   - earlier 不存在：无二父，返回当前成环边；
//   - earlier 存在：跳过 later 后仍有环，返回 earlier。
//
//   若全部边重放完都无环：
//   说明跳过 later 后已经是一棵合法有根树
//   => 返回 later。
//
//   候选压缩依据：只有一个额外边，因此至多一个节点会出现入度 2。
//
// 4. 执行步骤
//   1. 第一遍用 directParent[to] 记录每个节点第一次见到的父亲；若同一 to 再出现，记录 earlier 与 later 两条候选边下标
//   2. 重新初始化 DSU，第二遍按原顺序重放所有边，但暂时跳过 later；DSU 只负责判断忽略方向后的环
//   3. 若重放过程中出现同根：没有二父候选时直接返回当前边；存在二父候选时返回 earlier
//   4. 若跳过 later 后所有边都未成环，说明删除 later 已同时解决二父问题并恢复树，返回 later
//   5. 整个过程只做常数次线性扫描，不修改原有正确算法结构
//   记忆：先查二父，再假删后来的父边；假删后还成环 -> 删早边，不成环 -> 删晚边；无二父 -> LC-684。
//
// 5. 为什么不会漏 / 不会重
//   若没有二父节点，那么所有非根节点的入度结构没有被额外边破坏，唯一可能使结果不是有根树的因素就是环，LC-684 判出的成环边即答案。若存在二父节点 v，删除任何不指向 v 的边都无法消除 v 的两个父亲，因此答案只能是 earlier/later。假删 later 后：若图无环，剩余 n-1 条边且每个节点至多一个父亲，结合题目由树加一边的保证，得到合法有根树，所以 later 正确；若仍有环，later 不在当前重放图中，因此删除 later 不能修复，唯一剩余候选 earlier 必须同时位于环上，删它才能同时解除二父与环。
//
// 6. 边界与易错点
//   DSU 在这里不是判断“有向环”的通用算法；它之所以可用，是因为题目具有“有根树 + 一条额外边”的特殊结构，我们先处理了入度 2，再把剩余候选交给无向连通/成环判定。不要忽略返回输入中靠后的合法答案这一语义。当前实现为了找到 earlier 又向前扫描一次，n<=1000 完全可接受；教学重点是分类逻辑而不是这处常数优化。
//
// 7. 举一反三
//   这题展示了复杂题的常见拆法：先找违反的局部结构约束，把候选集合大幅缩小；再复用已经学会的简单判定器验证候选。LC-684 提供 DSU 判环，LC-685 只新增“每个节点最多一个父亲”的分类层。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：m (边数，等于 n)。
//   接下来 m 行：u v (u 是 v 的父节点)。
//   输出：冗余边 "u v"。
// test.in 的预期输出：2 3
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> findRedundantDirectedConnection(vector<vector<int>>& edges) {
        const int n = static_cast<int>(edges.size());

        // 第一阶段只处理“每个非根节点最多一个父亲”这条有根树结构约束。
        // directParent[v]==0 表示 v 还没见过父边；否则再次出现 -> v 就是唯一可能的二父节点。
        vector<int> directParent(n + 1, 0);
        int earlier = -1, later = -1;

        for (int i = 0; i < n; ++i) {
            int from = edges[i][0], to = edges[i][1];
            if (directParent[to] == 0) {
                directParent[to] = from;
            } else {
                // 当前 i 是较晚出现的第二条父边 later。
                // 再向前找到同样指向 to 的第一条父边 earlier；真正答案只可能在这两条边中。
                for (int j = 0; j < i; ++j) {
                    if (edges[j][1] == to) {
                        earlier = j;
                        break;
                    }
                }
                later = i;
                break;
            }
        }

        // 第二阶段复用 LC-684：把边方向暂时忽略，用 DSU 判断“剩余边是否还形成环”。
        vector<int> parent(n + 1);
        iota(parent.begin(), parent.end(), 0);
        function<int(int)> find = [&](int x) {
            return parent[x] == x ? x : parent[x] = find(parent[x]);
        };

        for (int i = 0; i < n; ++i) {
            // 若存在二父冲突，先假设删除较晚的 later；因此重放图时必须跳过它。
            if (i == later) continue;

            int a = find(edges[i][0]);
            int b = find(edges[i][1]);

            if (a == b) {
                // 没有二父候选：问题退化为 LC-684，当前边就是唯一闭环边。
                // 有二父候选：later 已被跳过却仍成环，说明 later 不是答案；必须删 earlier。
                return earlier == -1 ? edges[i] : edges[earlier];
            }

            // 当前边没有成环，才把两个集合合并，维持“此前重放边的连通性”不变量。
            parent[b] = a;
        }

        // 能走到这里说明：跳过 later 后整张图没有环。
        // 因而删除 later 已经同时解决了二父问题并恢复有根树。
        return edges[later];
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int m; if (!(cin >> m)) return 0;
    vector<vector<int>> e(m, vector<int>(2));
    for (int i = 0; i < m; ++i) cin >> e[i][0] >> e[i][1];
    auto ans = sol.findRedundantDirectedConnection(e);
    cout << ans[0] << " " << ans[1] << "\n";
    return 0;
}
