"""Generate exam-gap supplements without changing the 106-problem formal corpus.

These problems are added after real exam feedback exposes a missing capability.
They live in the normal Week/Day problem tree and use the same local judge, but
remain outside the original 4-week count so existing formal-corpus validation
stays stable.

Run:
    python3 tools/gen_exam_gaps.py          # write supplements
    python3 tools/gen_exam_gaps.py --check  # non-mutating fidelity check
"""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def comment_block(title: str, text: str) -> str:
    lines = [f"// {title}"]
    for line in text.strip("\n").splitlines():
        lines.append(f"//   {line}" if line else "//")
    return "\n".join(lines)


def render_analysis(p: dict) -> str:
    sections = [
        ("1. 题目直觉 / 图形模型", p["visual"]),
        ("2. 最自然的一般性解法", p["general_solution"]),
        ("3. 一般解法的问题与限制", p["limitations"]),
        ("4. 从具体问题抽象规律", p["generalization"]),
        (f"5. 专项算法｜{p['pattern']}", p["algorithm_background"]),
        ("6. 核心算法", p["core"]),
        ("7. 公式 / 不变量", p["formula"]),
    ]
    out = [
        "// ----------------------------------------------------------------------------",
        "// 解法精讲｜从题目直觉到可复用算法",
        "//",
    ]
    for title, text in sections:
        out.append(comment_block(title, text))
        out.append("//")

    out.append("// 8. 执行步骤")
    for i, step in enumerate(p["steps"], 1):
        out.append(f"//   {i}. {step}")
    out.append(f"//   记忆：{p['memory']}")
    out.append("//")
    out.append(comment_block("9. 为什么不会漏 / 不会重", p["proof"]))
    out.append("//")
    out.append(comment_block("10. 边界与易错点", p["pitfalls"]))
    out.append("//")
    out.append(comment_block("11. 举一反三", p["transfer"]))
    out.append("// ----------------------------------------------------------------------------")
    return "\n".join(out)


def render_solution(p: dict) -> str:
    examples = []
    for i, example in enumerate(p["examples"], 1):
        examples.extend([
            f"// 题目示例 {i}：",
            f"//   Input:  {example['input']}",
            f"//   Output: {example['output']}",
        ])
        if example.get("explanation"):
            examples.append(f"//   Explanation: {example['explanation']}")
        examples.append("//")

    constraints = "\n".join(f"//   - {line}" for line in p["constraints"])
    description = "\n".join(f"// {line}" for line in p["description"])
    iofmt = "\n".join(f"//   {line}" for line in p["iofmt"])
    body = f"""// ============================================================================
// LC-{p['num']}：{p['title']}
// 难度：{p['difficulty']}
// 优先级：{p['priority']}（考试查漏补缺）
// 学习进度：第 {p['week']} 周 / 第 {p['day']} 天（补充题）
// ----------------------------------------------------------------------------
// 题目描述：
{description}
//
{chr(10).join(examples).rstrip()}
//
// 约束与要求：
{constraints}
//
// 复杂度目标：{p['goal']}
//
{render_analysis(p)}
//
// 本地输入输出格式（用于 test.in）：
{iofmt}
// test.in 的预期输出：{p['expected']}
// ============================================================================
#include <bits/stdc++.h>
using namespace std;

{p['code'].strip()}

// ---------- 本地测试适配器 ----------
{p['main'].strip()}
"""
    return body.rstrip("\n") + "\n"


def render_makefile(p: dict) -> str:
    return f"""# Auto-generated by tools/gen_exam_gaps.py — safe to re-run.
# Problem: LC-{p['num']} {p['title']}
#
#   make            compile ./sol   (alias: make build)
#   make test       judge ALL cases via the central judge
#   make run        build & run ./sol on test.in (quick smoke)
#   make clean      remove ./sol

SRC := solution.cpp
BIN := sol
NUM := {p['num']}

CXX      := g++
CXXFLAGS := -std=c++17 -O2 -Wall -Wextra

ROOT  := $(abspath $(CURDIR)/../../..)
JUDGE := $(ROOT)/tools/judge.sh
PCH   := $(ROOT)/.build/all.h.gch

PCHFLAGS :=
ifneq ($(wildcard $(PCH)),)
PCHFLAGS := -include $(ROOT)/.build/all.h -I $(ROOT)/.build
endif
CXXFLAGS += $(PCHFLAGS)

.PHONY: all build test judge run clean

all build: $(BIN)

$(BIN): $(SRC) $(wildcard $(SRC:.cpp=.h))
\t$(CXX) $(CXXFLAGS) $(SRC) -o $(BIN)

test judge:
\t@bash "$(JUDGE)" $(NUM)

run: build
\t@if [ -f test.in ]; then \\
\t    echo "--- test.in ---"; cat test.in; \\
\t    echo "--- stdout ---"; ./$(BIN) < test.in; \\
\telse echo "(no test.in)"; ./$(BIN); fi

clean:
\trm -f $(BIN)
"""


