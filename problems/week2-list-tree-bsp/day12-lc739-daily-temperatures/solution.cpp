// ============================================================================
// LC-739：每日温度
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 2 周 / 第 12 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个整数数组 temperatures，表示每天的温度，返回一个数组 answer，其中 answer[i] 是指对于第 i 天，下一个更高温度出现在几天后。
// 如果气温在这之后都不会升高，请在该位置用 0 来代替。
//
// 题目示例：
// 示例 1：
//   Input: temperatures = [73,74,75,71,69,72,76,73]
//   Output: [1,1,4,2,1,1,0,0]
//
// 示例 2：
//   Input: temperatures = [30,40,50,60]
//   Output: [1,1,1,0]
//
// 示例 3：
//   Input: temperatures = [30,60,90]
//   Output: [1,1,0]
//
// 约束与要求：
//   - 1 <= temperatures.length <= 10^5
//   - 30 <= temperatures[i] <= 100
//
// 复杂度目标：O(n) 时间（单调栈）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜单调递减栈：把向未来重复搜索改成未决问题一次结算
//
// 0. 优化是怎么来的
//   最直接的做法，是对每一天 i 向右逐日寻找第一个更高温度；最坏每个位置都要扫描很远，总时间 O(n^2)。
//
//   这个暴力算法真正重复的是“为很多历史位置重新向未来扫描”。换成从左到右后，只保存答案还没有确定的历史日期；当前温度如果第一次高过某个未决日期，就可以立即结算它，不必以后再搜索。
//
//   为了让当前温度只检查仍有必要等待的候选，把已经能够结算的更冷日期从栈顶连续弹出。栈的单调性是这些未决问题被逐步结算后的结果，而不是算法的出发点。
//
//   优化类型：每个位置向未来重复搜索 -> 保存未决状态，由未来事件一次结算。每个下标只入栈/出栈一次，O(n)。
//
// 1. 图像直觉
//   先不要想“递减栈”，先看暴力算法在重复什么。
//
//   对每一天 day，最自然的做法是向右逐日扫描，直到找到第一个严格更暖的日期：
//
//   for each day:
//       scan day+1, day+2, ...
//       stop at first warmer day
//
//   不同 day 会反复扫过大量相同位置。换成从左到右后，只需要保存“已经出现、但答案还没有确定”的日期。
//
//   temperatures = [73, 74, 75, 71, 69, 72, 76]
//
//   扫描到 72 前，未决日期可能是：
//   下标       2    3    4
//   温度      75   71   69
//              |    |    |
//             等待  等待  等待
//
//   72 到来：
//   69 < 72 -> 69 第一次等到更暖日，答案确定，pop
//   71 < 72 -> 71 第一次等到更暖日，答案确定，pop
//   75 > 72 -> 75 仍然未决，停止
//
//   所以 pop 的原因不是“为了把栈排好序”，而是这个历史问题已经被当前元素解决。剩余未决元素自然呈现温度单调不增。
//
// 2. 一句话核心
//   栈保存的不是一组需要排序的温度，而是一组“还没找到右侧第一个更暖日”的历史问题；当前温度第一次能解决谁，就把谁结算并弹出。
//
// 3. 公式 / 不变量
//   扫描到 day 前：
//   pending = 尚未找到右侧第一个严格更暖日期的历史下标
//   T[pending] 从栈底到栈顶单调不增
//
//   若：
//   T[day] > T[pending.top()]
//
//   则当前 day 就是栈顶日期的第一个更暖日：
//   previous = pending.top()
//   answer[previous] = day - previous
//   pop(previous)
//
//   相等不能弹，因为题目要求 strictly warmer。
//   默认存 index 而不是只存温度，因为答案需要位置差 day-previous。
//
// 4. 执行步骤
//   1. 先从题意写出“每一天向右找第一个更暖日”的 O(n^2) 基线，并识别重复的向右搜索
//   2. 从左到右扫描，把尚未找到答案的历史下标保存在 pending；当前温度严格更高时，反复结算并弹出栈顶
//   3. 把当前 day 压栈，表示它从此也成为一个等待未来更暖日来结算的未决问题；扫描结束仍未决的位置保持答案 0
//   记忆：先问“栈顶在等什么、为什么恰好现在能解决”，最后再观察栈是递增还是递减；单调性是未决候选被不断结算后的结果。
//
// 5. 为什么不会漏 / 不会重
//   为什么 day 是被弹日期的第一个更暖日？因为我们按时间从左到右扫描；若中间更早出现过严格更暖日，该下标已经在那个时刻被弹，不可能继续留到现在。
//   为什么可以连续弹？当前温度如果高于栈顶，就能解决这个最近的未决日期；弹掉后继续检查新的栈顶，直到剩余问题都不能由当前温度解决。
//   每个下标只入栈一次、出栈至多一次，所以所有 while 的总 pop 数不超过 n，整体是摊还 O(n)。
//
// 6. 边界与易错点
//   必须存下标而非只存温度，因为答案是天数差；比较条件必须是 `>` 而不是 `>=`；不要把 pop 解释成单纯维护排序；也不要看到 for+while 就误判 O(n^2)，应按每个下标的完整生命周期做摊还分析。
//
// 7. 举一反三
//   LC-739 是单调栈第一层：pop 时确定一个右侧答案。LC-84 在此基础上升级为边界题：pop 时确定右侧阻挡位置，pop 后的新栈顶再提供左侧阻挡信息；再往后，子数组 min/max 贡献题会把左右边界距离乘起来统计贡献。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：n 个以空格分隔的等待天数。
// test.in 的预期输出：1 1 4 2 1 1 0 0
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> dailyTemperatures(vector<int>& temperatures) {
        // 默认 0 正好代表“直到末尾都没有更暖日期”；只有被未来事件结算的下标才会改写。
        vector<int> answer(temperatures.size(), 0);

        // pending 存“还没找到第一个更暖日期”的历史下标。
        // 下标从底到顶递增，对应温度单调不增；栈顶是最近、最先有机会被当前温度结算的日期。
        stack<int> pending;

        for (int day = 0; day < static_cast<int>(temperatures.size()); ++day) {
            // 当前温度严格高于栈顶时，day 就是该历史日期第一次遇到的更暖日：
            // 若更早已有答案，它早已在当时被弹栈，不可能继续留在 pending。
            // 相等温度不能弹，因为题目要求 strictly warmer。
            while (!pending.empty() && temperatures[day] > temperatures[pending.top()]) {
                const int previous = pending.top();
                pending.pop();

                // pending 存的是下标而非温度，正是为了直接得到等待天数 day-previous。
                answer[previous] = day - previous;
            }

            // 当前日期暂时不知道未来答案，加入未决集合；以后由第一个严格更暖的日期负责结算。
            pending.push(day);
        }

        // 扫描结束仍留在栈中的日期从未遇到更暖日，保持初始化的 0。
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    auto ans = sol.dailyTemperatures(a);
    for (size_t i = 0; i < ans.size(); ++i) cout << ans[i] << " \n"[i + 1 == ans.size()];
    return 0;
}