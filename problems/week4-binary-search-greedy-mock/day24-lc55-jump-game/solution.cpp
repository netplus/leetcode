// ============================================================================
// LC-55：跳跃游戏
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 4 周 / 第 24 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个非负整数数组 nums，你最初位于数组的第一个下标。
// 数组中的每个元素代表你在该位置可以跳跃的最大长度。
// 判断你是否能够到达最后一个下标，如果可以，返回 true；否则，返回 false。
//
// 题目示例：
// 示例 1：
//   Input: nums = [2,3,1,1,4]
//   Output: true
//   Explanation: Jump 1 step from index 0 to 1, then 3 steps to the last index.
//
// 示例 2：
//   Input: nums = [3,2,1,0,4]
//   Output: false
//   Explanation: You will always arrive at index 3 no matter what. Its maximum jump length is 0, which makes it impossible to reach the last index.
//
// 约束与要求：
//   - 1 <= nums.length <= 10^4
//   - 0 <= nums[i] <= 10^5
//
// 复杂度目标：O(n) 时间，O(1) 空间（贪心）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜贪心前沿：把所有可达路径压缩成最远可达位置
//
// 0. 优化是怎么来的
//   最自然的正确做法是 DFS/BFS：从每个可达位置 i 枚举 1..nums[i] 的所有下一跳，直到到达末尾或搜索完所有状态。它不会漏掉任何路径，但同一个位置可能由很多不同跳法到达，而且从这些路径继续向后的能力只由‘当前下标’决定；枚举具体路径制造了大量重复状态。
//
//   进一步观察，这题甚至不必为每个可达下标保存 visited。因为每次从可达位置 i 可以跳到 i+1..i+nums[i]，所有已发现位置会形成一个连续前缀 [0,farthest]。对于“是否最终可达”这个问题，前缀内部到底经由哪条路径到达已经失去意义；未来只需要知道最右边界 farthest。
//
//   于是把整片搜索状态压缩成一个整数：扫描所有 i<=farthest 的位置，并持续扩大 farthest。若扫描下标第一次超过 farthest，说明出现了不可跨越的空隙；若 farthest 覆盖 n-1，则成功。优化类型：重复状态消除 + 候选状态压缩。
//
// 1. 图像直觉
//   nums = [2,3,1,1,4]
//
//   起点 0：最多到 2
//   可达前缀：
//   [0 1 2] 3 4
//        ^ farthest=2
//
//   扫描 i=1，它本身已在可达前缀内：
//   1 + nums[1] = 4
//
//   可达前缀扩成：
//   [0 1 2 3 4]
//           ^ farthest=4
//
//   此时已经覆盖终点。
//
//   反例 nums=[3,2,1,0,4]：
//   前沿最终停在 3。
//   扫描到 i=4 时：
//   0 1 2 3 | 4
//         farthest=3
//             i=4 > farthest
//   出现缺口，任何具体跳法都跨不过去。
//
// 2. 一句话核心
//   不枚举怎么跳，只维护所有已知可达路径共同产生的最右前沿 farthest；能扫描到的点负责继续扩张前沿。
//
// 3. 公式 / 不变量
//   初始 farthest = 0。
//
//   扫描位置 i 前：
//   i <= farthest  <=>  i 已被某条路径覆盖，可以作为下一跳起点。
//
//   若 i > farthest：
//       当前连续可达前缀已经结束，返回 false。
//
//   否则：
//   farthest = max(farthest, i + nums[i])。
//
//   不变量：处理完下标 0..i 后，farthest 是只使用这些已处理起点能够到达的最远位置，并且 [0,farthest] 是连续可达的。
//
//   若 farthest >= n-1，返回 true。
//
// 4. 执行步骤
//   1. 令 farthest=0，表示起点本身已可达
//   2. 从左到右扫描 i；先检查 i 是否超过 farthest，超过则说明没有任何已知路径能到这里，立即失败
//   3. 只有确认 i 可达后，才用 i+nums[i] 更新 farthest，把从 i 出发新增的覆盖范围并入全局前沿
//   4. 一旦 farthest>=n-1 就立即成功；否则扫描结束后也说明所有位置均未出现缺口
//   记忆：路径不重要，可达前缀才重要：i 进得了前沿，才有资格把前沿推得更远。
//
// 5. 为什么不会漏 / 不会重
//   归纳来看，初始 [0,0] 可达。若 i<=farthest，则 i 位于已有连续可达前缀中，所以存在一条路径到 i；从 i 可到达 i..i+nums[i]，与原前缀相交，因此合并后仍是连续前缀 [0,newFarthest]。反之若 i>farthest，所有已经能作为起点的位置都已扫描过，而它们的最远贡献仍到不了 i；后面的下标自身也尚不可达，无法凭空产生新的跳跃，因此这个缺口永远无法跨越。只保留 farthest 不会漏掉任何可达性信息。
//
// 6. 边界与易错点
//   必须先确认 i<=farthest 再使用 nums[i]，否则会让一个实际不可达的位置错误扩张前沿。长度为 1 时起点就是终点。现有实现用 long long 保存 farthest 与 i+nums[i]，在更大约束下也避免加法溢出。
//
// 7. 举一反三
//   LC-45 在同一前沿模型上增加‘最少跳几次’：不能只保留全局 farthest，还要记录当前跳数这一层的边界 currentEnd。图论视角上，LC-55 把 BFS 的所有已发现节点压成一个连续区间；这种‘状态集合可由边界完整表示’的压缩思想也会出现在区间覆盖问题。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：能到达最后一个下标时输出 1，否则输出 0。
// test.in 的预期输出：1
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    bool canJump(vector<int>& nums) {
        // farthest 压缩了所有已知路径：当前已经证明连续前缀 [0,farthest] 全部可达。
        long long farthest = 0;
        for (int i = 0; i < static_cast<int>(nums.size()); ++i) {
            // 只有已经落在可达前缀中的位置才有资格贡献下一跳；
            // 第一次出现 i>farthest 时形成永久缺口，后面的未达位置不可能反过来扩张前沿。
            if (i > farthest) return false;

            // 把当前可达起点 i 的最远落点并入总前沿；中间所有更短落点都已经被连续前缀包含。
            farthest = max(farthest, static_cast<long long>(i) + nums[i]);
            if (farthest >= static_cast<int>(nums.size()) - 1) return true;
        }
        return true;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << (sol.canJump(a) ? 1 : 0) << "\n";
    return 0;
}
