// ============================================================================
// LC-56：合并区间
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 6 天
// ----------------------------------------------------------------------------
// 题目描述：
// 以数组 intervals 表示若干个区间的集合，其中单个区间为 intervals[i] = [start_i, end_i]。
// 请你合并所有重叠的区间，并返回一个不重叠的区间数组，该数组需恰好覆盖输入中的所有区间。
//
// 约束与要求：
//   - 1 <= intervals.length <= 10^4
//   - intervals[i].length == 2
//   - 0 <= start_i <= end_i <= 10^4
//
// 复杂度目标：O(m log m) 时间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜排序后线性合并区间
//
// 0. 优化是怎么来的
//   一种直接做法，是反复寻找任意一对重叠区间，把它们合并后再从头检查；虽然正确，但同一批区间可能被多轮重新比较，最坏接近 O(m^2)。
//
//   真正困难的原因是输入无序：一个刚合并好的区间，不知道后面是否还有起点更靠左的区间回来与它相接。按起点排序后，这种“未来回头”被消除了。
//
//   此时只需维护一个尚未封口的当前并集 [L,R]：新区间能接上就扩 R；一旦 start>R，后面所有 start 只会更大，旧并集永久不可能再被连接，可以立即输出。
//
//   优化类型：重复全局重扫 -> 排序后维护一个可延续的活动区间；全局合并被压缩为 O(m log m)+O(m)。
//
// 1. 图像直觉
//   把排序后的区间想成从左向右扫一条数轴，并维护一个正在生长的“当前并集”。
//
//   intervals = [[1,3],[2,6],[8,10],[9,12]]
//
//   先拿 [1,3]：
//   [1-----3]
//
//   看到 [2,6]，2 <= 3，碰到了当前并集：
//   [1-----3]
//      [2---------6]
//   => [1-----------6]
//
//   再看到 [8,10]，8 > 6，中间出现真正的空隙：
//   [1-----------6]   [8----10]
//                     ^
//   此时 [1,6] 可以“封口”了；因为后面的区间起点只会更大，不可能再回来碰到它。
//
//   所以扫描过程中只有两种事件：
//   1. start <= currentEnd：继续把当前并集向右撑大；
//   2. start > currentEnd：旧并集封口，开启新的一段。
//
// 2. 一句话核心
//   排序后只维护最后一个已合并区间；新区间能碰到它就扩右端，碰不到就说明出现永久空隙，开启新的合并段。
//
// 3. 公式 / 不变量
//   answer.back() = [L,R]，当前区间 = [s,e]。
//
//   若 s <= R：两区间重叠或端点相接
//   [L,R] U [s,e] = [L, max(R,e)]
//
//   若 s > R：出现空隙
//   [L,R] 已经最终确定
//   新段从 [s,e] 开始
//
//   关键不变量：
//   answer 中除最后一段外都已经封口；最后一段是所有已扫描且仍连通区间的并集。
//
// 4. 执行步骤
//   1. 按区间起点排序，使后续 start 单调不减
//   2. answer 为空时，把当前区间直接作为第一段
//   3. 若 interval.start > answer.back().end，说明存在空隙，把当前区间作为新段加入 answer
//   4. 否则两段相交，把 answer.back().end 更新为 max(oldEnd, interval.end)
//   5. 扫描结束后，answer 中每一段都是一个已经封口的连通并集
//   记忆：能接上就扩右端；出现空隙就封口开新段。
//
// 5. 为什么不会漏 / 不会重
//   排序后，一旦某个新区间的 start 已经大于当前合并段 R，之后所有区间的 start 只会更大，所以没有任何未来区间能跨过这个空隙重新连接旧段，旧段可以安全封口；若 s <= R，则新区间与当前并集共享至少一个点，取 max(R,e) 恰好得到两者并集。每个原区间只被归入当前连通块一次，因此既不漏覆盖，也不会重复输出。
//
// 6. 边界与易错点
//   题目区间是闭区间，端点相等也算重叠，所以只有 start > lastEnd 才能开新段；不能写成 >=。排序会修改 intervals。不要只和原数组的前一个区间比较后直接输出，因为前面若已经合并，真正应该比较的是不断扩张后的 answer.back()。
//
// 7. 举一反三
//   直接复用 LC-252 的“排序让关系局部化”：LC-252 遇到重叠就失败，LC-56 遇到重叠则把状态 [L,R] 扩大。下一题 LC-57 输入已经排序且互不重叠，本质上是在这条扫描线上只对 newInterval 附近做一次局部 LC-56。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：m (区间数量)。
//   接下来 m 行：start end。
//   每行输出一个合并后的区间 start end，并按起点升序排列。
// test.in 的预期输出：1 6 | 8 10 | 15 18
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<vector<int>> merge(vector<vector<int>>& intervals) {
        sort(intervals.begin(), intervals.end());
        vector<vector<int>> answer;
        for (const auto& interval : intervals) {
            if (answer.empty() || interval[0] > answer.back()[1]) {
                answer.push_back(interval);
            } else {
                answer.back()[1] = max(answer.back()[1], interval[1]);
            }
        }
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int m; if (!(cin >> m)) return 0;
    vector<vector<int>> iv(m, vector<int>(2));
    for (int i = 0; i < m; ++i) cin >> iv[i][0] >> iv[i][1];
    auto res = sol.merge(iv);
    for (auto& x : res) cout << x[0] << " " << x[1] << "\n";
    return 0;
}

