// ============================================================================
// LC-70：爬楼梯
// 难度：简单
// 优先级：P0（必做）
// 学习进度：第 3 周 / 第 18 天
// ----------------------------------------------------------------------------
// 题目描述：
// 假设你正在爬楼梯。
// 需要 n 阶你才能到达楼顶。
// 每次你可以爬 1 或 2 个台阶。
// 你有多少种不同的方法可以爬到楼顶呢？
//
// 约束与要求：
//   - 1 <= n <= 45
//
// 复杂度目标：O(n) 时间，O(1) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜线性 DP 入门：从重复递归到只保存前两个已解子问题
//
// 0. 优化是怎么来的
//   最自然的正确解法是直接递归：
//
//   ways(i) = ways(i-1) + ways(i-2)
//
//   它为什么正确？任何到达 i 的方案，最后一步不是 1 阶就是 2 阶，两类互斥且覆盖全部方案。
//
//   问题出在递归树会重复计算同一个子问题。例如 ways(5) 会展开 ways(4) 和 ways(3)，而 ways(4) 内部又会再次计算 ways(3)。随着 n 增大，同一 ways(k) 会从很多祖先路径反复出现，时间呈指数增长。
//
//   第一次优化是把已经算过的 ways(k) 保存下来：重复子问题 -> 记忆化 / DP。若自底向上计算，ways[1], ways[2] 已知后，每个 ways[i] 只算一次，时间降为 O(n)。
//
//   再看依赖关系：计算 ways[i] 时只读取 ways[i-1] 和 ways[i-2]，更早状态以后永远不会再被使用。因此整张 O(n) 数组也不是必须的，只保留 previous1/previous2 即可。
//
//   优化链：指数递归中的重复子问题 -> 每个状态只算一次 -> 只依赖前两项 -> O(1) 滚动状态。这最后才叫线性 DP + 状态压缩。
//
// 1. 图像直觉
//   以 n=5 为例，只画“最后一步从哪里来”：
//
//   ways(3) ----\
//                 +--> ways(5)
//   ways(4) ----/
//
//   更具体地：
//   到第 5 阶的方案最后一步只有两类：
//
//   ... -> 4 -> 5   （最后走 1 阶）
//   ... -> 3 -> 5   （最后走 2 阶）
//
//   所以：
//   ways(5) = ways(4) + ways(3)
//
//   滚动计算时只需要一条很短的传送带：
//
//   step=3 前： previous2=ways(1), previous1=ways(2)
//   算 current=ways(3)
//   然后整体前移：
//   previous2 <- old ways(2)
//   previous1 <- ways(3)
//
//   下一轮再用 ways(2), ways(3) 算 ways(4)。
//   更早的 ways(1) 已经失去未来用途，可以永久丢弃。
//
// 2. 一句话核心
//   把“到当前阶的全部走法”按最后一步拆成两个互斥来源；每个子问题只算一次，而未来只依赖最近两项，所以只滚动保留两个状态。
//
// 3. 公式 / 不变量
//   状态定义：
//   ways[i] = 恰好到达第 i 阶的方法数。
//
//   边界：
//   ways[1] = 1
//   ways[2] = 2
//
//   对 i >= 3：
//   ways[i] = ways[i-1] + ways[i-2]
//
//   滚动不变量：进入 step=i 时：
//   previous2 = ways[i-2]
//   previous1 = ways[i-1]
//
//   计算：
//   current = previous1 + previous2
//   然后前移：
//   previous2 = previous1
//   previous1 = current。
//
// 4. 执行步骤
//   1. 先处理 n<=2，答案就是 n；这同时固定递推的两个初始状态
//   2. 令 previous2=ways(1)=1、previous1=ways(2)=2；明确两个变量对应的状态位置
//   3. 从 step=3 到 n，先用旧 previous1/previous2 计算 current，不能在计算前覆盖任一旧值
//   4. 计算完成后再执行 previous2=previous1、previous1=current，让两个变量向前滚动一格
//   5. 循环结束时 previous1 恰好代表 ways(n)，直接返回
//   记忆：先问最后一步从哪来；重复子问题只算一次；未来只看两项，就只留两项。
//
// 5. 为什么不会漏 / 不会重
//   任何到 i 的完整路径按最后一步长度唯一分成两类：最后走 1 阶的路径，与到 i-1 的路径一一对应；最后走 2 阶的路径，与到 i-2 的路径一一对应。两类不相交，因此数量可直接相加。自底向上按 i 递增时两个依赖状态已经正确；滚动变量只删除以后不会再访问的更早项，不改变递推结果，所以既不会漏方案也不会重复计数。
//
// 6. 边界与易错点
//   状态必须定义成“到达第 i 阶的方法数”，不要在中途又把变量解释成“还剩多少阶”。n=1 不能强行访问第二个基线。滚动更新必须先算 current，再移动 previous2/previous1；若先覆盖 previous2 或 previous1，就会丢失当前递推仍需要的旧值。n<=45 时 int 足够。
//
// 7. 举一反三
//   这是 Day 18 的 DP 母模型：先定义一个能完整描述前缀子问题的状态，再找它依赖哪些更小状态。LC-746 保留完全相同的“只依赖前两项”骨架，只把“方案数相加”改成“两个来源取最小成本”；LC-198 则把两个来源改成“选当前 / 不选当前”。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   输出：方案数。
// test.in 的预期输出：3
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int climbStairs(int n) {
        // ways[1]=1、ways[2]=2 是滚动递推的两个基线；n<=2 时可直接返回，避免访问不存在的第二状态。
        if (n <= 2) return n;

        // 进入 step=3 前保持不变量：previous2=ways[1]，previous1=ways[2]。
        // 后续进入任意 step=i 时，它们分别代表 ways[i-2] 与 ways[i-1]。
        int previous2 = 1, previous1 = 2;

        for (int step = 3; step <= n; ++step) {
            // 到 step 的最后一步只能来自 step-1 或 step-2，两类方案互斥，因此直接相加。
            // 必须先用两个“旧状态”算出 current，之后才能覆盖 previous2/previous1。
            int current = previous1 + previous2;

            // 整体向前滚动一格：旧 ways[i-1] 成为下一轮的 ways[(i+1)-2]，
            // current 则成为下一轮的 ways[(i+1)-1]。
            previous2 = previous1;
            previous1 = current;
        }

        // 循环结束后 previous1 恰好对应 ways[n]。
        return previous1;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    cout << sol.climbStairs(n) << "\n";
    return 0;
}

