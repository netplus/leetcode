// ============================================================================
// LC-1109：航班预订统计
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 4 天
// ----------------------------------------------------------------------------
// 题目描述：
// 这里有 n 个航班，它们分别从 1 到 n 进行编号。
// 有一份航班预订表 bookings，表中第 i 条预订记录 bookings[i] = [first_i, last_i, seats_i] 意味着在从 first_i 到 last_i （包含
// first_i 和 last_i）的每个航班上预订了 seats_i 个座位。
// 请你返回一个长度为 n 的数组 answer，里面的元素是每个航班预定的座位总数。
//
// 约束与要求：
//   - 1 <= n <= 2 * 10^4
//   - 1 <= bookings.length <= 2 * 10^4
//   - bookings[i].length == 3
//   - 1 <= first_i <= last_i <= n
//   - 1 <= seats_i <= 10^4
//
// 复杂度目标：O(n + m) 使用 差分数组。
//
// ----------------------------------------------------------------------------
// 解法精讲｜从逐航班模拟到差分：把重复区间更新延迟展开
//
// 1. 图像直觉
//   第一步永远先写最直观的算法。
//
//   假设只有一条：
//   booking = [2,5,25]
//
//   朴素做法就是：
//   航班：      1    2    3    4    5    6
//   增加量：    0   25   25   25   25    0
//
//   也就是依次执行：
//   flight[2] += 25
//   flight[3] += 25
//   flight[4] += 25
//   flight[5] += 25
//
//   这个算法完全正确。差分只是在问：
//   既然 2..5 每个位置做的事情都一模一样，能不能不要立刻写 4 次？
//
//   可以。我们只记录“这份 +25 从哪里开始生效，以及从哪里开始不再生效”：
//
//   位置：      1    2    3    4    5    6
//   事件：      0   +25   0    0    0   -25
//
//   然后从左到右维护 running：
//   位置 1：running = 0
//   位置 2：running = 0 + 25 = 25
//   位置 3：running = 25 + 0 = 25
//   位置 4：running = 25 + 0 = 25
//   位置 5：running = 25 + 0 = 25
//   位置 6：running = 25 - 25 = 0
//
//   于是重新展开出来的增加量正好还是：
//   0, 25, 25, 25, 25, 0
//
//   这里最容易误解的是位置 6 上的 -25。
//   它绝不是说“6 号航班原本有 0 个座位，现在真的减掉 25”。
//   它只是一个控制 running 的结束事件：前面从位置 2 开始持续生效的 +25，到这里应该停止了，所以用 -25 把 running 从 25 恢复为 0。
//
//   如果没有这个 -25：
//   事件：      0   +25   0    0    0    0    0 ...
//   前缀累加：  0    25  25   25   25   25   25 ...
//
//   那么 +25 会错误地一直传到 6、7、8... 后面的所有位置。
//   所以右侧的 -25 本质上是“撤销之前开启的持续效果”，而不是对某个真实航班做一次负数更新。
//
//   再看大区间 booking=[2,10000,25]。
//   它表达的是：2..10000 全部 +25。
//   差分只记录：
//
//   2 号航班对应的位置：             +25   <- 开始生效
//   10000 号航班之后的边界：          -25   <- 到这里结束
//
//   如果题目恰好 n=10000，那么根本不存在 10001 号航班。
//   代码里的那个额外位置只是 diff 的哨兵槽位，用来承接“10000 号航班之后结束”这个事件；最终 answer 只读取 1..10000，不会输出这个哨兵位置。
//
//   因此更准确的图像不是：
//   “10001 号航班减 25”
//   而是：
//
//   2 号航班                  10000 号航班       右边界
//      |-----------------------------|               |
//     +25                                           -25
//      |<--------- +25 持续生效 --------->|          |
//
//   第二步，再从数学上看为什么只需两个事件。
//   若最终每点增加量为 A，则差分记录相邻位置的变化：
//
//   diff[0] = A[0]
//   diff[i] = A[i] - A[i-1]
//
//   对闭区间 [L,R] 整体 +x 后，区间内部任意相邻两点都会同时 +x：
//
//   (A[i] + x) - (A[i-1] + x)
//   = A[i] - A[i-1]
//
//   因此内部差值完全不变，只有：
//   进入区间：diff[L]     += x
//   离开区间：diff[R + 1] -= x
//
//   最后做一次前缀和，就是把这些“开始/结束事件”重新展开成最初那个逐航班累加的结果。
//
// 2. 一句话核心
//   差分就是把朴素的“区间内每个航班都 +=seats”延迟展开：左端的 +seats 开启一份持续影响，右端后一位的 -seats 负责撤销这份影响；这个 -seats 是结束事件，不是把某个真实航班减成负数。
//
// 3. 公式 / 不变量
//   先看朴素语义：
//   对 booking=[first,last,seats]，希望最终满足：
//   answer[first..last] 全部 += seats
//
//   差分把这段重复写入改成两个事件。
//   若使用 0-based 闭区间 [L,R]：
//
//   diff[L]     += seats      // 从 L 开始 running 多 seats
//   diff[R + 1] -= seats      // 从 R+1 开始撤销这份 seats
//
//   随后：
//   running += diff[i]
//   answer[i] = running
//
//   所以 -seats 的作用可以直接从 running 看：
//   在 L..R：running 包含这份 seats
//   到 R+1：running = running - seats
//   于是这条 booking 的影响从这里起归零。
//
//   本题输入是 1-based 的 [first,last]：
//   L = first - 1
//   R = last - 1
//   R + 1 = last
//
//   代码因此是：
//   first = booking[0] - 1
//   afterLast = booking[1]
//   diff[first]     += seats
//   diff[afterLast] -= seats
//
//   特别注意：当 last == n 时，afterLast == n 是 vector 中额外的哨兵下标，不对应任何真实航班。它只表示“最后一个航班之后，这份影响结束”。
//
// 4. 执行步骤
//   1. 先写出朴素模型：answer[flight-1]+=seats，flight 从 first 走到 last；先确认题目本质就是连续区间逐点加
//   2. 观察浪费：一条 booking 在连续很多个位置重复执行完全相同的 +=seats
//   3. 把这些重复写入延迟：在 first 对应位置记录 +seats，表示从这里开始生效
//   4. 在 last 后面的边界记录 -seats，表示撤销之前那份持续影响；不要理解成某个真实航班被减 seats
//   5. 所有 booking 的开始/结束事件叠加到同一个 diff 中
//   6. 最后从左到右 running+=diff[i]；running 就是当前位置所有仍然生效的 booking 贡献之和
//   7. 只把前 n 个 running 写入 answer；第 n 个额外 diff 槽位只可能是结束哨兵，不属于答案
//   记忆：先想朴素逐点加；差分只是把它压成两个开关：L 开启 +x，R 后面的边界用 -x 关掉。-x 是撤销持续效果，不是给那个位置算负数。
//
// 5. 为什么不会漏 / 不会重
//   拿单条 booking=[first,last,seats] 单独看：扫描到 first 前，running 中没有这份 seats；在 first 处遇到 +seats 后，running 多出 seats。first 到 last 之间没有任何事件撤销它，因此每个真实航班都得到这份 seats。走过 last 后，在 next boundary 遇到 -seats，running 恰好减回去，所以后续位置不再得到这份贡献。若 last=n，这个撤销事件虽然不会被 answer 扫描到，但把它放进 n+1 的 diff 能让区间表示保持统一且无需分支。多条 booking 只是把各自的开始/结束事件相加，线性叠加后与朴素逐航班修改完全等价。
//
// 6. 边界与易错点
//   最容易产生的误解是把 diff 中的负数当成“对这个航班做减法”。实际上 diff[i] 表示从位置 i 开始，running 要变化多少。特别是 last=n 时，diff[n]-=seats 位于真实 answer 之外，它只是“最后一个航班之后的结束边界”。另一个常见错误是把题面 1-based 航班号与 vector 0-based 下标混在一起：真实航班区间 [first,last] 对应数组 [first-1,last-1]，关闭事件下标恰好是 last。
//
// 7. 举一反三
//   差分适合“很多次区间统一加，最后统一读取每个点”。可以把它理解成事件压缩或延迟展开：公交 [上车,+人数] / [下车后,-人数]、会议开始/结束时人数变化、区间覆盖次数、扫描线都使用同一个模型。若更新和查询在线交错，通常升级到 Fenwick Tree / Segment Tree；二维矩形统一更新则可扩展到二维差分。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n (航班数) m (预订记录)。
//   接下来 m 行：first last seats。
//   输出：n 个以空格分隔的整数，表示从 1 开始编号的每个航班的座位数。
// test.in 的预期输出：10 55 45 25 25 0 0 0 0 0
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<int> corpFlightBookings(vector<vector<int>>& bookings, int n) {
        vector<int> diff(n + 1, 0);
        for (const auto& booking : bookings) {
            const int first = booking[0] - 1;
            const int afterLast = booking[1];
            diff[first] += booking[2];
            diff[afterLast] -= booking[2];
        }
        vector<int> answer(n);
        int running = 0;
        for (int i = 0; i < n; ++i) {
            running += diff[i];
            answer[i] = running;
        }
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, m; if (!(cin >> n >> m)) return 0;
    vector<vector<int>> bk(m, vector<int>(3));
    for (int i = 0; i < m; ++i) cin >> bk[i][0] >> bk[i][1] >> bk[i][2];
    auto ans = sol.corpFlightBookings(bk, n);
    for (int i = 0; i < n; ++i) cout << ans[i] << " \n"[i + 1 == n];
    return 0;
}
