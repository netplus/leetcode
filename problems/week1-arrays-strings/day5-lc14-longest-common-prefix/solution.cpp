// ============================================================================
// LC-14：最长公共前缀
// 难度：简单
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 5 天
// ----------------------------------------------------------------------------
// 题目描述：
// 编写一个函数来查找字符串数组中的最长公共前缀。
// 如果不存在公共前缀，返回空字符串 ""。
//
// 题目示例：
// 示例 1：
//   Input: strs = ["flower","flow","flight"]
//   Output: "fl"
//
// 示例 2：
//   Input: strs = ["dog","racecar","car"]
//   Output: ""
//   Explanation: There is no common prefix among the input strings.
//
// 约束与要求：
//   - 1 <= strs.length <= 200
//   - 0 <= strs[i].length <= 200
//   - strs[i] 如果非空，则仅由小写英文字母组成
//
// 复杂度目标：O(S) 其中 S = 字符总数。
//
// ----------------------------------------------------------------------------
// 解法精讲｜纵向扫描：逐列验证公共前缀
//
// 1. 图像直觉
//   把所有字符串竖着对齐来看：
//
//   flower
//   flow
//   flight
//
//   第 0 列：f f f  -> 全部相同
//   第 1 列：l l l  -> 全部相同
//   第 2 列：o o i  -> 第一次失败
//
//   公共前缀就像从左往右逐列验收：只要某一列有人缺字符，或者字符不同，
//   这一列以及后面的所有列都不可能再属于公共前缀。
//   所以第一次失败的位置，天然就是最长公共前缀的右边界。
//
// 2. 一句话核心
//   逐列检查所有字符串；前面每一列都通过，直到第一列失败，失败位置之前就是最长公共前缀。
//
// 3. 公式 / 不变量
//   设 first = strs[0]。
//   对位置 i：
//
//   若存在某个 j，使得
//     i == strs[j].size()
//   或
//     strs[j][i] != first[i]
//
//   则答案长度就是 i。
//
//   如果 first 的所有位置都通过，答案就是 first 本身。
//
// 4. 执行步骤
//   1. 把 strs[0] 当作公共前缀长度的最大上界
//   2. 从 i=0 开始逐列扫描 first
//   3. 对每一列 i，检查其余所有字符串是否仍有该位置且字符相同
//   4. 第一次越界或字符不同，立即返回 first.substr(0,i)
//   5. 如果 first 全部检查完成，返回 first
//   记忆：逐列验收；第一次失败就是答案边界。
//
// 5. 为什么不会漏 / 不会重
//   公共前缀要求从第 0 个字符开始连续一致，因此一旦第 i 列失败，任何长度大于 i 的字符串片段都不可能成为公共前缀；
//   而 [0,i) 的每一列都已经经过所有字符串验证，所以返回它既不会短也不会长。
//
// 6. 边界与易错点
//   字符串数组非空，但某个字符串可以为空；空串会在第 0 列立即终止。
//   不要把“公共子串”和“公共前缀”混淆：前缀必须从下标 0 开始，所以第一次失败后无需继续搜索。
//
// 7. 举一反三
//   这是“从共同起点向前推进，首次失败决定边界”的模型。
//   共同路径、版本号共同前缀、Trie 中沿唯一公共分支向下走，都有相同直觉。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n (字符串数量)。
//   接下来 n 行：每行一个字符串。
//   输出：最长公共前缀。
// test.in 的预期输出：fl
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    string longestCommonPrefix(vector<string>& strs) {
        const string& first = strs[0];
        for (int i = 0; i < static_cast<int>(first.size()); ++i) {
            for (int j = 1; j < static_cast<int>(strs.size()); ++j) {
                if (i == static_cast<int>(strs[j].size()) || strs[j][i] != first[i]) {
                    return first.substr(0, i);
                }
            }
        }
        return first;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    vector<string> strs(n);
    string discard; getline(cin, discard);
    for (int i = 0; i < n; ++i) getline(cin, strs[i]);
    cout << sol.longestCommonPrefix(strs) << "\n";
    return 0;
}
