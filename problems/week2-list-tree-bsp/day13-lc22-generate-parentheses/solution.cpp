// ============================================================================
// LC-22：括号生成
// 难度：中等
// 优先级：P1（进阶）
// 学习进度：第 2 周 / 第 13 天
// ----------------------------------------------------------------------------
// 题目描述：
// 数字 n 代表生成括号的对数，请你设计一个函数，用于能够生成所有可能的并且有效的括号组合。
//
// 题目示例：
// 示例 1：
//   Input: n = 3
//   Output: ["((()))","(()())","(())()","()(())","()()()"]
//
// 示例 2：
//   Input: n = 1
//   Output: ["()"]
//
// 约束与要求：
//   - 1 <= n <= 8
//
// 复杂度目标：O(4^n / sqrt(n))。
//
// ----------------------------------------------------------------------------
// 解法精讲｜约束生成：把合法前缀写进搜索树，只生成仍可能成功的节点
//
// 0. 优化是怎么来的
//   先从能写出来的直接算法开始：长度固定为 2n，每一位都枚举 '(' 或 ')'。
//
//   总候选数 = 2^(2n) = 4^n。
//   生成完整字符串后，再用 LC-20 的括号匹配规则判断是否合法。
//
//   问题在于很多候选在很短的前缀阶段就已经“判死刑”。例如：
//
//   ())...
//     ^
//   扫描到这里 close=2、open=1。
//   右括号已经比左括号多；未来再追加任何字符，都不可能修复“某个右括号出现时没有可匹配左括号”这个历史事实。
//
//   还有另一类必死前缀：已经放了 n 个左括号后还继续放 '('，最终根本没有足够位置放 n 个右括号。
//
//   所以不要“先生成坏字符串，再过滤”；把验证条件搬到生成过程中：
//   - open < n 才允许继续放 '('；
//   - close < open 才允许继续放 ')'。
//
//   这类优化删掉的是“已经违反前缀约束、未来永远无法恢复”的搜索分支。最后再把这种边构造边剪枝的 DFS 叫做回溯。
//
// 1. 图像直觉
//   n=3 时，不要把搜索树画成完整的二叉树；非法孩子根本不生成：
//
//                        ""  (open=0, close=0)
//                         |
//                        "(" (1,0)
//                     /          \
//                 "(("(2,0)    "()"(1,1)
//                 /   \             |
//             "((("  "(()"          "()("
//              |        ...            ...
//
//   根节点为什么没有 ')' 分支？
//   因为 close<open 不成立：一开始没有任何左括号可供它闭合。
//
//   对任意前缀都维护：
//   0 <= close <= open <= n
//
//   可以把 open-close 看成“当前还有多少个已打开但未闭合的括号”。
//   它绝不能为负；open 也绝不能超过总额度 n。
//
//   当长度达到 2n 时，既然 open<=n、close<=open，又已经放满 2n 个字符，就只能是 open=close=n，于是当前 path 自动是合法答案，不需要再调用 LC-20 验证。
//
// 2. 一句话核心
//   把 LC-20 的括号合法性从“完整字符串验收”前移成搜索前缀约束；只给仍可能完成的前缀生成孩子。
//
// 3. 公式 / 不变量
//   状态：
//   open  = path 中已使用 '(' 数
//   close = path 中已使用 ')' 数
//
//   所有被搜索的前缀始终满足：
//   0 <= close <= open <= n
//
//   添加 '(' 的条件：
//   open < n
//
//   添加 ')' 的条件：
//   close < open
//
//   终点：
//   path.size() == 2n
//
//   此时长度给出：
//   open + close = 2n
//   又有 close <= open <= n
//   => open = close = n
//   => path 必为完整合法括号串。
//
// 4. 执行步骤
//   1. 从空 path、open=0、close=0 开始；当前状态天然满足合法前缀不变量
//   2. 若 open<n，push '(' 并递归 open+1；回来后 pop，恢复当前前缀
//   3. 若 close<open，push ')' 并递归 close+1；这个条件保证任何时刻右括号都不会超过已出现的左括号
//   4. 当 path 长度达到 2n 时直接记录答案；此时不变量已经保证左右括号各 n 个且嵌套合法
//   记忆：不要先造坏答案再过滤；能开才开，手里有未闭合左括号才关。
//
// 5. 为什么不会漏 / 不会重
//   不会生成非法答案：每个前缀都满足 close<=open，所以从未出现无法匹配的右括号；open<=n 且最终长度为 2n，又迫使终点 open=close=n。不会漏：任意合法括号串的每个前缀都必满足 close<=open，并且总左括号数不超过 n，所以按照它真实的下一个字符走时，对应分支条件始终允许，最终一定能到达该答案。不会重：一个具体字符串的字符序列唯一，对应搜索树中唯一一条根到叶路径。
//
// 6. 边界与易错点
//   右括号条件必须是 `close < open`，不是 `close < n`；后者会生成 `)(` 一类无法修复的非法前缀。push 后递归、递归后 pop 必须成对，否则兄弟分支会继承错误字符串。这里无需在终点再调用 LC-20 校验，因为合法性已经作为不变量贯穿整个生成过程。题目 n>=1；若扩展到 n=0，这套逻辑也会自然返回空字符串这一种组合。
//
// 7. 举一反三
//   这是 LC-20 的反向使用：LC-20 给定完整字符串后判断“这个前缀是否已经非法”；LC-22 在生成阶段只允许不会让前缀非法的动作。以后遇到构造 IP、表达式、棋盘或受限序列时，优先问：哪些局部前缀一旦违规，未来无论怎么补都救不回来？把这些条件放进递归入口就是剪枝。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   输出：所有组合，每行一个。
// test.in 的预期输出：((())) | (()()) | (())() | ()(()) | ()()()
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
    vector<string> answer;
    string path;

    // open/close 是当前前缀已经使用的左右括号数。
    // 每次进入 search 时都保持 0 <= close <= open <= n，因此 path 始终是“仍可能完成”的合法前缀。
    void search(int n, int open, int close) {
        // 前缀始终合法且长度已达到 2*n 时，必有 open==close==n；
        // 所以当前 path 自动是一条完整合法答案，不需要再调用 LC-20 做二次验证。
        if (static_cast<int>(path.size()) == 2 * n) {
            answer.push_back(path);
            return;
        }

        // 左括号总量还没达到 n 时，可以继续开启一个尚未闭合的结构。
        if (open < n) {
            path.push_back('(');
            search(n, open + 1, close);
            path.pop_back();
        }

        // 只有当前未闭合左括号数 open-close > 0 时，才允许添加右括号；
        // 这条条件把任何 close>open 的永久非法前缀在生成之前就剪掉。
        if (close < open) {
            path.push_back(')');
            search(n, open, close + 1);
            path.pop_back();
        }
    }

public:
    vector<string> generateParenthesis(int n) {
        // 每次公开调用前清空成员状态；根搜索状态是空前缀、左右括号都尚未使用。
        answer.clear();
        path.clear();
        search(n, 0, 0);
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    auto res = sol.generateParenthesis(n);
    for (auto& s : res) cout << s << "\n";
    return 0;
}
