// ============================================================================
// LC-53：最大子数组和
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 1 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 nums，请你找出一个具有最大和的连续子数组（子数组最少包含一个元素），返回其最大和。
// 子数组是数组中的一个连续部分。
//
// 题目示例：
// 示例 1：
//   Input: nums = [-2,1,-3,4,-1,2,1,-5,4]
//   Output: 6
//   Explanation: The subarray [4,-1,2,1] has the largest sum 6.
//
// 示例 2：
//   Input: nums = [1]
//   Output: 1
//   Explanation: The subarray [1] has the largest sum 1.
//
// 示例 3：
//   Input: nums = [5,4,-1,7,8]
//   Output: 23
//   Explanation: The subarray [5,4,-1,7,8] has the largest sum 23.
//
// 约束与要求：
//   - 1 <= nums.length <= 10^5
//   - -10^4 <= nums[i] <= 10^4
//
// 复杂度目标：O(n) 时间，O(1) 空间（Kadane）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜从枚举所有区间到 Kadane：只保留最有前途的结尾状态
//
// 1. 图像直觉
//   先从最自然的枚举开始。例：
//
//   nums = [-2, 1, -3, 4, -1, 2, 1, -5, 4]
//
//   固定一个起点 left，向右扩展 right，同时维护 sum：
//
//   left=0：[-2] -> [-2,1] -> [-2,1,-3] -> ...
//   left=1：     [1] -> [1,-3] -> [1,-3,4] -> ...
//   left=2：            [-3] -> [-3,4] -> ...
//   ...
//
//   这样可以正确检查所有连续子数组，但有 O(n^2) 个区间。
//
//   现在换个角度：不要按“起点”分类，而按“终点”分类。
//
//   当终点固定在 nums[3]=4 时，所有以 4 结尾的候选是：
//
//   [-2, 1, -3, 4]  和 = 0
//   [    1, -3, 4]  和 = 2
//   [       -3, 4]  和 = 1
//   [            4]  和 = 4   <- 最大
//
//   为什么只保留 4 这一条就够了？
//   因为下一步如果统一接上 -1：
//
//   0 + (-1) = -1
//   2 + (-1) =  1
//   1 + (-1) =  0
//   4 + (-1) =  3   <- 仍然最大
//
//   以后再接 2、1、-5……也是同一个道理：所有候选都加上相同的新元素，原来更小的那个永远追不上原来更大的那个。
//
//   所以走到每个位置 i，只保留：
//   current = “必须以 i 结尾”的最大子数组和。
//
//   对样例逐步扫描：
//
//    i       0   1   2   3   4   5   6   7   8
//   nums    -2   1  -3   4  -1   2   1  -5   4
//   current -2   1  -2   4   3   5   6   1   5
//   best    -2   1   1   4   4   5   6   6   6
//
//   current 只回答“以当前位置结尾的最好是多少”；best 才保存整个扫描过程见过的全局最大值。
//
// 2. 一句话核心
//   暴力会保留很多以同一位置结尾的候选；由于未来给它们追加的是同一批元素，只需留下当前和最大的那个，再决定它值得继续带上还是从当前位置重新开始。
//
// 3. 公式 / 不变量
//   最直接的 O(n^2) 枚举：
//
//   for each left:
//       sum = 0
//       for right = left .. n-1:
//           sum += nums[right]
//           best = max(best, sum)
//
//   把候选按“终点 i”重新组织。
//   任意以 i 结尾的连续子数组只有两类：
//
//   1. 只包含 nums[i]，从当前位置重新开始；
//   2. 某个以 i-1 结尾的连续子数组，再接上 nums[i]。
//
//   第二类中只需保留上一位置最大的那个 current：
//
//   current_i = max(nums[i], current_(i-1) + nums[i])
//   best_i    = max(best_(i-1), current_i)
//
//   不变量：
//   current = 必须以当前 i 结尾的最大子数组和
//   best    = 下标 [0..i] 内已经出现过的最大子数组和
//
//   等价直觉：
//   若旧 current < 0，它只会拖累 nums[i]，从 i 重开；
//   若旧 current > 0，带上它一定比只取 nums[i] 更好；
//   旧 current == 0 时两种选择等价。
//
// 4. 执行步骤
//   1. 先想清楚暴力：枚举 left，向右扩 right，用 running sum 检查所有 O(n^2) 个连续区间
//   2. 改为从左到右枚举终点 i，并令 current 表示“必须以 i 结尾”的最大子数组和
//   3. 处理 nums[i] 时，只比较两种合法来源：从 nums[i] 重开，或把 nums[i] 接到上一位置的 current 后面
//   4. 执行 current=max(nums[i], current+nums[i])，把所有以 i 结尾的候选再次压缩成一个最优状态
//   5. 执行 best=max(best,current)，因为全局答案可能在任何一个终点结束，而 current 之后还会继续变化
//   记忆：先枚举区间理解问题 -> 改按终点看 -> 同一终点只留最大候选 -> current 决定接上还是重开 -> best 记录所有终点里的最大值。
//
// 5. 为什么不会漏 / 不会重
//   固定终点 i，任何非空连续子数组要么只含 nums[i]，要么由一个以 i-1 结尾的连续子数组加上 nums[i] 得到。对第二类而言，所有候选都加同一个 nums[i]，因此上一位置和更小的候选不可能在加法后超过上一位置的最大候选；只保留 current 不会丢掉未来可能成为最优解的状态。于是 current 精确覆盖“以 i 结尾”的最优答案，再对所有终点的 current 取最大，就得到全局最大子数组和。
//
// 6. 边界与易错点
//   不要把 current 和 best 混为一谈：样例扫描到 -5 时 current 从 6 降到 1，但历史最优 best 仍是 6。current/best 必须用 nums[0] 初始化，不能初始化为 0，否则全负数组会错误选择不存在的空子数组；例如 [-5,-2,-3,-1,-4] 的答案应为 -1。所谓“负数就丢掉”更准确地说是“旧 current<0 时不再把它接到当前元素前面”，并不是数组里遇到负数就一定断开。当前约束下最大和不超过 10^9，int 足够；更宽泛的变体可改用 long long。
//
// 7. 举一反三
//   这题最值得迁移的是“按终点组织候选 + 丢掉被支配状态”的动态规划视角。以后遇到连续区间最优问题，可以先问：固定当前终点后，过去有哪些候选会面对完全相同的未来？如果一个状态在所有未来扩展下都不可能反超另一个，就可以安全淘汰。最大乘积子数组之所以要同时保留最大值和最小值，正是因为乘负数会反转大小关系，不能像本题一样只留一个最大状态。
//
// 进阶优化
//   如果题目还要求返回最大子数组的左右边界，可以在“从当前位置重开”时记录新的 candidateLeft，并在 best 被 current 刷新时保存 bestLeft/bestRight；Kadane 的状态压缩逻辑本身不变。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：最大子数组和。
// test.in 的预期输出：6
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int maxSubArray(vector<int>& nums) {
        // current：必须以“当前扫描位置”结尾的最大子数组和。
        // best：截至当前，所有可能终点中出现过的最大子数组和。
        // 两者都从 nums[0] 开始，而不能从 0 开始：题目要求子数组非空；
        // 若数组全为负数，0 代表的是一个并不存在的空子数组，会得到错误答案。
        int current = nums[0];
        int best = nums[0];

        for (int i = 1; i < static_cast<int>(nums.size()); ++i) {
            // 所有以 i 结尾的合法区间只有两类来源：
            // 1) 从 nums[i] 重新开始；
            // 2) 把 nums[i] 接到某个以 i-1 结尾的区间后面。
            //
            // 第二类中只需要保留上一位置最大的 current：所有候选以后都会追加
            // 完全相同的未来后缀，当前和更小的候选永远不可能反超更大的候选，
            // 因而可以永久淘汰。这就是这里能把 O(n) 个结尾候选压成 1 个状态的原因。
            current = max(nums[i], current + nums[i]);

            // current 只回答“必须在 i 结束时最好是多少”；它下一步可能下降。
            // best 保存历史全局答案，因此必须独立更新，不能直接用最新 current 代替。
            best = max(best, current);
        }
        return best;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.maxSubArray(a) << "\n";
    return 0;
}
