// ============================================================================
// LC-5：最长回文子串
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 1 周 / 第 5 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个字符串 s，找到 s 中最长的回文子串。
//
// 题目示例：
// 示例 1：
//   Input: s = "babad"
//   Output: "bab"
//   Explanation: "aba" is also a valid answer.
//
// 示例 2：
//   Input: s = "cbbd"
//   Output: "bb"
//
// 约束与要求：
//   - 1 <= s.length <= 1000
//   - s 仅由数字和英文字母组成
//
// 复杂度目标：O(n^2) (中心扩展) 或 O(n)（Manacher）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜中心扩展：统一奇偶回文
//
// 前置概念
//   子串（substring）是原字符串中的连续片段，不允许跳过字符。
//
//   例如 s="abcba"："bcb" 是子串；"aba" 若依靠跳过中间字符才能取得，就不是该位置上的子串。
//
//   所以“最长回文子串”要求回文字符在原串中连续出现，这也是中心扩展可以用左右指针连续向外走的前提。
//
// 0. 优化是怎么来的
//   最直接的正确做法，是枚举所有子串 [left,right]，再逐个检查它是否回文；子串有 O(n^2) 个，每次检查又可能 O(n)，总时间 O(n^3)。
//
//   这里重复做的工作是：同一个回文内部的镜像字符，会在许多包含它的子串检查里被反复比较。换一个视角，每个回文其实都有唯一的几何中心；只要固定中心，回文能延伸多远就只需从内向外顺序比较一次。
//
//   于是搜索空间从“枚举两个端点 + 再检查内部”改成“枚举 O(n) 个字符中心和 O(n) 个缝隙中心 + 向外扩展”。每个中心的最大回文直接在一次扩展里得到。
//
//   优化类型：重复验证内部结构 -> 改变枚举坐标系，从端点枚举转成唯一中心枚举。时间从 O(n^3) 降为 O(n^2)。
//
// 1. 图像直觉
//   任何回文都可以从“中心”向两边展开。
//
//   奇数长度："racecar"
//                e
//             <- | ->
//   中心落在一个字符上。
//
//   偶数长度："abba"
//                ||
//             <-    ->
//   中心落在两个字符之间的缝隙上。
//
//   所以对每个位置 i，只需要枚举两种中心：
//   (i,i)     -> 奇数回文
//   (i,i+1)   -> 偶数回文
//
//   然后只要左右字符相等，就继续同时向外走。
//
// 2. 一句话核心
//   枚举所有可能的回文中心，并从中心向两侧扩展；字符一旦不同，该中心能得到的最长回文就已经确定。
//
// 3. 公式 / 不变量
//   扩展条件：
//   left >= 0
//   right < n
//   s[left] == s[right]
//
//   循环结束时已经多走了一步，因此真实回文区间是：
//   [left+1, right-1]
//   长度：
//   right - left - 1
//
// 4. 执行步骤
//   1. 遍历每个 center
//   2. 调用 expand(center,center)，覆盖所有奇数长度回文
//   3. 调用 expand(center,center+1)，覆盖所有偶数长度回文
//   4. expand 中左右字符相等就同时向外扩张
//   5. 停止后计算 length=right-left-1；若更长就更新 bestStart/bestLength
//   记忆：每个位置看两种中心；左右相等就扩，第一次不等就停。
//
// 5. 为什么不会漏 / 不会重
//   每个非空回文都有且只有一个几何中心：奇数回文中心是某个字符，偶数回文中心是相邻字符之间的间隙；我们枚举了全部这两类中心。对固定中心，向外扩展直到首次失败，得到的就是该中心下最大的回文，因此全局最长回文必会被某次扩展完整发现。
//
// 6. 边界与易错点
//   最容易漏掉偶数中心 (i,i+1)；循环退出时 left/right 已经越过真实回文一格，所以长度是 right-left-1，起点是 left+1；若只在 length>bestLength 时更新，可稳定保留最早发现的同长度答案。
//
// 7. 举一反三
//   中心扩展不仅能求最长回文，也能把每次成功扩展计数后得到“回文子串总数”。如果规模更大，再学习 Manacher，本质仍是复用已经得到的回文半径。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：字符串 s。
//   输出：最长回文子串。
// test.in 的预期输出：bab
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    string longestPalindrome(string s) {
        int bestStart = 0, bestLength = 0;

        // expand(left,right) 接收一个几何中心：
        // left==right 表示字符中心（奇数长度），right==left+1 表示字符间隙中心（偶数长度）。
        auto expand = [&](int left, int right) {
            // 只要左右仍在边界内且字符相同，就把当前回文同时向两侧扩一格。
            while (left >= 0 && right < static_cast<int>(s.size()) && s[left] == s[right]) {
                --left;
                ++right;
            }

            // 循环退出时，left/right 已经各自越过真实回文一格：
            // 真正的最大回文是闭区间 [left+1, right-1]，长度因此为 right-left-1。
            const int length = right - left - 1;
            if (length > bestLength) {
                bestLength = length;
                bestStart = left + 1;
            }
        };

        for (int center = 0; center < static_cast<int>(s.size()); ++center) {
            // 每个非空回文都有唯一的几何中心；枚举这两种中心即可覆盖全部奇偶回文。
            expand(center, center);       // 奇数长度：中心落在 s[center]
            expand(center, center + 1);   // 偶数长度：中心落在 center 与 center+1 的缝隙
        }

        // bestStart/bestLength 始终描述当前发现的最长真实回文区间。
        return s.substr(bestStart, bestLength);
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    string s;
    if (!(cin >> s)) return 0;
    cout << sol.longestPalindrome(s) << "\n";
    return 0;
}
