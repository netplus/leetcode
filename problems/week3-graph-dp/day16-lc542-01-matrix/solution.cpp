// ============================================================================
// LC-542：01 矩阵
// 难度：中等
// 优先级：P1（进阶）
// 学习进度：第 3 周 / 第 16 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个由 0 和 1 组成的矩阵 mat，请输出一个大小相同的矩阵，其中每一个格子是 mat 中对应位置元素到最近的 0 的距离。
// 两个相邻元素间的距离为 1。
//
// 题目示例：
// 示例 1：
//   Input: mat = [[0,0,0],[0,1,0],[0,0,0]]
//   Output: [[0,0,0],[0,1,0],[0,0,0]]
//
// 示例 2：
//   Input: mat = [[0,0,0],[0,1,0],[1,1,1]]
//   Output: [[0,0,0],[0,1,0],[1,2,1]]
//
// 约束与要求：
//   - m == mat.length
//   - n == mat[i].length
//   - 1 <= m, n <= 10^4
//   - 1 <= m * n <= 10^4
//   - mat[i][j] 为 0 或 1。
//   - mat 中至少有一个 0
//
// 复杂度目标：O(m*n) 时间（多源 BFS）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜多源 BFS 最近距离：把所有目标同时放进第 0 层，让最近的波前自然获胜
//
// 0. 优化是怎么来的
//   最自然的正确做法，是对每个值为 1 的格子单独做 BFS，直到找到第一个 0。单个 BFS 最坏访问整个矩阵 O(mn)，如果几乎所有格子都是 1，就会把同一片网格重复搜索很多次，最坏接近 O((mn)^2)。
//
//   观察所有这些独立 BFS 的目标完全相同：都在寻找“0 集合”。距离又是对称的——A 到 B 的四邻步数和 B 到 A 相同。因此无需让每个 1 去寻找 0，可以让所有 0 同时向外传播。
//
//   把所有 0 先放到距离 0 层，相当于增加一个虚拟超级源，用 0 代价连到所有真实 0；普通 BFS 每向外一层距离加 1。不同源的波前相遇时，无需比较第二次，因为首次到达已经是全体源中的最短距离。
//
//   优化类型：每个查询点重复最短路 -> 目标集合变成多源起点，一次 BFS 同时回答所有格子。
//
// 1. 图像直觉
//   mat：
//   0 0 0
//   0 1 0
//   1 1 1
//
//   先把所有 0 同时放进第 0 层：
//   0 0 0
//   0 ? 0
//   ? ? ?
//
//   它们一起向外扩散：
//
//   距离0: 所有原始 0
//   距离1: 中心和底部两侧
//   距离2: 底部中间
//
//   结果：
//   0 0 0
//   0 1 0
//   1 2 1
//
//   不是“某个 0 跑遍全图”，而是所有 0 的波前同时扩张；谁先碰到一个格子，谁就是它最近的 0。
//
// 2. 一句话核心
//   所有 0 同时作为距离 0 的 BFS 源；未访问格第一次被任意源的波前到达时，当前层数就是它到最近 0 的距离。
//
// 3. 公式 / 不变量
//   distance[r][c]：到任意 0 的最短四邻步数。
//
//   初始化：
//   mat[r][c] == 0 => distance[r][c] = 0，入队
//   mat[r][c] == 1 => distance[r][c] = -1，表示尚未确定
//
//   状态转移：
//   若 neighbor 尚未访问：
//   distance[neighbor] = distance[current] + 1
//   neighbor 入队
//
//   BFS 队列保证 current 的 distance 非降序，因此 neighbor 第一次赋值就是：
//   min over all zero sources (distance(source, neighbor))。
//
// 4. 执行步骤
//   1. 创建与 mat 同尺寸的 distance，统一初始化为 -1；扫描矩阵，把所有 0 的 distance 设为 0 并全部入队
//   2. 从队首弹出当前格，枚举上下左右四个相邻位置
//   3. 越界或 distance 已经不是 -1 的格子跳过；后者表示已经被更早或同层的最近波前确定
//   4. 对首次到达的邻格赋 distance[current]+1，并立即入队，保证它只处理一次
//   5. 队列耗尽后返回 distance；题目保证至少存在一个 0，所以所有格子最终都会得到距离
//   记忆：最近哪个源？不要每个点自己找；让所有源同时从距离 0 向外扩散。
//
// 5. 为什么不会漏 / 不会重
//   把所有 0 看成同时出发的源。BFS 第 k 层恰好包含与最近源距离为 k 的尚未处理节点：第 0 层显然成立；若 current 的最短距离为 k，则任何首次由它发现的邻居存在一条长度 k+1 的路径。若该邻居存在更短路径，它应当已被更早层的某个源发现，与“尚未访问”矛盾。因此第一次赋值就是到所有 0 中最近一个的距离。
//
// 6. 边界与易错点
//   所有 0 必须在 BFS 开始前同时入队，不能逐个 0 分别跑完整 BFS。`-1` 同时承担未访问标记和“距离尚未确定”状态，避免另开 visited。题目是四方向步数，不允许对角线。当前代码仅使用 C++17 或更早特性。
//
// 7. 举一反三
//   与 LC-994 完全同源：LC-542 的层数表示“离最近 0 多远”，LC-994 的层数表示“最早第几分钟被腐烂”。以后看到“每个点到最近医院/门/出口/障碍的距离”，优先把所有目标点一起作为第 0 层。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：m n。
//   接下来 m 行：n 个以空格分隔的整数。
//   输出：距离矩阵，每行输出矩阵的一行，元素以空格分隔。
// test.in 的预期输出：0 0 0 | 0 1 0 | 1 2 1
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    vector<vector<int>> updateMatrix(vector<vector<int>>& mat) {
        const int rows = static_cast<int>(mat.size());
        const int cols = static_cast<int>(mat[0].size());

        // distance 同时保存答案和 visited 状态：
        // -1 表示“尚未被任何 0 的波前到达，最近距离还没确定”；非负值就是已经确定的最短距离。
        vector<vector<int>> distance(rows, vector<int>(cols, -1));
        queue<pair<int, int>> pending;

        // 所有原始 0 必须在 BFS 开始前同时成为距离 0 的源。
        // 这样队列中的不同波前是在同一张图上并行扩散，而不是逐个 0 重复跑搜索。
        for (int r = 0; r < rows; ++r) {
            for (int c = 0; c < cols; ++c) {
                if (mat[r][c] == 0) {
                    distance[r][c] = 0;
                    pending.push({r, c});
                }
            }
        }

        const int directions[4][2] = {{1, 0}, {-1, 0}, {0, 1}, {0, -1}};
        while (!pending.empty()) {
            auto [r, c] = pending.front();
            pending.pop();

            // 多源 BFS 仍按 distance 非降序扩展；当前格的距离已经是到所有 0 中最近一个的最短距离。
            for (auto& d : directions) {
                int nr = r + d[0], nc = c + d[1];

                // 只处理 distance==-1 的格子。一个格子第一次被任意源的波前到达时，
                // distance[current]+1 已经是全体 0 源中的最短值，因此以后无需再次松弛或比较。
                if (nr >= 0 && nr < rows && nc >= 0 && nc < cols && distance[nr][nc] == -1) {
                    // 赋值发生在入队之前：从这一刻起该格已被声明 visited，其他波前不会重复入队它。
                    distance[nr][nc] = distance[r][c] + 1;
                    pending.push({nr, nc});
                }
            }
        }

        // 题目保证至少有一个 0；四邻网格连通，因此所有格最终都会从 -1 变成其最近 0 距离。
        return distance;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int m, n; if (!(cin >> m >> n)) return 0;
    vector<vector<int>> g(m, vector<int>(n));
    for (int i = 0; i < m; ++i) for (int j = 0; j < n; ++j) cin >> g[i][j];
    auto res = sol.updateMatrix(g);
    for (auto& r : res) for (size_t j = 0; j < r.size(); ++j) cout << r[j] << " \n"[j + 1 == r.size()];
    return 0;
}
