// ============================================================================
// LC-990：等式方程的可满足性
// 难度：中等
// 优先级：P1（进阶）
// 学习进度：第 3 周 / 第 17 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个由表示变量之间关系的字符串方程组成的数组，每个字符串方程 equations[i] 的长度为 4，并采用两种不同的形式之一："a==b" 或 "a!=b"。
// 在这里，a 和 b 是小写字母（不一定不同），表示单字母变量名。
// 只有当可以将整数分配给变量名，以便满足所有给定的方程时才返回 true，否则返回 false。
//
// 约束与要求：
//   - 1 <= equations.length <= 500
//   - equations[i].length == 4
//   - equations[i][0] 和 equations[i][3] 是小写字母
//   - equations[i][1] 要么是 '='，要么是 '!'
//   - equations[i][2] 是 '='
//
// 复杂度目标：O(n) 并查集。
//
// ----------------------------------------------------------------------------
// 解法精讲｜等价类约束：先合并所有 ==，再验证 != 是否跨集合
//
// 0. 优化是怎么来的
//   一个自然解法，是先根据所有 `==` 建无向图，再对 26 个变量做 DFS/BFS，给每个连通分量编号；第二遍检查 `a!=b` 是否落在同一编号。这个方案完全正确，而且因为变量只有 26 个，性能也足够好。
//
//   并查集在这里仍然不是为了制造虚假的数量级优势，而是因为问题本质就是“不断声明两个对象等价，并反复查询它们是否属于同一等价类”。这正是 DSU 的原生语义：
//   `a==b` -> unite(a,b)
//   `a!=b` -> find(a) != find(b)
//
//   为什么必须先处理全部等式？因为输入顺序不代表逻辑推导顺序。例如先看到 `a!=c` 时，后面可能还有 `a==b`、`b==c`；只有把等式传递闭包全部建立后，才能判断不等式是否矛盾。
//
//   这里的优化/抽象是：显式建立等价图并遍历分量 -> 直接持续维护等价类代表；复杂度同样近线性，但状态表达可以直接迁移到账户合并、同义实体归并等问题。
//
// 1. 图像直觉
//   等式：
//   a == b
//   b == c
//
//   合并过程：
//
//   a     b     c
//   |     |     |
//   a     b     c
//
//   unite(a,b)
//   [a,b]       [c]
//
//   unite(b,c)
//   [a,b,c]
//
//   此后虽然没有直接出现 a==c，仍然有：
//   find(a) == find(c)
//
//   如果约束里还有：
//   a != c
//
//   第二遍检查时发现同根：
//   find(a) == find(c)
//   却要求 a != c
//   => 矛盾。
//
//   如果 d != a，而 d 在另一个集合：
//   [d]    [a,b,c]
//   => 可以给两个集合赋不同整数，约束可满足。
//
// 2. 一句话核心
//   相等关系先做传递闭包：所有 `==` 都 union；随后每条 `!=` 只检查两端是否同根，同根即矛盾，跨集合即可满足。
//
// 3. 公式 / 不变量
//   第一遍：对每条 x==y
//   union(x,y)
//
//   完成后 DSU 表示等式的传递闭包：
//   find(x) == find(y)
//   <=> 已知等式强制 x、y 取相同值。
//
//   第二遍：对每条 x!=y
//   若 find(x) == find(y)：
//   等式闭包要求相等，但当前约束要求不等
//   => false。
//
//   若所有不等式都跨集合：
//   给每个 DSU 根分配一个不同整数
//   => 所有 == 与 != 可同时满足
//   => true。
//
// 4. 执行步骤
//   1. 初始化 26 个字母各自为独立集合，parent[i]=i
//   2. 第一遍只处理 equation[1]=='=' 的方程，把左右变量对应的两个根合并
//   3. 等式全部处理完后，DSU 已经包含所有直接和间接的相等关系
//   4. 第二遍只处理 `!=`；若左右变量 find 后同根，立即返回 false
//   5. 若所有不等式都跨不同集合，返回 true
//   记忆：等式先全部合并，再检查不等式；同根代表逻辑上已经被迫相等。
//
// 5. 为什么不会漏 / 不会重
//   第一遍 union 后，同一 DSU 集合恰好包含由等式链连接起来的变量，因此同集合变量在任何满足方案中都必须取相同值。若某条不等式两端同根，它直接与这些等式的传递结果冲突，不可能满足。反过来，若每条不等式都连接两个不同集合，只需给每个集合分配互不相同的整数；集合内部自动满足全部等式，不同集合之间的所有已给不等式也必然成立，因此方程组可满足。
//
// 6. 边界与易错点
//   必须先处理所有 `==` 再检查 `!=`，不能按输入顺序遇到不等式就立即判断，因为后续等式可能通过传递性把两端合到一起。`x!=x` 会自然因为同根而失败。当前代码用 `find()` 和路径压缩，完全属于 C++17；不要为了写得短改用 C++20 容器 API。
//
// 7. 举一反三
//   LC-547 把“城市连通”表达成集合；LC-990 只是把“连通”换成“逻辑等价”。以后遇到账号别名、同义关系、身份归并、动态等价类时，可以先问：我是否只关心‘属于同一组吗’，而不关心组内具体路径？若是，DSU 往往比显式图更贴近问题语义。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n (方程数量)。
//   接下来 n 行：每行一个方程字符串。
//   输出：方程组可满足时输出 1，否则输出 0。
// test.in 的预期输出：1
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    bool equationsPossible(vector<string>& equations) {
        array<int, 26> parent;
        iota(parent.begin(), parent.end(), 0);
        function<int(int)> find = [&](int x) {
            return parent[x] == x ? x : parent[x] = find(parent[x]);
        };
        for (const string& equation : equations) {
            if (equation[1] == '=') {
                int a = find(equation[0] - 'a');
                int b = find(equation[3] - 'a');
                parent[a] = b;
            }
        }
        for (const string& equation : equations) {
            if (equation[1] == '!' && find(equation[0] - 'a') == find(equation[3] - 'a')) {
                return false;
            }
        }
        return true;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    vector<string> eq(n);
    for (int i = 0; i < n; ++i) cin >> eq[i];
    cout << (sol.equationsPossible(eq) ? 1 : 0) << "\n";
    return 0;
}
