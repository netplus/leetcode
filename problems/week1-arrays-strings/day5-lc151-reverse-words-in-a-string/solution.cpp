// ============================================================================
// LC-151：反转字符串中的单词
// 难度：中等
// 优先级：P1（进阶）
// 学习进度：第 1 周 / 第 5 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个字符串 s，请你反转字符串中单词的顺序。
// 单词是由非空格字符组成的字符串。
// s 中使用至少一个空格将字符串中的单词分隔开。
// 返回单词顺序颠倒且单词之间用单个空格连接的结果字符串。
// 注意：输入字符串 s 中可能会存在前导空格、尾随空格或者单词间的多个空格。
// 返回的结果字符串中，单词间应当仅用单个空格分隔，且不包含任何额外的空格。
//
// 约束与要求：
//   - 1 <= s.length <= 10^4
//   - s 包含英文大小写字母、数字和空格 ' '
//   - s 中至少存在一个单词
//
// 复杂度目标：O(n) 时间，O(1) 额外空间（原地）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜整体反转 + 原地压缩 + 单词复原
//
// 1. 图像直觉
//   例：s = "  the   sky is  blue "。
//
//   第一步整体反转：
//   " eulb  si yks   eht  "
//
//   此时单词顺序已经变成：blue / is / sky / the，
//   但每个单词内部也被反转了，而且空格仍很乱。
//
//   接下来把字符串看成 LC-283 的稳定压缩：
//
//   read  -> 负责寻找下一个单词字符
//   write -> 负责把有效内容紧凑写回前面
//
//   压缩过程中，每复制完一个单词，就把这个单词局部再反转一次：
//
//   eulb -> blue
//   si   -> is
//   yks  -> sky
//   eht  -> the
//
//   最终得到："blue is sky the"。
//
// 2. 一句话核心
//   整体反转先解决“单词顺序”，read/write 再压缩空格并复制单词，每个单词复制完后局部反转恢复字符顺序。
//
// 3. 公式 / 不变量
//   整体反转后：
//   原词序 W1 W2 ... Wk
//   变成 reverse(Wk) ... reverse(W2) reverse(W1)
//
//   再对每个 reverse(Wi) 单独反转：
//   => Wk ... W2 W1
//
//   压缩阶段维护：
//   [0, write) = 已整理好的结果
//   read        = 下一个尚未处理的位置
//
// 4. 执行步骤
//   1. reverse 整个字符串，让单词整体顺序先倒过来
//   2. 用 read 跳过连续空格，找到下一个单词起点
//   3. 若结果中已经有单词，先由 write 写入一个空格
//   4. 把当前单词逐字符复制到 write，并记录该单词在结果中的 [wordStart,write)
//   5. 局部 reverse 这个新写入的单词，恢复其字符顺序
//   6. 全部处理后 resize(write)，删除尾部旧内容
//   记忆：整体反转改词序 -> read/write 压空格 -> 每个单词再反转回来。
//
// 5. 为什么不会漏 / 不会重
//   整体反转已经唯一确定了正确的单词排列；之后的 read/write 只删除冗余空格、按出现顺序复制这些反转后的单词，
//   不会改变单词之间的相对次序；每个单词再局部反转一次，恰好恢复原字符顺序。
//
// 6. 边界与易错点
//   本题输入可能有前导、尾随和多个连续空格，本地测试必须整行读取；write 不会超过 read，因此原地覆盖不会破坏尚未读取的有效字符；
//   空格压缩时只在两个已输出单词之间写一个空格。
//
// 7. 举一反三
//   这里直接复用 LC-283 的 read/write 稳定压缩思想：read 负责找要保留的内容，write 决定它应落在哪里。
//   再叠加“整体变换 + 局部修复”，可迁移到数组旋转、块反转等原地重排问题。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：完整字符串 s（可含前导、尾随或连续空格）。
//   输出：反转单词顺序后、以单个空格连接的字符串。
// test.in 的预期输出：blue is sky the
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    string reverseWords(string s) {
        reverse(s.begin(), s.end());
        int read = 0, write = 0;
        const int n = static_cast<int>(s.size());
        while (read < n) {
            while (read < n && s[read] == ' ') ++read;
            if (read == n) break;
            if (write > 0) s[write++] = ' ';

            const int wordStart = write;
            while (read < n && s[read] != ' ') s[write++] = s[read++];
            reverse(s.begin() + wordStart, s.begin() + write);
        }
        s.resize(write);
        return s;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    string s;
    getline(cin, s);
    cout << sol.reverseWords(s) << "\n";
    return 0;
}
