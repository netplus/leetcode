// ============================================================================
// LC-134：加油站
// 难度：中等
// 优先级：P1（进阶）
// 学习进度：第 4 周 / 第 24 天
// ----------------------------------------------------------------------------
// 题目描述：
// 在一条环路上有 n 个加油站，其中第 i 个加油站有汽油 gas[i] 升。
// 你有一辆油箱容量无限的的汽车，从第 i 个加油站开往第 i+1 个加油站需要消耗汽油 cost[i] 升。
// 你从其中的一个加油站出发，开始时油箱为空。
// 给定两个整数数组 gas 和 cost，如果你可以按顺序绕环路行驶一周，则返回出发时加油站的编号，否则返回 -1。
// 如果存在解，则保证它是唯一的。
//
// 约束与要求：
//   - n == gas.length == cost.length
//   - 1 <= n <= 10^5
//   - 0 <= gas[i], cost[i] <= 10^4
//   - 输入保证答案唯一。
//
// 复杂度目标：O(n) 时间，O(1) 空间（贪心）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜贪心候选淘汰：一次失败排除整段起点
//
// 0. 优化是怎么来的
//   最直接的正确算法是把每个站都当作起点模拟一整圈：从 s 出发逐站累加 gas[i]-cost[i]，
//   油量一旦为负就判 s 失败；若走满 n 站则成功。它不会漏答案，但最多 n 个起点各走 O(n) 站，
//   最坏 O(n^2)。
//
//   浪费发生在失败模拟之间的大量重叠。设从 start 出发直到 i 才第一次出现累计和为负：
//   sum(start..i)<0。对任意 j∈(start,i]，此前 sum(start..j-1)>=0，因此
//   sum(j..i)=sum(start..i)-sum(start..j-1)<0。
//   所以 j 自己出发也一定跨不过 i。
//
//   一次失败就能把 start..i 的所有候选永久排除，下一候选直接跳到 i+1；
//   再用全局 total=sum(gas-cost) 判断整圈是否总体可行。优化类型：失败前缀的批量候选淘汰。
//
// 1. 图像直觉
//   gas  = [1,2,3,4,5]
//   cost = [3,4,5,1,2]
//   gain = [-2,-2,-2,+3,+3]
//
//   start=0 到 0：tank=-2 -> 0 失败，下一候选 1
//   start=1 到 1：tank=-2 -> 1 失败，下一候选 2
//   start=2 到 2：tank=-2 -> 2 失败，下一候选 3
//
//   从 3 开始：+3,+3,-2,-2,-2
//   前缀剩余：3,6,4,2,0，可以走完一圈。
//
//   一般地，start..i 第一次累计成负数时：
//   start ........ i | i+1
//      整段起点失败  ^ 下一个候选
//
// 2. 一句话核心
//   局部油箱一旦变负，就证明当前失败段里的所有起点都不可能成功；整段跳过，同时用全局 total 判断有没有解。
//
// 3. 公式 / 不变量
//   gain[i] = gas[i] - cost[i]
//   total       += gain[i]
//   currentTank += gain[i]
//
//   若 currentTank < 0：
//       start = i + 1
//       currentTank = 0
//
//   在首次失败 i 前，对任意 j∈(start,i]：
//   sum(start..j-1)>=0 且 sum(start..i)<0，
//   所以 sum(j..i)=sum(start..i)-sum(start..j-1)<0，j 也过不了 i。
//
//   全局条件：total=sum(gas)-sum(cost)>=0 才可能绕完整圈。
//
// 4. 执行步骤
//   1. 扫描每个站，计算 gain，并同时累加全局 total 与当前候选的 currentTank。
//   2. currentTank<0 时，把 start 直接跳到 i+1，并把局部 currentTank 重置为 0。
//   3. 继续扫描；已经淘汰的起点不再回看，因此每个下标只处理一次。
//   4. 扫描后若 total<0 返回 -1，否则返回最后保留下来的 start。
//   记忆：局部失败淘汰一整段，全局 total 决定有没有解。
//
// 5. 为什么不会漏 / 不会重
//   每次局部失败时，前缀和关系已经证明 start..i 的所有起点都无法跨过 i，批量删除不会漏真正答案。
//   若 total<0，整圈总消耗大于总供给，无论从哪里开始都不可能成功。若 total>=0，所有更早候选都已被证明失败，
//   最后留下的 start 的后半段从未出现负油量；全局盈余又足以补足绕回前半段所需的亏损，因此它可以完成整圈。
//
// 6. 边界与易错点
//   currentTank 只判断当前候选何时失败，不能替代 total；局部重置时绝不能把 total 清零。
//   净收益方向必须是 gas-cost。现有题目数值范围内 int 足够，若迁移到更大范围可改用 long long。
//
// 7. 举一反三
//   与 LC-53 最大子数组有共同结构：一个已经证明有害的负前缀面对相同未来只会拖累后续候选，
//   因而可以永久丢弃；LC-134 额外需要环形问题的全局守恒条件 total>=0。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个 gas 值。
//   第 3 行：n 个 cost 值。
//   输出：可行的起点下标；不存在时输出 -1。
// test.in 的预期输出：3
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int canCompleteCircuit(vector<int>& gas, vector<int>& cost) {
        int total = 0, currentTank = 0, start = 0;
        for (int i = 0; i < static_cast<int>(gas.size()); ++i) {
            const int gain = gas[i] - cost[i];
            total += gain;
            currentTank += gain;
            if (currentTank < 0) {
                start = i + 1;
                currentTank = 0;
            }
        }
        return total >= 0 ? start : -1;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n; if (!(cin >> n)) return 0;
    vector<int> gas(n), cost(n);
    for (int i = 0; i < n; ++i) cin >> gas[i];
    for (int i = 0; i < n; ++i) cin >> cost[i];
    cout << sol.canCompleteCircuit(gas, cost) << "\n";
    return 0;
}
