// ============================================================================
// LC-1248：统计「优美子数组」
// 难度：中等
// 优先级：P1（进阶）
// 学习进度：第 1 周 / 第 1 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 nums 和一个整数 k。
// 如果某个连续子数组中恰好有 k 个奇数数字，我们就认为这个子数组是「 优美子数组 」。
// 请返回这个数组中 「优美子数组」 的数目。
//
// 题目示例：
// 示例 1：
//   Input: nums = [1,1,2,1,1], k = 3
//   Output: 2
//   Explanation: The only sub-arrays with 3 odd numbers are [1,1,2,1] and [1,2,1,1].
//
// 示例 2：
//   Input: nums = [2,4,6], k = 1
//   Output: 0
//   Explanation: There are no odd numbers in the array.
//
// 示例 3：
//   Input: nums = [2,2,2,1,2,2,1,2,2,2], k = 2
//   Output: 16
//
// 约束与要求：
//   - 1 <= nums.length <= 50000
//   - 1 <= nums[i] <= 10^5
//   - 1 <= k <= nums.length
//
// 复杂度目标：O(n) 时间，O(1) 额外空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜奇偶映射 + 前缀和 + 频次哈希表（复用 LC-560）
//
// 0. 优化是怎么来的
//   最自然的做法，是枚举每个子数组并数里面有多少个奇数；即使向右扩展时复用当前 oddCount，仍然要检查 O(n^2) 个连续区间。
//
//   真正值得先做的不是立刻发明一个新窗口公式，而是把题目里的“奇数个数”翻译成可累加数值：奇数记 1，偶数记 0。这样一个区间“恰好有 k 个奇数”就等价于这个 0/1 区间“元素和恰好为 k”。
//
//   问题到这里已经完整变成 LC-560：固定当前前缀 prefix 后，需要寻找的历史状态唯一是 prefix-k，于是把枚举所有起点改成一次历史频次查询。
//
//   优化类型：先做问题等价变换，再复用已学的“重复查找 -> 历史状态索引”。主线优先复用 LC-560，而不是为同一问题重新背一套模板。
//
// 1. 图像直觉
//   先做一次非常简单的等价转换：
//
//   原数组： [2, 2, 1, 2, 1, 2]
//   奇偶值： [0, 0, 1, 0, 1, 0]
//
//   于是问题变成：上面的 0/1 数组中，有多少个连续子数组的和为 k？
//
//   |------------- 当前 prefix：累计奇数数 -------------|
//   |--------- 历史 prefix-k ---------|
//                                         ^
//                                 中间恰好多出 k 个奇数
//
//   这和 LC-560 的图完全相同，只是 prefix 从“元素累计和”变成了“奇数累计个数”。
//
// 2. 一句话核心
//   先把奇数当 1、偶数当 0，然后把这题直接当成 LC-560：当前 prefix 去历史里找 prefix-k。
//
// 3. 公式 / 不变量
//   区间内奇数个数 = 当前累计奇数数 - 过去累计奇数数
//   prefix - oldPrefix = k
//   oldPrefix = prefix - k
//
// 4. 执行步骤
//   1. frequency[0]=1，记录数组开始前的空前缀
//   2. 扫描 value：奇数让 prefix 加 1，偶数让 prefix 加 0
//   3. 用 find(prefix-k) 查询历史频次，存在就累加到答案
//   4. 最后执行 ++frequency[prefix]，把当前累计奇数数加入历史
//   记忆：奇偶转 0/1 -> 先算现在 -> 查 prefix-k -> 再记录现在。
//
// 5. 为什么不会漏 / 不会重
//   prefix 表示从开头到当前位置累计遇到的奇数个数；两个 prefix 的差就是它们之间连续区间的奇数个数，因此历史 prefix-k 与当前位置一一组成恰好含 k 个奇数的子数组。
//
// 6. 边界与易错点
//   必须保存 prefix 的出现频次而不是只判断存在；frequency[0]=1 才能统计从下标 0 开始的答案；查询 prefix-k 用 find()，避免纯查询意外插入；偶数只是贡献 0，不是窗口边界。当前主解法 O(n) 时间、O(n) 额外空间。
//
// 7. 举一反三
//   这是 LC-560 的直接变形：先把题目属性映射成可累加的 0/1 状态，再统计指定前缀差；类似的“恰好 K 次满足条件”问题也可先尝试这种转换。
//
// 进阶优化
//   如果必须满足题头的 O(1) 额外空间目标，再学习 atMost(k)-atMost(k-1) 的滑动窗口版本；它是空间优化，不作为第一次理解本题的主线。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n k。
//   第 2 行：n 个以空格分隔的整数。
//   输出：优美子数组的数量。
// test.in 的预期输出：2
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int numberOfSubarrays(vector<int>& nums, int k) {
        // 这里不是在保存“元素和”，而是在保存“累计遇到的奇数个数”。
        // frequency[p] 表示：在当前元素之前，累计奇数数 p 一共出现过多少次。
        // 同一个 p 可出现在多个位置；每个位置都是一个不同的候选起点，因此必须保存频次。
        unordered_map<int, int> frequency;
        frequency.reserve(nums.size() * 2 + 1);

        // 数组开始前还没看任何元素，累计奇数数为 0，记作一次虚拟空前缀。
        // 这样当当前 prefix == k 时，[0..i] 也能通过 prefix-k==0 被统一统计。
        frequency[0] = 1;

        int prefix = 0;
        int answer = 0;
        for (int value : nums) {
            // 把题目先变形成 LC-560：奇数贡献 1，偶数贡献 0。
            // 因而 prefix 始终表示“从数组开头到当前位置累计出现了多少个奇数”。
            prefix += value & 1;

            // 若某个历史累计值 oldPrefix 满足 prefix-oldPrefix == k，
            // 那么它之后到当前位置这一段就恰好含 k 个奇数，即 oldPrefix=prefix-k。
            // 历史上该值出现几次，就有几个不同起点的优美子数组。
            auto it = frequency.find(prefix - k);
            if (it != frequency.end()) {
                answer += it->second;
            }

            // 查询结束后再把当前 prefix 归入历史，保持 frequency 只描述“过去”的不变量。
            // 本题约束 k>=1，即使先记当前值也不会产生 prefix==prefix-k 的自匹配；
            // 但保持“先查过去、再记现在”与 LC-560 完全一致，也让推广到 k==0 时仍然正确。
            ++frequency[prefix];
        }
        return answer;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n, k;
    if (!(cin >> n >> k)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.numberOfSubarrays(a, k) << "\n";
    return 0;
}
