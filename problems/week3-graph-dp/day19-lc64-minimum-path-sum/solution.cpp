// ============================================================================
// LC-64：最小路径和
// 难度：中等
// 优先级：P0（必做）
// 学习进度：第 3 周 / 第 19 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个包含非负整数的 m x n 网格 grid，请找出一条从左上角到右下角的路径，使得路径上的数字总和为最小。
// 说明：每次只能向下或者向右移动一步。
//
// 题目示例：
// 示例 1：
//   Input: grid = [[1,3,1],[1,5,1],[4,2,1]]
//   Output: 7
//   Explanation: Because the path 1 → 3 → 1 → 1 → 1 minimizes the sum.
//
// 示例 2：
//   Input: grid = [[1,2,3],[4,5,6]]
//   Output: 12
//
// 约束与要求：
//   - m == grid.length
//   - n == grid[i].length
//   - 1 <= m, n <= 200
//   - 0 <= grid[i][j] <= 200
//
// 复杂度目标：O(m*n) 时间，O(n) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜网格最短路径 DP：复用 LC-62 的上/左依赖，把计数改成最小代价
//
// 0. 优化是怎么来的
//   最自然的正确做法仍然可以是 DFS：从左上角向右/下枚举所有合法路径，走到右下角时计算路径和并取最小。它当然不会漏答案，但不同路径会反复进入同一个格子；从同一个格子到终点的最优剩余成本是同一个子问题，却被重复求解，路径数量又是组合爆炸的。
//
//   把问题改成“到达每个格子的最小累计成本”，每个格子只需解一次。因为最后一步只能来自上或左，所以：
//   best[r][c] = min(best[r-1][c], best[r][c-1]) + grid[r][c]。
//   这就是最短路径意义下的最优子结构：到当前格时，如果某条来自上方的前缀已经比 best[r-1][c] 更贵，那么后面再加完全相同的当前格和未来成本，它永远不可能反超，可以永久丢弃。
//
//   和 LC-62 一样，当前格只依赖上一行同列与当前行左侧，因此二维 best 表可以压成一行 dp。
//
//   优化链：枚举整条路径 -> 同一格子的剩余问题重复出现 -> 每格只保留一个不被更差前缀支配的最小成本 -> 上/左二维 DP -> 一行滚动。
//
// 1. 图像直觉
//   grid =
//   1 3 1
//   1 5 1
//   4 2 1
//
//   把每格改写成“到这里的最低累计成本”：
//
//   1 4 5
//   2 7 6
//   6 8 7
//
//   例如右中格值为 1：
//
//   上方最低成本 = 5
//   左方最低成本 = 7
//   当前格成本   = 1
//
//   所以当前最低 = min(5,7) + 1 = 6。
//
//   压成一维时仍和 LC-62 一样：
//   更新前 dp[col]   = 上方最低成本
//   更新后 dp[col-1] = 左方最低成本
//
//   只是操作从“+ 两个来源”变成：
//   min(上, 左) + 当前格。
//
// 2. 一句话核心
//   移动依赖完全复用 LC-62；到当前格只保留上/左两类来源中更便宜的前缀，再加当前格成本。
//
// 3. 公式 / 不变量
//   二维状态：
//   best[r][c] = 从左上角到 (r,c) 的最小路径和。
//
//   内部格：
//   best[r][c] = min(best[r-1][c], best[r][c-1]) + grid[r][c]
//
//   第一格：
//   best[0][0] = grid[0][0]
//   第一行只能来自左；第一列只能来自上。
//
//   当前实现的一维不变量：进入某行时 dp[col] 是上一行对应列的最优值。
//   处理 col==0：
//   dp[0] = dp[0] + grid[row][0]
//
//   处理 col>0：
//   dp[col] = min(dp[col], dp[col-1]) + grid[row][col]
//
//   其中旧 dp[col] 是上，新 dp[col-1] 是左。
//
// 4. 执行步骤
//   1. 创建长度 cols 的 dp，并把除 dp[0] 外的位置设为 INT_MAX；dp[0]=0 让第一格可以统一由虚拟起点进入
//   2. 逐行扫描 grid，并在每一行从左到右更新，保持和 LC-62 相同的依赖方向
//   3. col==0 时只能从上方下来，因此执行 dp[0]+=row[0]；不要读取不存在的左邻居
//   4. col>0 时，先比较旧 dp[col]（上）与新 dp[col-1]（左），取较小者后再加当前 row[col]
//   5. 最后 dp[cols-1] 即右下角最小路径和
//   记忆：先复用 LC-62 的箭头，再把“上+左”换成“min(上,左)+当前成本”。
//
// 5. 为什么不会漏 / 不会重
//   所有到 (r,c) 的路径最后一步仍只可能来自上或左。固定最后一步来自上时，若此前不用到上方格子的最小成本，而选一个更贵的前缀，之后两条候选都会加相同的当前格成本，所以更贵前缀永远不能变优；左方同理。因此只需保留两个来源各自的最优摘要，再取 min。按左到右更新保证一维 dp 的上/左语义正确，所以空间压缩不影响二维递推。
//
// 6. 边界与易错点
//   不要把第一行/第一列按普通双来源公式处理；当前代码用 col==0 单独处理第一列。INT_MAX 只用于初始化不可达状态，不能在尚为 INT_MAX 时盲目加值；当前 dp[0]=0 且逐行推进，实际更新路径不会对不可达 INT_MAX 做加法。遍历必须左到右。
//
// 7. 举一反三
//   LC-62 与 LC-64 是一对非常重要的模型迁移：状态图不变，只改变聚合运算。看到同样的“只能从上/左进入”，先复用依赖图，再判断目标是计数、最小成本还是最大收益。LC-1143 也会再次出现上、左、左上三个二维依赖。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：m n。
//   接下来 m 行：n 个以空格分隔的整数。
//   输出：最小路径和。
// test.in 的预期输出：7
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int minPathSum(vector<vector<int>>& grid) {
        const int cols = static_cast<int>(grid[0].size());
        vector<int> dp(cols, INT_MAX);
        dp[0] = 0;
        for (const auto& row : grid) {
            for (int col = 0; col < cols; ++col) {
                if (col == 0) dp[col] = dp[col] + row[col];
                else dp[col] = min(dp[col], dp[col - 1]) + row[col];
            }
        }
        return dp[cols - 1];
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int m, n; if (!(cin >> m >> n)) return 0;
    vector<vector<int>> g(m, vector<int>(n));
    for (int i = 0; i < m; ++i) for (int j = 0; j < n; ++j) cin >> g[i][j];
    cout << sol.minPathSum(g) << "\n";
    return 0;
}
