// ============================================================================
// LC-152：乘积最大子数组
// 难度：中等
// 优先级：P1（进阶）
// 学习进度：第 3 周 / 第 21 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给你一个整数数组 nums，请你找出数组中乘积最大的非空连续子数组 （该子数组中至少包含一个数字），并返回该子数组所对应的乘积。
// 测试用例的答案是一个 32-位整数。
// 请注意，一个只包含一个元素的数组的乘积是这个元素的值。
//
// 题目示例：
// 示例 1：
//   Input: nums = [2,3,-2,4]
//   Output: 6
//   Explanation: [2,3] has the largest product 6.
//
// 示例 2：
//   Input: nums = [-2,0,-1]
//   Output: 0
//   Explanation: The result cannot be 2, because [-2,-1] is not a subarray.
//
// 约束与要求：
//   - 1 <= nums.length <= 2 * 10^4
//   - -10 <= nums[i] <= 10
//   - nums 的任何子数组的乘积都保证是一个 32-位整数
//
// 复杂度目标：O(n) 时间，O(1) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜双极值状态 DP：负数会翻转候选优劣，所以同时保留最大与最小后缀
//
// 0. 优化是怎么来的
//   一个自然正确的直接算法是枚举每个左端点，再向右不断累乘并更新全局最大值；它检查了所有连续子数组，时间 O(n^2)。
//
//   对最大子数组和 LC-53，我们曾经利用候选支配：固定同一个终点时，只保留最大的后缀和就够了，因为未来无论再加什么值，两个候选都会加同一个量，较差者永远不能反超。
//
//   乘法却破坏了这个单状态支配关系。假设以当前位置结尾的两个候选乘积是 6 和 -10。面对未来 x=-2：
//   6 * -2 = -12，
//   -10 * -2 = 20。
//   原来最差的 -10 反而成为最好。因此“只留最大值”会丢掉未来可能翻身的候选。
//
//   但仍不需要保留所有后缀乘积。未来只会把每个候选统一乘同一个 x：x>0 时大小顺序保持，x<0 时大小顺序完全翻转，x=0 时全部归零。因此在任何时刻，真正可能成为下一步最大或最小的只需要当前极大值与极小值；中间候选无论正乘还是负乘都不会超出这两个边界。
//
//   于是状态压缩成 currentMax/currentMin。遇到负数可以先交换两者，把“乘负数后角色互换”显式编码，再分别决定是从 value 单独重开还是延续旧后缀。
//
//   优化链：O(n^2) 枚举所有连续区间 -> 尝试复用 LC-53 的 ending-here 压缩 -> 发现负数会让最大/最小互换 -> 中间候选仍被两个极值支配 -> 双极值 O(n) DP。
//
// 1. 图像直觉
//   nums = [2,3,-2,4]
//
//   处理到 3：
//   currentMax = 6
//   currentMin = 3
//
//   遇到 -2 时，未来角色翻转：
//   最大的 6 乘 -2 -> -12
//   较小的 3 乘 -2 -> -6
//   所以负号让“大”朝“小”方向走。
//
//   更关键的例子：
//   候选 6 与 -10，下一项 -2：
//   6   -> -12
//   -10 ->  20
//
//   因此负乘积不是垃圾状态；它可能只差一个负数就翻成最大正乘积。
//   代码中的 swap(currentMax,currentMin) 就是在 value<0 时先交换“谁有资格产生最大/最小”。
//
// 2. 一句话核心
//   固定当前终点时同时保存最大和最小乘积；正数保持二者角色，负数交换角色，0 则自然让后续状态重新开始。
//
// 3. 公式 / 不变量
//   设上一位置：
//   oldMax = 以 i-1 结尾的最大乘积
//   oldMin = 以 i-1 结尾的最小乘积
//   x = nums[i]
//
//   所有以 i 结尾的候选只有三类：
//   x
//   oldMax * x
//   oldMin * x
//
//   所以数学上：
//   newMax = max(x, oldMax*x, oldMin*x)
//   newMin = min(x, oldMax*x, oldMin*x)
//
//   当前实现把 x<0 的情况先 swap(oldMax,oldMin)，之后可写成：
//   currentMax = max(x, currentMax*x)
//   currentMin = min(x, currentMin*x)
//
//   best = max(best, currentMax)
//
//   不变量：处理完 i 后，currentMax/currentMin 精确覆盖所有以 i 结尾非空连续子数组乘积的最大值/最小值；best 是所有已处理终点中的全局最大值。
//
// 4. 执行步骤
//   1. 用 nums[0] 同时初始化 currentMax、currentMin 和 best，确保单元素、全负数组都不会被错误的 0 初值覆盖
//   2. 从第二个元素开始读取 value；若 value<0，先交换 currentMax/currentMin，因为乘负数会把旧极大候选变成极小来源、旧极小候选变成极大来源
//   3. 更新 currentMax=max(value,currentMax*value)，在“从当前元素重新开始”与“延续旧后缀”之间选择最大
//   4. 更新 currentMin=min(value,currentMin*value)，保留未来遇到负数时可能翻成最大值的最小后缀
//   5. 用 currentMax 更新历史 best；遍历结束返回 best
//   记忆：加法只留最好；乘法遇负号会翻面，所以最好和最坏都要留。
//
// 5. 为什么不会漏 / 不会重
//   所有以 i 结尾的连续子数组，要么只包含 nums[i]，要么由某个以 i-1 结尾的连续子数组再乘 nums[i] 得到。统一乘正数时，旧乘积集合的最大/最小仍分别产生新集合的最大/最小；统一乘负数时次序完全反转，所以旧最小产生新最大、旧最大产生新最小；乘 0 时所有延续候选都是 0。故除了旧最大和旧最小，其余中间候选永远不可能产生边界极值，可以永久丢弃。逐点维护后，best 再覆盖所有可能终点，因此没有漏掉任何连续子数组。
//
// 6. 边界与易错点
//   不能照搬 LC-53 只保存一个 currentMax；负数会让旧最小翻身。更新顺序若不用 swap，就必须先保存 oldMax/oldMin，否则先改 currentMax 会污染 currentMin 的计算。0 无需特判：max/min 与 value=0 会自然重置状态。best 必须初始化为 nums[0]，不能初始化为 0。
//
// 7. 举一反三
//   这是 LC-53 候选支配思想的升级版：面对相同未来，若运算保持顺序就只留一个极值；若运算可能反转顺序，就保留足够描述边界的多个极值状态。带符号乘积、最大绝对值路径以及某些区间变换 DP 都有类似的“最大+最小”成对状态。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：最大乘积。
// test.in 的预期输出：6
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int maxProduct(vector<int>& nums) {
        // 三个状态都从 nums[0] 开始，保证单元素或全负数组不会被虚假的 0 初值覆盖。
        // currentMax/currentMin 分别是“必须以当前位置结尾”的最大/最小连续子数组乘积；
        // best 才是所有已处理终点中的历史全局最大值。
        int currentMax = nums[0];
        int currentMin = nums[0];
        int best = nums[0];

        for (int i = 1; i < static_cast<int>(nums.size()); ++i) {
            const int value = nums[i];

            // 乘负数会把大小顺序完全翻转：旧最小值可能成为新最大值的最佳来源，旧最大值反之。
            // 先交换两者后，后续就仍可用“最大延续最大、最小延续最小”的统一写法。
            if (value < 0) swap(currentMax, currentMin);

            // 所有以 i 结尾的候选只有两类：从 value 单独重开，或把 value 接到旧后缀后。
            // swap 已经处理了负数时的来源互换，因此这里只需分别维护新的两个极值。
            currentMax = max(value, currentMax * value);
            currentMin = min(value, currentMin * value);

            // currentMax 只覆盖“当前终点”，全局答案必须另外保留历史 best。
            best = max(best, currentMax);
        }
        return best;
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.maxProduct(a) << "\n";
    return 0;
}
