// ============================================================================
// LC-312：戳气球
// 难度：困难
// 优先级：P1（进阶）
// 学习进度：第 3 周 / 第 20 天
// ----------------------------------------------------------------------------
// 题目描述：
// 有 n 个气球，编号为 0 到 n - 1，每个气球上都标有一个数字，这些数字存在数组 nums 中。
// 现在要求你戳破所有的气球。
// 戳破第 i 个气球，你可以获得 nums[i - 1] * nums[i] * nums[i + 1] 枚硬币。
// 这里的 i - 1 和 i + 1 代表和 i 相邻的两个气球的序号。
// 如果 i - 1 或 i + 1 超出了数组的边界，那么就当它是一个数字为 1 的气球。
// 求所能获得硬币的最大数量。
//
// 题目示例：
// 示例 1：
//   Input: nums = [3,1,5,8]
//   Output: 167
//   Explanation:
//   nums = [3,1,5,8] --> [3,5,8] --> [3,8] --> [8] --> []
//   coins = 3*1*5 + 3*5*8 + 1*3*8 + 1*8*1 = 167
//
// 示例 2：
//   Input: nums = [1,5]
//   Output: 10
//
// 约束与要求：
//   - n == nums.length
//   - 1 <= n <= 300
//   - 0 <= nums[i] <= 100
//
// 复杂度目标：O(n^3) 时间（区间 DP）。
//
// ----------------------------------------------------------------------------
// 解法精讲｜区间 DP：把难确定的“先戳谁”反过来改成邻居固定的“最后戳谁”
//
// 0. 优化是怎么来的
//   最直接且正确的方法是枚举戳气球的顺序：当前剩哪些气球，就尝试戳其中任意一个，按它此刻的左右邻居计算收益，再递归处理剩余气球。所有 n! 种顺序都被覆盖，因此当然能得到最大值。
//
//   仅仅说‘它是指数/阶乘复杂度’还不够。真正难以复用状态的原因是：如果按第一枚被戳的 k 来划分，k 消失以后，它左右两侧的气球会重新成为邻居。之后左侧的操作收益可能依赖右侧还剩谁，右侧也可能依赖左侧，所以‘先戳 k’并不能把问题切成两个独立子问题。
//
//   反过来问：在某个边界区间内，哪一个气球最后被戳？假设最后是 k。当它被戳时，(left,right) 内除 k 外的气球已经全部消失，因此 k 当时的两个邻居确定就是边界 left 和 right，最后一步收益固定为 values[left]*values[k]*values[right]。
//
//   而在 k 被留下直到最后之前，左侧 (left,k) 内部如何全部戳完，不会再依赖右侧内部；右侧 (k,right) 同理。于是原本动态变化的邻居关系被‘最后操作’固定住，产生真正独立的两个子问题。
//
//   给原数组两端补虚拟气球 1 后，定义 dp[left][right] 为开区间 (left,right) 全部戳完的最大收益。枚举最后的 k：
//   dp[left][right] = max(dp[left][k] + values[left]*values[k]*values[right] + dp[k][right])。
//   因为大区间依赖两个更短区间，所以按区间宽度从小到大计算。
//
//   优化链：枚举 n! 个戳破顺序 -> 发现按“第一步”无法独立切分 -> 改问“区间内最后一步是谁” -> 最后一步邻居被边界固定 -> 左右子区间独立 -> O(n^3) 区间 DP。
//
// 1. 图像直觉
//   给 nums=[3,1,5,8] 两端补 1：
//
//   index:   0  1  2  3  4  5
//   values: [1, 3, 1, 5, 8, 1]
//
//   考虑开区间 (left,right)=(0,4)，也就是内部 [3,1,5]。
//   不要问“先戳谁”，而问“谁最后留下”。
//
//   若最后留下 k=3（值 5）：
//
//   left=0       k=3       right=4
//    value 1      5          8
//       |---------|----------|
//        (0,3)       (3,4)
//
//   等轮到 5 最后被戳时，区间内其他气球已经没了，它的邻居一定是边界值 1 和 8，所以最后收益固定为 1*5*8。
//   此前左边怎么戳，只由 (0,3) 决定；右边怎么戳，只由 (3,4) 决定。
//
//   因此候选值就是：
//   dp[0][3] + 1*5*8 + dp[3][4]。
//
//   把 k 在 (left,right) 内全部枚举，就覆盖了所有可能的“最后一步”。
//
// 2. 一句话核心
//   动态邻居让“先戳谁”无法切分；改为枚举区间内最后戳的气球后，它的邻居固定为两端边界，左右区间因此真正独立。
//
// 3. 公式 / 不变量
//   补边界：
//   values = [1] + nums + [1]
//
//   状态采用开区间：
//   dp[left][right] = 把 (left,right) 内所有气球戳完能得到的最大硬币数。
//
//   空区间：
//   right = left + 1 时，dp[left][right] = 0。
//
//   若 k 是 (left,right) 内最后被戳的气球：
//   candidate = dp[left][k]
//             + values[left] * values[k] * values[right]
//             + dp[k][right]
//
//   因此：
//   dp[left][right]
//   = max over left<k<right(candidate)
//
//   依赖不变量：计算宽度 width=right-left 的区间时，所有 dp[left][k] 与 dp[k][right] 的宽度都严格小于 width，因此已经计算完成。
//
// 4. 执行步骤
//   1. 构造 values，在原 nums 两端各补一个值为 1 的虚拟边界；它们从不被戳，只用来统一边界乘法
//   2. 创建二维 dp，默认 0；开区间没有内部气球时收益本来就是 0，所以无需额外初始化
//   3. 让 width 从 2 递增；width=2 是第一个恰好含一个内部气球的非空开区间
//   4. 固定 left 并令 right=left+width，枚举每个 last∈(left,right) 作为该区间最后被戳的气球
//   5. 用已经完成的 dp[left][last]、dp[last][right] 加上最后一步的固定收益 values[left]*values[last]*values[right] 更新最大值
//   6. 最终 dp[0][n-1] 表示两个虚拟边界之间，也就是整个原数组全部戳完的最大收益
//   记忆：第一步邻居会变，切不开；最后一步邻居固定。补 1、用开区间、枚举 last、短区间先算。
//
// 5. 为什么不会漏 / 不会重
//   任意一种把 (left,right) 内气球全部戳完的顺序都有唯一的最后一个气球 k，因此所有合法顺序会被按 last=k 唯一分类，不会漏也不会重复。固定 k 后，在最后一步发生前，(left,k) 和 (k,right) 内的气球都必须已经全部消失；由于 k 一直保留，它把左右两侧隔开，所以两边内部操作可以分别达到各自最优 dp[left][k] 与 dp[k][right]，最后再获得固定边界乘积。反过来，任取左右两个合法最优顺序并在最后戳 k，都构成一个合法的 (left,right) 顺序，因此转移枚举的每个候选都可实现。
//
// 6. 边界与易错点
//   状态是开区间，不要把 left/right 自己当成需要被戳的内部气球；width 必须由小到大，否则依赖的子区间还没求好。最容易误入歧途的是按‘第一枚’强行切左右，因为第一枚消失后两侧会重新相邻，并不独立。两端补 1 只是题面越界邻居规则的统一编码，不是额外可选择的真实气球。
//
// 7. 举一反三
//   这是 Day 19 二维 DP 的另一种坐标含义：LC-62/64 的两个维度是网格位置，LC-1143 是两个前缀长度，而这里是区间左右边界。更重要的迁移是‘改变决策时间方向来制造独立子问题’：矩阵链乘、石子合并、多边形三角剖分等区间 DP 都常枚举最后合并 / 最后操作 / 分割点，而不是执着于真实执行顺序的第一步。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：n。
//   第 2 行：n 个以空格分隔的整数。
//   输出：可获得的最大硬币数。
// test.in 的预期输出：167
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    int maxCoins(vector<int>& nums) {
        // 两端补的 1 是永不被戳的虚拟边界，只用于把原数组两端的越界邻居规则统一进同一个乘法公式。
        vector<int> values;
        values.reserve(nums.size() + 2);
        values.push_back(1);
        values.insert(values.end(), nums.begin(), nums.end());
        values.push_back(1);
        const int n = static_cast<int>(values.size());

        // dp[left][right] 表示：把开区间 (left,right) 内所有真实气球都戳完能得到的最大收益。
        // 相邻边界 right=left+1 时区间为空，默认 0 正好就是基础状态。
        vector<vector<int>> dp(n, vector<int>(n, 0));

        // width=right-left。大区间依赖更短的 (left,last) 与 (last,right)，
        // 所以必须按 width 从小到大；width=2 是第一个恰好含一个内部气球的非空区间。
        for (int width = 2; width < n; ++width) {
            for (int left = 0; left + width < n; ++left) {
                int right = left + width;

                // 枚举 last 作为 (left,right) 内“最后被戳”的气球。
                // 到它最后被戳时，其余内部气球都已消失，真实邻居被固定成边界 left/right，
                // 因而最后一步收益可以稳定写成 values[left]*values[last]*values[right]。
                for (int last = left + 1; last < right; ++last) {
                    // last 一直保留到最后，会把此前操作分成互不干扰的左右两个开区间；
                    // 两个子区间宽度都更小，此时已经求好，可以直接组合并取最大值。
                    dp[left][right] = max(dp[left][right],
                        dp[left][last] + values[left] * values[last] * values[right]
                        + dp[last][right]);
                }
            }
        }

        // 两个虚拟边界 0 与 n-1 之间正好覆盖全部原始气球。
        return dp[0][n - 1];
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    int n;
    if (!(cin >> n)) return 0;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    cout << sol.maxCoins(a) << "\n";
    return 0;
}
