// ============================================================================
// LC-20：有效的括号
// 难度：简单
// 优先级：P0（必做）
// 学习进度：第 2 周 / 第 12 天
// ----------------------------------------------------------------------------
// 题目描述：
// 给定一个只包括 '('，')'，'{'，'}'，'['，']' 的字符串 s，判断字符串是否有效。
// 有效字符串需满足：左括号必须用相同类型的右括号闭合。
// 左括号必须以正确的顺序闭合。
// 每个右括号都有一个对应的相同类型的左括号。
//
// 题目示例：
// 示例 1：
//   Input: s = "()"
//
//   Output: true
//
// 示例 2：
//   Input: s = "()[]{}"
//
//   Output: true
//
// 示例 3：
//   Input: s = "(]"
//
//   Output: false
//
// 示例 4：
//   Input: s = "([])"
//
//   Output: true
//
// 示例 5：
//   Input: s = "([)]"
//
//   Output: false
//
// 约束与要求：
//   - 1 <= s.length <= 10^4
//   - s 仅由括号 '()[]{}' 组成
//
// 复杂度目标：O(n) 时间，O(n) 空间。
//
// ----------------------------------------------------------------------------
// 解法精讲｜从题目直觉到可复用算法
//
// 1. 题目直觉 / 图形模型
//   把括号理解成一层层尚未关闭的盒子：
//
//   读 '(' ：打开圆括号盒子
//   读 '[' ：在里面又打开方括号盒子
//   读 ']' ：必须先关掉最近打开的 '['
//   读 ')' ：随后才能关掉 '('
//
//   ([)] 为什么错？因为读到 ')' 时，最近尚未关闭的是 '['，不能绕过它去关更外层。
//
// 2. 最自然的一般性解法
//   从左到右扫描。遇到左括号就把它记到“尚未关闭的括号序列”末尾；遇到右括号时，只检查最近那个尚未关闭的左括号，类型一致就删除它，否则立即失败。扫描结束还要求没有残留未关闭括号。
//
// 3. 一般解法的问题与限制
//   如果每遇到右括号都去所有历史左括号里搜索同类型，会破坏嵌套顺序；题目要求的不是‘数量能配上’，而是‘最近开启的结构必须最先关闭’。因此历史中真正需要访问的永远只有最后一个未完成状态。
//
// 4. 从具体问题抽象规律
//   当结构具有‘后开启先结束’的嵌套关系时，只需要保存尚未完成的上下文，并始终从最近一个开始结算。这是 LIFO，而不是普通的集合匹配。
//
// 5. 专项算法｜栈保存未闭合结构：最近开启，最先关闭
//   前面的推理已经得到可复用机制；现在才给它一个检索名称：栈保存未完成的嵌套上下文。通用机制见 docs/algorithms/stack-queue.md。回到本题时，只需要把其中的状态、边界和更新事件映射到当前题意，不要反过来用模板猜题。
//
// 6. 核心算法
//   右括号不是去历史里随便找同类型左括号，而是必须关闭最近一个尚未闭合的左括号。
//
// 7. 公式 / 不变量
//   扫描完任意前缀后：
//   stack = 这个前缀中尚未闭合的左括号，按开启顺序保存
//   stack.top() = 下一次最先允许被关闭的左括号
//
//   遇到右括号 close：
//   stack 非空 && stack.top() == match(close)
//   才合法，然后 pop。
//
//   扫描结束还要求 stack.empty()。
//
// 8. 执行步骤
//   1. 遇到左括号就压栈，表示开启了一个尚未完成的嵌套结构
//   2. 遇到右括号先检查栈是否为空，再检查栈顶是否是与它匹配的左括号；不匹配立即失败
//   3. 匹配成功就弹出栈顶；全部扫描结束后，只有栈为空才说明所有开启结构都已闭合
//   记忆：左括号负责“欠一笔闭合账”，右括号只能还最近的一笔。
//
// 9. 为什么不会漏 / 不会重
//   不会漏：每个左括号进入栈后一直保留到自己真正被关闭，因此任何未闭合结构都不会消失。
//   不会错配：合法嵌套要求后开启的结构先结束；若当前右括号连栈顶都不能匹配，就不可能绕过这个更近的未闭合结构去匹配更早的括号。
//   不会残留：最终栈非空说明仍有左括号没有右括号与之配对，所以必须判非法。
//
// 10. 边界与易错点
//   不能只统计三种括号数量是否相等，`([)]` 数量完全相等但嵌套顺序错误；遇到右括号必须先判空再访问 top；扫描完后别忘记检查残余左括号。
//
// 11. 举一反三
//   这是 Day 10 迭代 DFS 中“栈保存暂停现场”的同一思想：栈保存尚未完成的上下文。后续表达式求值、路径回退、HTML/XML 标签匹配都在复用这个模型。
// ----------------------------------------------------------------------------
//
// 本地输入输出格式（用于 test.in）：
//   第 1 行：字符串 s。
//   输出：有效时输出 1，否则输出 0。
// test.in 的预期输出：1
// ============================================================================
#include <bits/stdc++.h>
using namespace std;


// ---------- 题解实现 ----------
class Solution {
public:
    bool isValid(string s) {
        // openings 保存“已经开启、但尚未闭合”的左括号；
        // 栈顶就是最近开启的结构，也是下一只右括号唯一允许关闭的对象。
        stack<char> openings;

        for (char c : s) {
            if (c == '(' || c == '[' || c == '{') {
                // 左括号开启新的嵌套上下文，先欠下一笔等待未来关闭的账。
                openings.push(c);
                continue;
            }

            // 当前字符既然是右括号，就必须关闭一个已有上下文；
            // 若栈已空，说明没有任何左括号可与它配对，立即非法。
            if (openings.empty()) return false;

            // 把当前右括号映射成“它唯一允许匹配的左括号类型”。
            const char expected = (c == ')') ? '(' : (c == ']') ? '[' : '{';

            // 合法嵌套要求最近开启的结构最先关闭；
            // 即使栈更深处存在同类型左括号，也不能越过错误的栈顶去匹配它。
            if (openings.top() != expected) return false;
            openings.pop();
        }

        // 扫描结束后仍有左括号留栈，说明这些上下文从未被关闭，同样非法。
        return openings.empty();
    }
};

// ---------- 本地测试适配器 ----------
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    Solution sol;
    string s;
    if (!(cin >> s)) return 0;
    cout << (sol.isValid(s) ? 1 : 0) << "\n";
    return 0;
}
